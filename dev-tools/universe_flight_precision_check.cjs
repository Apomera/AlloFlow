const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const report=path.resolve('reports/universe-flight-2026-09-29');
(async()=>{
  const browser=await chromium.launch({args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('file:///'+path.join(report,'preview.html').replaceAll('\\','/'));
  await page.waitForFunction(()=>document.querySelector('.uf-transport button')?.disabled===false);
  await page.locator('.uf-precision summary').click();
  const panel=page.locator('.uf-precision'),canvas=page.locator('.uf-stage canvas');
  const readout=()=>page.locator('.uf-readouts').innerText();
  const start=await readout();
  await panel.getByRole('button',{name:'Fine',exact:true}).click();
  assert.match(await page.locator('.uf-step-distance').innerText(),/0.01 ly/);
  await page.getByRole('button',{name:'Step forward',exact:true}).click();
  assert.match(await readout(),/0.01 ly/);
  assert.equal(await page.locator('.uf-transport button').first().innerText(),'Start travel');
  await page.getByRole('button',{name:'Undo camera step',exact:true}).click();
  assert.equal(await readout(),start);
  await panel.getByRole('button',{name:'Survey',exact:true}).click();
  for(const name of ['Slide left','Slide right','Rise','Lower','Step forward','Step back'])await page.getByRole('button',{name,exact:true}).click();
  assert.match(await readout(),/0.6 ly/);
  for(let i=0;i<6;i++)await page.getByRole('button',{name:'Undo camera step',exact:true}).click();
  assert.equal(await readout(),start);
  assert.equal(await page.getByRole('button',{name:'Undo camera step',exact:true}).isDisabled(),true);
  await canvas.focus();await page.keyboard.down('w');await page.keyboard.down('w');await page.keyboard.up('w');
  assert.match(await readout(),/0.1 ly/,'Repeated keydown makes a single step');
  await canvas.press('z');assert.equal(await readout(),start);
  await page.locator('summary').filter({hasText:'Saved views and field notes'}).click();
  await page.locator('#uf-view-name').fill('wasdrfz');
  await page.locator('#uf-view-name').press('w');
  assert.equal(await readout(),start,'Typing in a field never moves the camera');
  await page.locator('#uf-region').selectOption('galaxy');
  assert.match(await page.locator('.uf-step-distance').innerText(),/1,000 ly/);
  await panel.getByRole('button',{name:'Large',exact:true}).click();
  assert.match(await page.locator('.uf-step-distance').innerText(),/10,000 ly/);
  await page.getByRole('button',{name:/Spiral portrait/}).click();
  await page.getByRole('button',{name:'Orbit destination',exact:true}).click();
  await canvas.press('d');
  assert.equal(await page.locator('.uf-transport button').first().innerText(),'Start travel');
  assert.equal(await page.getByRole('button',{name:'End orbit',exact:true}).count(),0);
  await panel.screenshot({path:path.join(report,'precision-camera-desktop.png')});
  await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).click();
  await canvas.focus();const beforeFull=await readout();await canvas.press('r');
  assert.notEqual(await readout(),beforeFull,'Precision shortcuts also work in fullscreen');
  await canvas.press('z');assert.equal(await readout(),beforeFull);
  await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).click();
  await page.getByRole('button',{name:'Einstein’s light chase',exact:true}).click();
  assert.equal(await page.locator('.uf-precision').count(),0);
  await canvas.focus();const physical=await readout();await canvas.press('w');assert.equal(await readout(),physical);
  await page.getByRole('button',{name:'Free exploration',exact:true}).click();
  await page.locator('.uf-precision summary').click();
  await page.setViewportSize({width:320,height:800});
  await panel.screenshot({path:path.join(report,'precision-camera-phone.png')});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
  const accessibility=await page.evaluate(async()=>{const result=await axe.run(document.querySelector('.uf-precision'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa']}});return result.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}));});
  assert.deepEqual(accessibility,[]);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(report,'precision-check.json'),JSON.stringify({errors,accessibility,checks:['six axes','fine steps','undo','key repeat','input isolation','scene scales','orbit handoff','fullscreen','relativity restriction','320px layout']},null,2));
  await browser.close();console.log('Precision camera browser checks passed.');
})().catch(e=>{console.error(e);process.exit(1);});
