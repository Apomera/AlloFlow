#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');
const { execFileSync } = require('node:child_process');
const ROOT = __dirname;
const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8');
execFileSync(process.execPath, [path.join(ROOT, 'dev-tools/sync_samira_app_case.cjs'), '--check'], { stdio: 'inherit' });
const data = JSON.parse(read('maine_sld_case_data.json'));
if (data.scoreRows.length !== 52 || data.cases.length < 5 || data.metadata.caseCount !== data.cases.length || new Set(data.cases.map(c => c.id)).size !== data.cases.length || !['alex', 'alex-general-ed-adequate', 'jordan', 'marisol', 'taylor'].every(id => data.cases.some(c => c.id === id)) || data.formSteps.length !== 9 || data.sources.length < 3) throw new Error('Incomplete reviewed case data.');
for (const c of data.cases) {
  if (!c.selection || !c.selection.gradeBand || !c.selection.academicFocus?.length || !c.selection.contexts?.length || !c.evidenceSupplement?.length || c.evidenceSupplement.some(item => !item.id || !item.title || !item.text) || new Set(c.evidenceSupplement.map(item => item.id)).size !== c.evidenceSupplement.length) throw new Error('Incomplete case selection or evidence supplement: ' + c.id);
}
const compiled = esbuild.transformSync(read('maine_sld_practice_source.jsx'), { loader: 'jsx', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment', target: 'es2020', charset: 'utf8', legalComments: 'none' }).code;
const stateWorkspaceCompiled = esbuild.transformSync(read('maine_sld_state_workspace_source.jsx'), { loader: 'jsx', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment', target: 'es2020', charset: 'utf8', legalComments: 'none' }).code;
const output = `/* AlloFlow Maine SLD Case Lab. Generated by _build_maine_sld_practice_module.js. */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.MaineSldPractice) return;
  var React = window.React;
  if (!React) throw new Error('Maine SLD Case Lab requires React.');
  ${read('maine_sld_practice_core.js')}
  ${read('maine_sld_state_reference_core.js')}
  ${read('maine_sld_state_documents.js')}
  ${stateWorkspaceCompiled}
  const MAINE_SLD_CASE_DATA = ${JSON.stringify(data)};
  ${compiled}
  window.AlloModules = window.AlloModules || {};
  window.AlloModules.MaineSldPractice = { MaineSldPracticePanel: MaineSldPracticePanel, _testing: { data: MAINE_SLD_CASE_DATA, Core: window.AlloSldPracticeCore, StateReferenceCore: window.AlloSldStateReferenceCore } };
})();
`;
const file = 'maine_sld_practice_module.js';
fs.writeFileSync(path.join(ROOT, file), output);
for (const dir of ['desktop/web-app/public', 'desktop/app-build', 'desktop/web-app/build']) {
  const resolved = path.join(ROOT, dir);
  if (fs.existsSync(resolved)) fs.writeFileSync(path.join(resolved, file), output);
}
console.log(`Built ${file}: ${data.scoreRows.length} results, ${data.cases.length} cases, ${Buffer.byteLength(output)} bytes.`);
