#!/usr/bin/env node
/**
 * Build meeting_docs_module.js from meeting_docs_source.jsx
 * (Meeting Documentation — Leadership Hub tool, Aug 2026.)
 * Mirrors _build_udl_walkthrough_module.js.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'meeting_docs_source.jsx');
const OUTPUT = path.join(ROOT, 'meeting_docs_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'meeting_docs_module.js');
const TMP = path.join(ROOT, '_tmp_meeting_docs_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__meetingDocsExports = { MeetingDocsPanel, meetdocsMask, meetdocsUnmask, meetdocsMaskPairs, meetdocsVerifyQuote, meetdocsParseAiJson, meetdocsBuildFromAi, meetdocsActionRollup, meetdocsMeetingHtml, meetdocsAiPrompt, MEETDOCS_BUILTIN_TEMPLATES };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling meeting_docs_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch(_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__meetingDocsExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow Meeting Documentation Module
 *
 * Auto-generated by _build_meeting_docs_module.js — DO NOT EDIT MANUALLY.
 * Source: meeting_docs_source.jsx
 *
 * Notes/transcript -> district meeting format. Local name masking before
 * any AI call; source-anchored extraction with unverified-item flags;
 * cross-meeting action tracker; accessible HTML export. Manual no-AI mode
 * uses the same templates.
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.MeetingDocs) {
    console.log('[CDN] MeetingDocs already loaded, skipping');
    return;
  }
  (function() {
    if (document.getElementById('allo-live-meetdocs')) return;
    var liveRegion = document.createElement('div');
    liveRegion.id = 'allo-live-meetdocs';
    liveRegion.setAttribute('aria-live', 'polite');
    liveRegion.setAttribute('aria-atomic', 'true');
    liveRegion.setAttribute('role', 'status');
    liveRegion.className = 'sr-only';
    liveRegion.style.cssText = 'position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);border:0';
    document.body.appendChild(liveRegion);
  })();
  var React = window.React;
  if (!React) { console.error('[MeetingDocs] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.MeetingDocs = {
    MeetingDocsPanel: MeetingDocsPanel,
    // Pure seams exposed for unit tests. Not part of the public contract.
    _testing: {
      meetdocsMask: meetdocsMask,
      meetdocsUnmask: meetdocsUnmask,
      meetdocsMaskPairs: meetdocsMaskPairs,
      meetdocsVerifyQuote: meetdocsVerifyQuote,
      meetdocsParseAiJson: meetdocsParseAiJson,
      meetdocsBuildFromAi: meetdocsBuildFromAi,
      meetdocsActionRollup: meetdocsActionRollup,
      meetdocsMeetingHtml: meetdocsMeetingHtml,
      meetdocsAiPrompt: meetdocsAiPrompt,
      MEETDOCS_BUILTIN_TEMPLATES: MEETDOCS_BUILTIN_TEMPLATES
    }
  };
  console.log('[CDN] MeetingDocs loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[MeetingDocs] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
