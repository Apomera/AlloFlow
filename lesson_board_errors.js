const PREFIXES = [['A playable board could not be validated. ', 'err_playable_board_validated'], ['The revised location could not be validated. The board is unchanged. ', 'err_revised_location_validated_board_unchang']];
function lineText(t, line) {
  if (ERROR_KEYS.has(line)) return tr(t, ERROR_KEYS.get(line), line);
  for (const [prefix, key] of PREFIXES) if (line.startsWith(prefix)) return tr(t, key, prefix.trim()) + ' ' + lineText(t, line.slice(prefix.length));
  const tail = /^(.*): ([A-Za-z0-9_-]{1,40})$/.exec(line);
  if (tail && ERROR_KEYS.has(tail[1])) return tr(t, ERROR_KEYS.get(tail[1]), tail[1]) + ': ' + tail[2];
  return line;
}
export function errorText(t, error) {
  const message = typeof error === 'string' ? error : String(error?.message || '');
  return message.split('\n').map(line => lineText(t, line)).join('\n');
}
