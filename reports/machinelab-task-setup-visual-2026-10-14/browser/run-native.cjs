const args=['dev-tools/ml_task_setup_visual_qa.cjs',out];
const before=sources.map(file=>({file,sha256:sha(file)})),startedAt=new Date().toISOString();
if(before.some(row=>row.sha256!==frozen))throw Error('Source or mirror differs from the frozen candidate.');
const runnerBefore=runners.map(file=>({file,sha256:sha(file)}));
fs.mkdirSync(out);
const result=cp.spawnSync(process.execPath,args,{cwd:root,encoding:'utf8',timeout:240000,maxBuffer:8*1024*1024});
fs.writeFileSync(path.join(out,'stdout.log'),(result.stdout||'').replace(/\r\n/g,'\n').trimEnd()+'\n');
