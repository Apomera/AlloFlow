const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const dir = __dirname;
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1365, height: 900 } });
  const errors = [], failedRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('requestfailed', r => failedRequests.push({ url: r.url().split('?')[0], error: r.failure()?.errorText }));
  const start = Date.now();
  await page.goto('https://alloflow-cdn.pages.dev/app/', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.locator('[data-alloflow-launch-pad]').waitFor({ state: 'visible', timeout: 60000 });
  await page.screenshot({ path: path.join(dir, 'public-first-run.png'), fullPage: false });
  const first = { elapsedMs: Date.now()-start, title: await page.title(), text: await page.locator('body').innerText(), buttons: await page.getByRole('button').allTextContents(), scripts: await page.locator('script[src]').evaluateAll(es=>es.map(e=>e.src)), errors, failedRequests };
  fs.writeFileSync(path.join(dir, 'public-first-run.json'), JSON.stringify(first, null, 2));
  console.log(JSON.stringify(first, null, 2));
  await page.locator('[data-pathway="guided"]').click({ timeout: 15000 });
  await page.locator('[data-alloflow-launch-pad]').waitFor({ state: 'hidden', timeout: 30000 });
  await page.screenshot({ path: path.join(dir, 'public-guided.png'), fullPage: false });
  const guided = { text: await page.locator('body').innerText(), buttons: await page.getByRole('button').allTextContents(), errors, failedRequests };
  fs.writeFileSync(path.join(dir, 'public-guided.json'), JSON.stringify(guided, null, 2));
  console.log('GUIDED', JSON.stringify(guided, null, 2));
  await page.getByRole('button', { name: 'Teacher', exact: true }).click();
  await page.screenshot({ path: path.join(dir, 'public-teacher.png'), fullPage: false });
  console.log('TEACHER', (await page.locator('body').innerText()).slice(0,11000));
  fs.writeFileSync(path.join(dir, 'public-teacher.txt'), await page.locator('body').innerText());
  await page.addScriptTag({path: require.resolve('axe-core/axe.min.js')});
  const a11y = await page.evaluate(async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}});return {violations:r.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({html:n.html,target:n.target,summary:n.failureSummary}))})),passes:r.passes.length,incomplete:r.incomplete.length};});
  fs.writeFileSync(path.join(dir, 'public-teacher-axe.json'), JSON.stringify(a11y,null,2));
  console.log('AXE', JSON.stringify(a11y,null,2));
  await browser.close();
})().catch(e=>{ console.error(e); process.exitCode=1; });
