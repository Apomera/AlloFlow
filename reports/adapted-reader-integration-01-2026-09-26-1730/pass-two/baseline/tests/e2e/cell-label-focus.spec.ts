import {test, expect} from '@playwright/test';
import {GlHarness} from './helpers/stem_gl_harness';
const harness = new GlHarness({toolFile:'stem_lab/stem_tool_cell.js', toolId:'cell', width:1200, height:1000, appStyles:true});
test.beforeAll(() => harness.start());
test.afterAll(() => harness.stop());
test.afterEach(async ({page}) => harness.destroy(page));
for (const width of [1200, 320]) test('label focus and specimen changes at ' + width, async ({page}) => {
 // Keep coordinate-based pointer checks independent of smooth page scrolling.
 await page.emulateMedia({reducedMotion:'reduce'});
 const errors: string[] = [];
 page.on('pageerror', e => errors.push(e.message));
 await page.setViewportSize({width, height:960});
 await harness.mount(page, {cell:{mode:'observe', selectedOrganism:'plantcell', paused:true, zoom:3}}, undefined, {expectCanvas:false});
 await page.addStyleTag({content:'body{background:#f8fafc}#wrap{width:100%;max-width:1200px;display:block}'});
 const stage = page.locator('[data-cell-stage]');
 const canvas = page.locator('[data-cell-sim-canvas]');
 const labels = () => canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels());
 const tooltip = () => canvas.evaluate((c:any) => c._cellSimGetOrganelleTooltip());
 await stage.scrollIntoViewIfNeeded();
 await stage.locator('[data-cell-observation-center]').click();
 await expect.poll(async () => (await labels()).length).toBeGreaterThan(2);
 const original = await labels();
 const target = original[0];
 const rect = (await canvas.boundingBox())!;
 await page.mouse.move(rect.x + target.x + target.width/2, rect.y + target.y + target.height/2);
 await expect.poll(async () => (await labels()).filter((b:any) => b.hovered).map((b:any) => b.name)).toEqual([target.name]);
 await expect(canvas).toHaveCSS('cursor','pointer');
 await stage.screenshot({scale:'css',path:'reports/cell-label-focus/hover-' + width + '.png'});
 expect((await labels()).map((b:any) => [b.name,b.x,b.y,b.width,b.height])).toEqual(original.map((b:any) => [b.name,b.x,b.y,b.width,b.height]));
 await page.mouse.click(rect.x + target.x + target.width/2, rect.y + target.y + target.height/2);
 await expect.poll(async () => (await labels()).filter((b:any) => b.selected).map((b:any) => b.name)).toEqual([target.name]);
 await page.mouse.move(0,0);
 await expect.poll(async () => (await labels()).some((b:any) => b.hovered)).toBe(false);
 expect((await labels()).filter((b:any) => b.selected).map((b:any) => b.name)).toEqual([target.name]);
 await stage.screenshot({scale:'css',path:'reports/cell-label-focus/selected-' + width + '.png'});
 await canvas.press('Escape');
 await expect.poll(tooltip).toBeNull();
 expect((await labels()).some((b:any) => b.selected)).toBe(false);
 // The keyboard-accessible anatomy list shares the same persistent selection.
 await page.locator('[data-cell-anatomy-item="Endoplasmic Reticulum"]').click();
 await expect(canvas).toBeFocused();
 await expect.poll(async () => (await labels()).filter((b:any) => b.selected).map((b:any) => b.name)).toEqual(['Endoplasmic Reticulum']);
 await canvas.evaluate((c:any) => c._cellSimSelectOrganism('amoeba',true));
 await expect.poll(tooltip).toBeNull();
 expect((await labels()).some((b:any) => b.selected || b.hovered)).toBe(false);
 await canvas.evaluate((c:any) => c._cellSimShowOrganelleTooltip('amoeba','Nucleus'));
 await expect.poll(async () => (await tooltip())?.name).toBe('Nucleus');
 await canvas.evaluate((c:any) => c._cellSimSetObservationLabels(false));
 expect(await tooltip()).toBeNull();
 expect(await labels()).toEqual([]);
 await canvas.evaluate((c:any) => c._cellSimSetObservationLabels(true));
 expect((await labels()).some((b:any) => b.selected || b.hovered)).toBe(false);
 await canvas.evaluate((c:any) => c._cellSimShowOrganelleTooltip('amoeba','Nucleus'));
 await canvas.evaluate((c:any) => c._cellSimSelectOrganism(null));
 expect(await tooltip()).toBeNull();
 expect(await labels()).toEqual([]);
 expect(errors).toEqual([]);
});

test('play labels expose hover and selected structure without changing mission behavior', async ({page}) => {
 await page.setViewportSize({width:390,height:960});
 await harness.mount(page,{cell:{mode:'play',playAsOrganism:'plantcell',selectedOrganism:'plantcell',paused:true,showPlayInstructions:false,playMission:{organismId:'plantcell',startSuccess:0,predictionSkipped:true},_cellExt:{successByOrganism:{plantcell:0},tutorialsSeen:{plantcell:true}}}},undefined,{expectCanvas:false});
 await page.addStyleTag({content:'#wrap{width:100%;display:block}'});
 await page.locator('[data-cell-stage]').scrollIntoViewIfNeeded();
 const canvas = page.locator('[data-cell-sim-canvas]');
 await expect.poll(() => canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels().length)).toBeGreaterThan(0);
 const target = await canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels()[0]);
 const rect = (await canvas.boundingBox())!;
 await page.mouse.move(rect.x+target.x+target.width/2,rect.y+target.y+target.height/2);
 await expect(canvas).toHaveCSS('cursor','pointer');
 await expect.poll(() => canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels().some((b:any) => b.hovered))).toBe(true);
 await page.mouse.click(rect.x+target.x+target.width/2,rect.y+target.y+target.height/2);
 await expect.poll(() => canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels().filter((b:any) => b.selected).map((b:any) => b.name))).toEqual([target.name]);
 await canvas.press('Escape');
 expect(await canvas.evaluate((c:any) => c._cellSimGetOrganelleTooltip())).toBeNull();
 await page.mouse.move(0,0);
 await canvas.evaluate((c:any) => c._cellSimShowOrganelleTooltip('plantcell','Chloroplast'));
 await expect.poll(() => canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels().some((b:any) => b.selected))).toBe(true);
 await page.getByRole('button',{name:'Close structure explanation',exact:true}).click();
 await expect.poll(() => canvas.evaluate((c:any) => c._cellSimGetOrganelleTooltip())).toBeNull();
 expect(await canvas.evaluate((c:any) => c._cellSimGetAnatomyLabels().some((b:any) => b.selected || b.hovered))).toBe(false);
});
