#!/usr/bin/env node
/**
 * Build mtss_triage_module.js from mtss_triage_source.jsx
 * (Leadership Hub — admin tools container shell, Aug 2026.)
 * Mirrors _build_udl_walkthrough_module.js.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'mtss_triage_source.jsx');
const OUTPUT = path.join(ROOT, 'mtss_triage_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'mtss_triage_module.js');
const TMP = path.join(ROOT, '_tmp_mtss_triage_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__mtssTriageExports = { MtssTriagePanel, mtssParsePaste, mtssTierOf, mtssValidateCuts, mtssBoard, mtssProgress, mtssSiblingCounts, mtssCsv };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling mtss_triage_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch(_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__mtssTriageExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow MTSS Triage Module
 * Auto-generated by _build_mtss_triage_module.js — DO NOT EDIT MANUALLY.
 * Source: mtss_triage_source.jsx
 * Universal-screening triage: user-entered cut scores -> suggested risk bands for TEAM review (never placement), intervention groups, window-over-window progress; codes-only, on-device.
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.MtssTriage) {
    console.log('[CDN] MtssTriage already loaded, skipping');
    return;
  }
  (function() {
    if (document.getElementById('allo-live-mtss')) return;
    var liveRegion = document.createElement('div');
    liveRegion.id = 'allo-live-mtss';
    liveRegion.setAttribute('aria-live', 'polite');
    liveRegion.setAttribute('aria-atomic', 'true');
    liveRegion.setAttribute('role', 'status');
    liveRegion.className = 'sr-only';
    liveRegion.style.cssText = 'position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);border:0';
    document.body.appendChild(liveRegion);
  })();
  var React = window.React;
  if (!React) { console.error('[MtssTriage] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.MtssTriage = {
    MtssTriagePanel: MtssTriagePanel,
    _testing: {
      mtssParsePaste: mtssParsePaste,
      mtssTierOf: mtssTierOf,
      mtssValidateCuts: mtssValidateCuts,
      mtssBoard: mtssBoard,
      mtssProgress: mtssProgress,
      mtssSiblingCounts: mtssSiblingCounts,
      mtssCsv: mtssCsv
    }
  };
  console.log('[CDN] MtssTriage loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[MtssTriage] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
