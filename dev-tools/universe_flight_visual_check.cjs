const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const report = path.resolve('reports/universe-flight-2026-09-29');
(async () => {
  const browser = await chromium.launch({args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto('file:///' + path.join(report,'preview.html').replaceAll('\\','/'));
  await page.waitForFunction(() => document.querySelector('.uf-transport button')?.disabled === false);
  const stage = page.locator('.uf-stage');
  await page.getByRole('button',{name:'Chart destination: Blue star',exact:true}).click();
  assert.match(await page.locator('#uf-target-info').innerText(),/Blue star/);
  const chartReadout=await page.locator('.uf-readouts').innerText();
  await page.getByRole('button',{name:'Side view · X/Y',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Side view · X/Y',exact:true}).getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.uf-readouts').innerText(),chartReadout,'Changing chart projection does not move the camera');
  await page.getByRole('button',{name:'Top view · X/Z',exact:true}).click();
  await page.getByRole('button',{name:'Behind',exact:true}).click();
  await page.getByRole('button',{name:'Find target: Blue star',exact:true}).click();
  assert.equal(await page.locator('.uf-target-finder').count(),0,'Finding target brings it into view');
  assert.equal(await page.locator('.uf-readouts').innerText(),chartReadout,'Finding a target only rotates the camera');
  await page.getByRole('button',{name:'Hide overlay',exact:true}).click();
  assert.equal(await page.locator('.uf-target-marker').isVisible(),false,'Clean view also hides selected landmark labels');
  await page.getByRole('button',{name:'Show overlay',exact:true}).click();
  const flightCanvas=page.locator('.uf-stage canvas');
  await flightCanvas.focus();await flightCanvas.press('Space');await page.waitForTimeout(650);await flightCanvas.press('Space');
  await page.waitForFunction(()=>document.querySelector('.uf-transport button').textContent==='Start travel');
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const pathBefore=await page.locator('.uf-chart-trail').getAttribute('points');
  assert.ok(pathBefore.split(' ').length>1,'Travel leaves a path on the chart');
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.uf-chart-trail').getAttribute('points'),pathBefore,'Paused path stays fixed');
  await page.locator('.uf-chart').screenshot({path:path.join(report,'navigation-chart-desktop.png')});
  await page.getByRole('button',{name:'Einstein’s light chase',exact:true}).click();
  await page.getByRole('button',{name:'Look sideways',exact:true}).click();
  await page.waitForFunction(()=>Math.abs(Number(document.querySelector('.uf-chart-camera').getAttribute('transform').match(/rotate\(([^)]+)\)/)[1])-154.158067)<0.001);
  const starChartPosition=await page.getByRole('button',{name:'Chart destination: Blue star',exact:true}).getAttribute('style');
  await page.getByRole('button',{name:'Unshifted sky comparison',exact:true}).click();
  await page.waitForFunction(()=>Math.abs(Number(document.querySelector('.uf-chart-camera').getAttribute('transform').match(/rotate\(([^)]+)\)/)[1])-90)<0.001);
  assert.equal(await page.getByRole('button',{name:'Chart destination: Blue star',exact:true}).getAttribute('style'),starChartPosition,'Optical comparison does not move stationary chart landmarks');
  await page.getByRole('button',{name:'Chart destination: Blue star',exact:true}).click();
  await page.getByRole('button',{name:'Behind',exact:true}).click();
  await page.getByRole('button',{name:'Find target: Blue star',exact:true}).click();
  assert.equal(await page.locator('.uf-target-finder').count(),0);
  await page.getByRole('button',{name:'Free exploration',exact:true}).click();
  for (const [region,title] of [['neighborhood','The stellar sea'],['neighborhood','Beside the amber star'],['galaxy','Spiral portrait'],['galaxy','Above the arms'],['galaxy','Across the disk'],['cosmic','Island universe'],['cosmic','The companion'],['cosmic','Golden elliptical'],['cosmic','The wider web']]) {
    await page.locator('#uf-region').selectOption(region);
    await page.locator('.uf-vistas').getByRole('button',{name:new RegExp(title)}).click();
    await page.waitForTimeout(250);
    assert.equal(await page.locator('.uf-transport button').first().innerText(),'Start travel');
    assert.match(await page.locator('.uf-transport [role="status"]').innerText(),/Journey counters reset/);
    assert.equal(await page.locator('.uf-stage canvas').evaluate(c => c.getContext('webgl').getError()),0,'WebGL draws without errors');
    await stage.screenshot({path:path.join(report,'vista-'+title.toLowerCase().replaceAll(' ','-')+'.png')});
  }
  await page.locator('#uf-region').selectOption('galaxy');
  await page.getByRole('button',{name:/Spiral portrait/}).click();
  const distance = await page.locator('#uf-target-info dd').first().innerText();
  const beforeOrbit = await page.locator('.uf-readouts').innerText();
  await page.getByRole('button',{name:'Orbit destination',exact:true}).click();
  await page.waitForTimeout(650);
  await page.getByRole('button',{name:'Pause travel',exact:true}).click();
  assert.notEqual(await page.locator('.uf-readouts').innerText(),beforeOrbit,'Orbit advances camera path length');
  assert.equal(await page.locator('#uf-target-info dd').first().innerText(),distance,'Orbit holds target distance');
  const pausedOrbit = await page.locator('.uf-readouts').innerText();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.uf-readouts').innerText(),pausedOrbit,'Pause holds orbit position');
  await page.getByRole('button',{name:'Reverse orbit direction',exact:true}).click();
  await page.getByRole('button',{name:'Start travel',exact:true}).click();
  await page.waitForTimeout(200);
  await page.getByRole('button',{name:'Right',exact:true}).click();
  assert.equal(await page.locator('.uf-transport button').first().innerText(),'Start travel','Manual look pauses');
  assert.equal(await page.getByRole('button',{name:'End orbit',exact:true}).count(),0,'Manual look ends orbit');
  await page.getByRole('button',{name:/Spiral portrait/}).click();
  await page.getByRole('button',{name:'Orbit destination',exact:true}).click();
  await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).click();
  await page.locator('.uf-fs-play').click();
  assert.equal(await page.locator('.uf-fs-play').innerText(),'Start travel','Fullscreen can pause orbit');
  await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).click();
  await page.getByRole('button',{name:'End orbit',exact:true}).click();
  await page.locator('#uf-region').selectOption('cosmic');
  await page.getByRole('button',{name:/Golden elliptical.*field of view/}).click();
  await page.getByRole('button',{name:'Hide overlay',exact:true}).click();
  assert.equal(await page.locator('.uf-reticle').isVisible(),false);
  assert.equal(await page.locator('.uf-target-marker').isVisible(),false);
  assert.equal(await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).isVisible(),true);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button',{name:'Save image',exact:true}).click();
  const file = path.join(report,'exported-generated-view.png');
  await (await downloaded).saveAs(file);
  const png = fs.readFileSync(file);
  assert.equal(png.subarray(1,4).toString(),'PNG');
  assert.ok(png.length>10000,'Export contains a rendered scene');
  const dimensions = await page.locator('.uf-stage canvas').evaluate(c => [c.width,c.height]);
  assert.deepEqual([png.readUInt32BE(16),png.readUInt32BE(20)],dimensions);
  await page.getByRole('button',{name:'Show overlay',exact:true}).click();
  assert.equal(await page.locator('.uf-reticle').isVisible(),true);
  await page.setViewportSize({width:320,height:800});
  await stage.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,'No narrow-screen overflow');
  await stage.screenshot({path:path.join(report,'vista-phone.png')});
  await page.locator('.uf-chart').screenshot({path:path.join(report,'navigation-chart-phone.png')});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(report,'visual-check.json'),JSON.stringify({errors,viewpoints:9,webglErrors:0,pngBytes:png.length,dimensions,overlay:true,narrowLayout:true,chart:['select','projection','find target','path','pause'],orbit:['travel','fixed distance','pause','reverse','manual look','fullscreen pause','end']},null,2));
  await browser.close();
  console.log('Visual checks passed: chart projections and relativity, 9 viewpoints, WebGL, camera orbits, overlay, PNG export, 320px layout.');
})().catch(error => { console.error(error); process.exit(1); });
