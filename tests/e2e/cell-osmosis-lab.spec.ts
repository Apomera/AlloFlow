import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_cell.js', toolId: 'cell', width: 1100, height: 900, appStyles: true });
test.beforeAll(async () => harness.start());
test.afterAll(async () => harness.stop());
test('osmosis notebook works on desktop and phone', async ({ page }) => {
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await harness.mount(page, { cell: { mode: 'osmoHunt', _cellPicked: true, _cellCategory: 'interactive' } }, undefined, { expectCanvas: false });
  const lab = page.locator('[data-cell-osmosis-lab]');
  await expect(lab).toBeVisible();
  await expect(page.getByRole('button', { name: /Osmosis Lab/ }).first()).toBeVisible();
  await lab.getByRole('button', { name: 'Water leaves', exact: true }).click();
  await expect(lab.locator('[data-osmosis-tonicity]')).toHaveText('Hypertonic external solution');
  await lab.getByLabel('Osmosis prediction').fill('Less permeability reduces flow.');
  await lab.getByRole('button', { name: 'Record trial' }).click();
  await lab.getByRole('button', { name: 'Blocked membrane' }).click();
  await expect(lab.locator('[data-osmosis-comparison]')).toContainText('One variable changed: perm');
  await lab.getByRole('button', { name: 'Record trial' }).click();
  await expect(lab.getByRole('table')).toContainText('Water movement blocked');
  await lab.getByRole('button', { name: 'Plant cell', exact: true }).click();
  await lab.getByRole('button', { name: 'Water enters', exact: true }).click();
  await expect(lab).toContainText('Water entry builds turgor');
  await lab.getByLabel('Osmosis explanation').fill('The wall resists expansion.');
  await lab.getByRole('button', { name: 'Reset controls' }).click();
  await expect(lab.getByLabel('Osmosis explanation')).toHaveValue('The wall resists expansion.');
  await lab.screenshot({ path: 'reports/cell-enhancement/osmosis-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addStyleTag({ content: '#wrap { width: 100%; }' });
  await expect(lab).toBeVisible();
  const overflow = await lab.evaluate(el => el.scrollWidth > el.clientWidth + 2);
  expect(overflow).toBe(false);
  expect(await lab.evaluate(el => el.getBoundingClientRect().width)).toBeLessThanOrEqual(390);
  await lab.getByLabel('Water permeability (%)', { exact: false }).focus();
  await page.keyboard.press('Home');
  await expect(lab.locator('#oh-perm')).toHaveValue('0');
  await lab.screenshot({ path: 'reports/cell-enhancement/osmosis-phone.png' });
  expect(errors).toEqual([]);
});
