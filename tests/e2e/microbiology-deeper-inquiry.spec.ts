test('explores outbreak evidence with a keyboard and preserves past markers after pump closure', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await mount(page, 'cases');
  const map = page.getByRole('region', { name: 'John Snow outbreak evidence illustration', exact: true });
  await expect(map).toContainText('not Snow\'s original map or a historical death-count dataset');
  const checkpoint = map.getByRole('slider', { name: 'Outbreak date checkpoint', exact: true });
  await checkpoint.focus(); await page.keyboard.press('End');
  await expect(checkpoint).toHaveAttribute('aria-valuetext', 'Sept 15, 1854; checkpoint 7 of 7');
  await expect(map.locator('[data-snow-markers] circle')).toHaveCount(220);
  const markers = await map.locator('[data-snow-markers]').innerHTML();
  const close = map.getByRole('button', { name: '🔧 Remove pump handle (Snow\'s intervention)', exact: true });
  await close.focus(); await page.keyboard.press('Enter');
  await expect(map.locator('[data-snow-summary]')).toContainText('Marks representing past deaths remain unchanged');
  expect(await map.locator('[data-snow-markers]').innerHTML()).toBe(markers);
  const locations = map.getByRole('combobox', { name: 'Inspect an illustrative location', exact: true });
  await locations.focus(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
  await expect(locations).toHaveValue('0');
  await expect(map).toContainText('Illustrative location 1. Example address:');
  await expect(map).toContainText('not a verified historical household');
  await map.screenshot({ path: path.join(out, 'outbreak-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow(page);
  await map.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'outbreak-phone.png') });
  expect(errors).toEqual([]);
});
