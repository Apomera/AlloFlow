import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_roadready.js', toolId: 'roadReady', width: 1100, height: 780, appStyles: true, preScripts: ['stem_lab/stem_lab_module.js'], probes: 'window.__testHooks={};' });
test.beforeAll(async () => { await harness.start(); });
test.afterAll(async () => { await harness.stop(); });
test.afterEach(async ({ page }) => { await harness.destroy(page); });
test('paused parking cannot complete, and finishing retains an earlier contact penalty', async ({ page }) => {
  await page.setViewportSize({ width: 1140, height: 950 });
  await harness.mount(page, { roadReady: { view: 'parking', reducedMotion: true, badges: { park_master: true } } }, undefined, { expectCanvas: false });
  const metrics = page.getByRole('region', { name: 'Live parking measurements' });
  const score = page.locator('.rr-parking-scene-heading');
  await page.evaluate(() => Object.assign((window as any).__testHooks.parking.carRef.current, { x: 285, y: 150, heading: -Math.PI / 2, speed: 0, steering: 0 }));
  await page.keyboard.down('w');
  await expect(score).toContainText('Score 75/100 · Contacts 1');
  await page.keyboard.up('w');
  await page.evaluate(() => Object.assign((window as any).__testHooks.parking.carRef.current, { x: 285, y: 167.5, speed: 0, steering: 0 }));
  await page.getByRole('button', { name: /^(Pause|Resume) practice$/ }).click();
  await expect(metrics).toContainText('Practice paused');
  await expect(metrics).not.toContainText('Ready to secure');
  await expect(metrics).toContainText('resume before securing the car');
  await expect(page.getByRole('button', { name: 'Park + parking brake', exact: true })).toBeDisabled();
  await page.keyboard.press('p');
  await page.waitForTimeout(300);
  expect(await page.evaluate(() => !!(window as any).__testHooks.parking.carRef.current.parkingBrake)).toBe(false);
  await page.keyboard.down('s');
  await page.getByRole('button', { name: /^(Pause|Resume) practice$/ }).click();
  await expect(metrics).toContainText('Release the driving controls to continue.');
  expect(await page.evaluate(() => (window as any).__testHooks.parking.carRef.current.y)).toBe(167.5);
  await page.keyboard.up('s');
  await expect(metrics).not.toContainText('Release the driving controls to continue.');
  await page.getByRole('button', { name: 'Park + parking brake', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Parking instructor' })).toContainText('Score: 75/100 (1 hits)');
  await expect(score).toContainText('Score 75/100 · Contacts 1');
  expect(await page.evaluate(() => (window as any).__events.errors)).toEqual([]);
});
