import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_roadready.js', toolId: 'roadReady', width: 1100, height: 780, appStyles: true, preScripts: ['stem_lab/stem_lab_module.js'], probes: "window.__testHooks={};document.documentElement.classList.add('theme-dark');" });
test.beforeAll(async () => { await harness.start(); });
test.afterAll(async () => { await harness.stop(); });
test.afterEach(async ({ page }) => { await harness.destroy(page); });
test('learners can find, preview and follow the parallel parking guide on a phone', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 });
  await harness.mount(page, { roadReady: { view: 'parkingMenu', reducedMotion: true } }, undefined, { expectCanvas: false });
  await page.evaluate(() => { document.getElementById('wrap')!.style.width = '100%'; });
  const standard = page.getByRole('button', { name: /^Standard Parallel/ });
  await expect(standard).toContainText('Start here: a guided 5-step');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await standard.click();
  const current = page.getByLabel('Current parking step');
  await expect(current).toContainText('Step 1 of 5 · Check and line up');
  await page.getByText('Preview the 5-step parking guide', { exact: true }).click();
  const steps = page.getByRole('list', { name: 'Parallel parking steps' });
  await expect(steps.getByRole('listitem')).toHaveCount(5);
  await expect(steps.locator('[aria-current="step"]')).toContainText('Check and line up');
  await expect(steps).toContainText('Before reversing, signal and check mirrors');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await page.keyboard.down('s');
  await expect(current).toContainText('Step 2 of 5 · Reverse and steer right');
  await page.keyboard.up('s');
  await expect(steps.locator('[aria-current="step"]')).toContainText('Reverse and steer right');
  await page.getByRole('button', { name: 'Reset practice', exact: true }).click();
  await expect(current).toContainText('Step 1 of 5');
  await expect(steps.locator('[aria-current="step"]')).toContainText('Check and line up');
  await expect(page.getByLabel('Car response')).toContainText('Stopped · D');
  await page.screenshot({ path: 'reports/roadready-review/parallel-guide-320.png', fullPage: true, scale: 'css' });
  expect(await page.evaluate(() => (window as any).__events.errors)).toEqual([]);
});
