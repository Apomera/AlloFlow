const unchanged=after.every(row=>row.sha256===frozen)&&JSON.stringify(runnerBefore)===JSON.stringify(runnerAfter);
const receipt={startedAt,completedAt:new Date().toISOString(),command:process.execPath,args,exitCode:result.status,signal:result.signal,error:result.error?String(result.error):null,frozenSourceSha256:frozen,unchanged,sourceBefore:before,sourceAfter:after,runnerBefore,runnerAfter};
fs.writeFileSync(path.join(out,'native-exit.json'),JSON.stringify(receipt,null,2)+'\n');
process.stdout.write(result.stdout||'');process.stderr.write(result.stderr||'');console.log(JSON.stringify(receipt,null,2));
if(result.error||result.signal||result.status!==0||!unchanged)process.exitCode=1;
