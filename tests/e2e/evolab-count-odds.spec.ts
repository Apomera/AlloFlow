import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { GlHarness } from './helpers/stem_gl_harness';

test.describe.configure({ timeout: 150_000, retries: 0 });
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_evolab.js', toolId: 'evoLab', width: 1380, height: 980, layout: 'document', appStyles: true });
const report = 'reports/evolab-living-island';
test.beforeAll(async () => { mkdirSync(report, { recursive: true }); await harness.start(); });
test.afterAll(async () => { await harness.stop(); });
test.afterEach(async ({ page }) => { await harness.destroy(page); });

test('probability exploration preserves a draft, advances once when locked and compares real trials without rerolling history', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1100 });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const notes = { livingIsland: { text: 'My own explanation.' }, livingIslandForecast: { text: 'My earlier forecast.' }, livingIslandChanceTrials: { text: 'My earlier trials.' } };
  await harness.mount(page, { evoLab: { view: 'livingIsland', evoProgress: { notes } } });
  const fixture = await page.evaluate(() => { const w = window as any, world = w.StemLab.evoIslandModel.create(2026); return { world, data: w.StemLab.evoIslandCountOdds.forecast(world), next: w.StemLab.evoIslandModel.step(world) }; });
  const world = fixture.world;
  await harness.mount(page, { evoLab: { view: 'livingIsland', island: world, evoProgress: { notes } } });
  const original = JSON.stringify(world), cache = await page.evaluate(() => localStorage.getItem('evoLab.island.v1'));
  const contexts = (await harness.glContexts(page)).filter(r => r.connected && !r.lost).map(r => r.id);
  await page.getByRole('button', { name: 'Predict this round', exact: true }).click();
  await page.locator('#ei-forecast-number').fill('17');
  await page.getByText('Reveal a probability clue', { exact: true }).click();
  const odds = page.locator('[data-count-odds="forecast"]');
  await expect(odds).toBeVisible();
  const mass = await odds.locator('[data-count-probability]').evaluateAll(bars => bars.map(bar => Number(bar.getAttribute('data-count-probability'))));
  expect(mass).toEqual(fixture.data.mass);
  await page.locator('#ei-count-odds-forecast-low').fill('12'); await page.locator('#ei-count-odds-forecast-high').fill('24');
  const chance = fixture.data.mass.slice(12, 25).reduce((sum: number, p: number) => sum + p, 0);
  await expect(odds.locator('[data-odds-band]')).toHaveAttribute('data-odds-band', '12:24');
  expect(Number(await odds.locator('[data-odds-band]').getAttribute('data-odds-band-probability'))).toBeCloseTo(chance, 12);
  await page.locator('#ei-count-odds-forecast-count').focus(); await page.keyboard.press('Home');
  await expect(odds.locator('[data-odds-selected]')).toHaveAttribute('data-odds-selected', '0');
  await odds.getByRole('button', { name: 'Use just this count', exact: true }).click();
  await expect(odds.locator('[data-odds-band]')).toHaveAttribute('data-odds-band', '0:0');
  await odds.getByRole('button', { name: 'Find a central 80% range', exact: true }).click();
  expect(Number(await odds.locator('[data-odds-band]').getAttribute('data-odds-band-probability'))).toBeGreaterThanOrEqual(.8);
  await odds.getByRole('button', { name: 'Save count probability evidence', exact: true }).click();
  let saved = await page.evaluate(() => JSON.parse(localStorage.getItem('evoLab.progress.v1')!).notes);
  expect(saved.livingIslandCountOdds.text).toContain('observed share is undefined'); expect(saved.livingIslandCountOdds.text).not.toContain('Recorded survivors:');
  expect(saved.livingIsland.text).toBe(notes.livingIsland.text); expect(saved.livingIslandForecast.text).toBe(notes.livingIslandForecast.text);
  await expect(page.locator('#ei-forecast-number')).toHaveValue('17');
  expect(await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.island))).toBe(original);
  expect(await page.evaluate(() => localStorage.getItem('evoLab.island.v1'))).toBe(cache);
  await odds.screenshot({ path: report + '/count-probability-desktop-clue.png', style: '.ei-commandbar{visibility:hidden!important}' });
  await page.getByRole('button', { name: 'Lock forecast & watch', exact: true }).click();
  await expect(page.locator('.ei-watch-guide')).toHaveAttribute('data-watch-phase', 'parents');
  await expect(page.locator('[data-count-odds]')).toHaveCount(0);
  expect(await page.evaluate(() => (window as any).__toolData.evoLab.island)).toEqual(fixture.next);
  await page.getByRole('button', { name: 'Reveal survivors', exact: false }).click();
  await page.getByText('Explore chance: repeat this round', { exact: true }).click();
  await page.getByText('Compare trial counts with probability', { exact: true }).click();
  const comparison = page.locator('[data-count-odds="trials"]');
  await expect(comparison.locator('[data-odds-recorded]')).toHaveAttribute('data-odds-recorded', String(fixture.next.history[1].survivors.length));
  const afterRound = await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.island));
  await page.getByRole('button', { name: 'Try five trials', exact: true }).click();
  await page.locator('#ei-count-odds-trials-low').fill('12'); await page.locator('#ei-count-odds-trials-high').fill('24');
  const rows = await page.evaluate(({ world }) => Array.from({ length: 5 }, (_, i) => (window as any).StemLab.evoIslandChanceTrials.run(world, i + 1)), { world });
  const matches = rows.filter((row: any) => row.count >= 12 && row.count <= 24).length;
  await expect(comparison).toContainText(matches + ' of 5 explored trials fall inside this range');
  await comparison.getByRole('button', { name: 'Save count probability evidence', exact: true }).click();
  saved = await page.evaluate(() => JSON.parse(localStorage.getItem('evoLab.progress.v1')!).notes);
  expect(saved.livingIslandCountOdds.text).toContain('Recorded survivors: ' + fixture.next.history[1].survivors.length);
  expect(saved.livingIslandCountOdds.text).toContain('Observed share: ' + (matches / 5).toFixed(6));
  expect(saved.livingIslandCountOdds.text.length).toBeLessThan(2000); expect(saved.livingIslandChanceTrials.text).toBe(notes.livingIslandChanceTrials.text);
  expect(await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.island))).toBe(afterRound);
  expect((await harness.glContexts(page)).filter(r => r.connected && !r.lost).map(r => r.id)).toEqual(contexts);
  await comparison.screenshot({ path: report + '/count-probability-desktop-trials.png', style: '.ei-commandbar{visibility:hidden!important}' });
  expect(errors).toEqual([]);
});

test('phone range controls validate input, expose keyboard equivalents and preserve a recorded zero-survivor result', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(() => { const get = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(type: string, ...args: any[]) { return type.includes('webgl') ? null : (get as any).call(this, type, ...args); } as any; });
  await harness.mount(page, { evoLab: { view: 'livingIsland' } }, undefined, { expectCanvas: false });
  const fixture = await page.evaluate(() => {
    const model = (window as any).StemLab.evoIslandModel;
    for (let seed = 1; seed < 100; seed++) {
      const world = model.create(seed); world.living = false; world.selection = false;
      world.history[0].population = world.history[0].population.slice(0, 1); world.history[0].stats = model.stats(world.history[0].population); world.nextId = 2;
      const next = model.step(world); if (next.history[1].survivors.length === 0) return { world, next };
    }
    throw new Error('No zero-survivor fixture');
  });
  await harness.mount(page, { evoLab: { view: 'livingIsland', island: fixture.world } }, undefined, { expectCanvas: false });
  await page.evaluate(() => { document.getElementById('wrap')!.style.width = '100%'; document.body.style.padding = '0'; });
  await page.getByRole('button', { name: 'Predict this round', exact: true }).click(); await page.getByText('Reveal a probability clue', { exact: true }).click();
  const odds = page.locator('[data-count-odds="forecast"]');
  await page.locator('#ei-count-odds-forecast-low').fill('1'); await page.locator('#ei-count-odds-forecast-high').fill('0');
  await expect(odds.getByRole('button', { name: 'Save count probability evidence', exact: true })).toBeDisabled();
  await expect(page.locator('#ei-count-odds-forecast-low')).toHaveAttribute('aria-invalid', 'true');
  await expect(odds).toContainText('Enter two whole counts');
  await odds.getByRole('button', { name: 'Include all counts', exact: true }).click();
  await expect(odds.locator('[data-odds-band]')).toHaveAttribute('data-odds-band-probability', '1');
  await page.locator('#ei-count-odds-forecast-count').focus(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight');
  await expect(odds.locator('[data-odds-selected]')).toHaveAttribute('data-odds-selected', '1');
  await odds.getByRole('button', { name: 'Use just this count', exact: true }).click();
  await page.addScriptTag({ path: 'node_modules/axe-core/axe.min.js' });
  const violations = await page.evaluate(async () => (window as any).axe.run('[data-count-odds="forecast"]', { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }).then((r: any) => r.violations.map((v: any) => ({ id: v.id, targets: v.nodes.map((n: any) => n.target) }))));
  expect(violations).toEqual([]); expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await odds.screenshot({ path: report + '/count-probability-phone.png', style: '.ei-commandbar{visibility:hidden!important}' });
  await page.getByRole('button', { name: 'Lock forecast & watch', exact: true }).click(); await page.getByRole('button', { name: 'Reveal survivors', exact: false }).click();
  await page.getByText('Explore chance: repeat this round', { exact: true }).click(); await page.getByText('Compare trial counts with probability', { exact: true }).click();
  const comparison = page.locator('[data-count-odds="trials"]');
  await expect(comparison.locator('[data-odds-recorded]')).toHaveAttribute('data-odds-recorded', '0');
  await expect(comparison.locator('[data-odds-recorded-marker]')).toHaveAttribute('data-odds-recorded-marker', '0');
  await page.locator('#ei-count-odds-trials-low').fill('0'); await page.locator('#ei-count-odds-trials-high').fill('0');
  await comparison.getByRole('button', { name: 'Save count probability evidence', exact: true }).click();
  const note = await page.evaluate(() => JSON.parse(localStorage.getItem('evoLab.progress.v1')!).notes.livingIslandCountOdds.text);
  expect(note).toContain('Recorded survivors: 0; inside the selected range'); expect(note).toContain('observed share is undefined');
  expect(await page.evaluate(() => (window as any).__toolData.evoLab.island)).toEqual(fixture.next);
});

test('the clue uses a coming climate change, supports chart taps and keeps its original probabilities after the round', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1100 });
  await harness.mount(page, { evoLab: { view: 'livingIsland' } });
  const fixture = await page.evaluate(() => { const w = window as any, model = w.StemLab.evoIslandModel; let world = model.create(2026); for (let i = 0; i < 4; i++) world = model.step(world); return { world, data: w.StemLab.evoIslandCountOdds.forecast(world), next: model.step(world) }; });
  expect(fixture.data.habitat).not.toBe(fixture.world.habitat);
  await harness.mount(page, { evoLab: { view: 'livingIsland', island: fixture.world } });
  await page.getByRole('button', { name: 'Predict this round', exact: true }).click(); await page.getByText('Reveal a probability clue', { exact: true }).click();
  const odds = page.locator('[data-count-odds="forecast"]'), mode = fixture.data.mass.indexOf(Math.max(...fixture.data.mass));
  await odds.locator('[data-count-bar="' + mode + '"] rect').first().click();
  await expect(odds.locator('[data-odds-band]')).toHaveAttribute('data-odds-band', mode + ':' + mode);
  expect(Number(await odds.locator('[data-odds-band]').getAttribute('data-odds-band-probability'))).toBeCloseTo(fixture.data.mass[mode], 12);
  await page.getByRole('button', { name: 'Lock forecast & watch', exact: true }).click(); await page.getByRole('button', { name: 'Show offspring', exact: true }).click();
  await page.getByText('Explore chance: repeat this round', { exact: true }).click(); await page.getByText('Compare trial counts with probability', { exact: true }).click();
  const actual = await page.locator('[data-count-odds="trials"] [data-count-probability]').evaluateAll(bars => bars.map(bar => Number(bar.getAttribute('data-count-probability'))));
  expect(actual).toEqual(fixture.data.mass);
  expect(await page.evaluate(() => (window as any).__toolData.evoLab.island)).toEqual(fixture.next);
});
