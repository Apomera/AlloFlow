function _pyStr(value) {
  if (value === null || value === undefined || typeof value === 'symbol') return '';
  if (typeof value === 'string') return value;
  try { return String(value); } catch (_) { return ''; }
}

function _pySafeParse(raw) {
  return JSON.parse(raw, function (k, v) {
    if (k === '__proto__' || k === 'constructor' || k === 'prototype') return undefined;
    return v;
  });
}

function _pyLog(method) {
  try {
    if (typeof console !== 'undefined' && console && typeof console[method] === 'function') {
      console[method].apply(console, Array.prototype.slice.call(arguments, 1));
    }
  } catch (_) {}
}

// Dynamically inject the Pyodide loader script. Returns a promise that
// resolves once `window.loadPyodide` is callable.
function _heuristicSyllablesJs(word) {
  const cleaned = _pyStr(word).toLowerCase().replace(/[^a-z]/g, '');
  if (!cleaned) return 0;
  if (cleaned.length <= 3) return 1;
  let w = cleaned.replace(/(?:[^laeiouy]es|ed|[^laeiouy]e)$/, '').replace(/^y/, '');
  const groups = w.match(/[aeiouy]{1,2}/g);
  return Math.max(1, groups ? groups.length : 1);
}

function _rhymeClassJs(word) {
  const cleaned = _pyStr(word).toLowerCase().replace(/[^a-z]/g, '');
  if (!cleaned) return '';
  return cleaned.length <= 3 ? '~' + cleaned : '~' + cleaned.slice(-3);
}

function verifyFormJs(form, poemText, targetWord = null) {
  const spec = form && typeof form === 'object' ? form : {};
  const boundedPoem = _pyStr(poemText).slice(0, MAX_POEM_TEXT_CHARS);
  const rawLines = boundedPoem.split(/\r?\n/).map(l => l.trimEnd()).filter(l => l.trim().length > 0);
  const findings = [];
  const formName = _pyStr(spec.name) || 'Poem';
  if (Number.isFinite(spec.lineCount) && spec.lineCount > 0 && rawLines.length !== spec.lineCount) {
    findings.push({
      severity: 'high',
      message: `${formName}: expected ${spec.lineCount} lines, found ${rawLines.length}.`,
    });
  }
  const expectedSyl = spec.syllablesPerLine;
  const shared = _sharedSyllables();
  const lineEntries = rawLines.map((text, idx) => {
    const words = text.match(/[a-zA-Z']+/g) || [];
    let exp = null;
    if (Array.isArray(expectedSyl)) exp = expectedSyl[idx] != null ? expectedSyl[idx] : null;
    else if (Number.isFinite(expectedSyl) && expectedSyl > 0) exp = expectedSyl;
    // PoetTree's counter reads the CMU-based word table; the rule below is
    // only what is left when PoetTree is not on the page.
    let info = null;
    if (shared) {
      try {
        const res = shared.line(text, exp);
        if (res && typeof res === 'object' && Number.isFinite(res.count)) info = res;
      } catch (_) { info = null; }
    }
    const syl = info ? info.count : words.reduce((acc, w) => acc + _heuristicSyllablesJs(w), 0);
    const match = info ? !!info.match : (exp == null ? true : syl === exp);
    if (!match) {
      findings.push({
        severity: 'medium',
        message: `Line ${idx + 1}: ${syl} syllables (expected ${exp}).`,
      });
    }
    const lastWord = words.length ? words[words.length - 1] : '';
    return {
      text,
      syllables_actual: syl,
      syllables_expected: exp,
      syllables_match: match,
      unknown_words: (info && Array.isArray(info.unknown)) ? info.unknown : words,
      stress_pattern: null,
      rhyme_class: _rhymeClassJs(lastWord),
    };
  });
  if (spec.id === 'acrostic' && targetWord) {
    const target = _pyStr(targetWord).replace(/[^a-zA-Z]/g, '').toUpperCase();
    if (target.length > 0 && rawLines.length !== target.length) {
      findings.push({
        severity: 'high',
        message: `Acrostic: expected ${target.length} lines for "${target}", found ${rawLines.length}.`,
      });
    }
    for (let i = 0; i < Math.min(rawLines.length, target.length); i++) {
      const m = rawLines[i].match(/[a-zA-Z]/);
      const got = m ? m[0].toUpperCase() : '';
      if (got !== target[i]) {
        findings.push({
          severity: 'high',
          message: `Acrostic line ${i + 1}: starts with '${got || '?'}', expected '${target[i]}'.`,
        });
      }
    }
  } else if (spec.id === 'villanelle' && rawLines.length >= 6) {
    [[0, 5], [0, 11], [0, 17]].forEach(([ref, tgt]) => {
      if (tgt < rawLines.length && rawLines[ref].trim().toLowerCase() !== rawLines[tgt].trim().toLowerCase()) {
        findings.push({ severity: 'medium', message: `Villanelle: line 1 should repeat at line ${tgt + 1}.` });
      }
    });
    [[2, 8], [2, 14], [2, 18]].forEach(([ref, tgt]) => {
      if (tgt < rawLines.length && rawLines[ref].trim().toLowerCase() !== rawLines[tgt].trim().toLowerCase()) {
        findings.push({ severity: 'medium', message: `Villanelle: line 3 should repeat at line ${tgt + 1}.` });
      }
    });
  } else if (spec.id === 'pantoum' && rawLines.length > 0 && rawLines.length % 4 !== 0) {
    findings.push({ severity: 'medium', message: 'Pantoum: lines should be grouped into four-line stanzas.' });
  } else if (spec.id === 'diamante' && rawLines.length !== 7) {
    findings.push({ severity: 'high', message: `Diamante: expected 7 lines, found ${rawLines.length}.` });
  } else if (spec.id === 'couplet' && rawLines.length % 2 !== 0) {
    findings.push({ severity: 'medium', message: 'Couplet: expected an even number of lines.' });
  } else if (spec.id === 'ballad' && rawLines.length > 0 && rawLines.length % 4 !== 0) {
    findings.push({ severity: 'medium', message: 'Ballad: traditional stanzas are groups of 4 lines.' });
  }
  return {
    form_id: spec.id || 'free',
    overall_match: findings.length === 0,
    findings,
    lines: lineEntries,
    source: shared ? 'word-table' : 'js-heuristic',
  };
}

// PoetTree owns the syllable counter (CMU-based word table, estimate only for
// a word the table lacks). The Python path has had no dictionary since the
// runtime `pronouncing` install was removed, so its counts are replaced too.
function _sharedSyllables() {
  const shared = typeof window === 'object' && window && window.AlloModules && window.AlloModules.PoetTreeSyllables;
  return shared && typeof shared.line === 'function' ? shared : null;
}

async function _loadSyllableTable() {
  const shared = _sharedSyllables();
  if (!shared || typeof shared.load !== 'function') return false;
  try { return !!(await shared.load()); } catch (_) { return false; }
}

function _applySharedSyllables(result) {
  const shared = _sharedSyllables();
  if (!shared || !result || result.error || !Array.isArray(result.lines)) return result;
  result.lines.forEach((ln, idx) => {
    if (!ln || typeof ln !== 'object') return;
    const exp = Number.isFinite(ln.syllables_expected) && ln.syllables_expected > 0 ? ln.syllables_expected : null;
    let info = null;
    try { info = shared.line(_pyStr(ln.text), exp); } catch (_) { info = null; }
    if (!info || typeof info !== 'object') return;
    if (ln.line_num == null) ln.line_num = idx + 1;
    ln.syllables_actual = info.count;
    ln.syllables_match = !!info.match;
    ln.unknown_words = Array.isArray(info.unknown) ? info.unknown : [];
    ln.method = info.estimated ? 'word-table+estimate' : 'word-table';
  });
  const kept = (Array.isArray(result.findings) ? result.findings : []).filter(f => f && f.kind !== 'syllables');
  const syllableFindings = result.lines.filter(ln => ln && !ln.syllables_match).map(ln => ({
    severity: 'medium',
    kind: 'syllables',
    line_num: ln.line_num,
    message: `Line ${ln.line_num}: ${ln.syllables_actual} syllables, expected ${ln.syllables_expected}. "${_pyStr(ln.text).slice(0, 60)}"`,
  }));
  result.findings = kept.filter(f => f.kind === 'line_count').concat(syllableFindings, kept.filter(f => f.kind !== 'line_count'));
  result.overall_match = result.findings.length === 0;
  return result;
}

function _loadPyodideScript() {
  if (!_canLoadExternalPyodide()) {
    return Promise.reject(new Error('External Pyodide runtime is disabled in offline or desktop mode.'));
  }
  if (typeof window.loadPyodide === 'function') return Promise.resolve();
  if (typeof document === 'undefined' || !document || !document.head) {
    return Promise.reject(new Error('DOM unavailable for loading pyodide.js.'));
  }
  return new Promise((resolve, reject) => {
    const script = document.createElement('script');
    script.integrity = PYODIDE_JS_SRI;
    script.crossOrigin = 'anonymous';
    script.referrerPolicy = 'no-referrer';
    script.src = PYODIDE_CDN + 'pyodide.js';
    script.async = true;
    let settled = false;
    const cleanup = () => {
      clearTimeout(timer);
      script.onload = null;
      script.onerror = null;
    };
    const fail = (err) => {
      if (settled) return;
      settled = true;
      cleanup();
      try { if (script.parentNode) script.parentNode.removeChild(script); } catch (_) {}
      reject(err);
    };
    const timer = setTimeout(() => fail(new Error('Timed out loading pyodide.js from ' + script.src)), 30000);
    script.onload = () => {
      if (settled) return;
      if (typeof window.loadPyodide !== 'function') {
        fail(new Error('pyodide.js loaded without window.loadPyodide from ' + script.src));
        return;
      }
      settled = true;
      cleanup();
      resolve();
    };
    script.onerror = () => fail(new Error('Failed to load pyodide.js from ' + script.src));
    document.head.appendChild(script);
  });
}

async function _init() {
  if (_pyodide) return _pyodide;
  _loadStartedAt = Date.now();
  _pyLog('log', '[PyodideRuntime] Initializing… (~10MB download on first load)');
  await _loadPyodideScript();
  let initTimer = null;
  const loadPromise = Promise.resolve().then(() => window.loadPyodide({ indexURL: PYODIDE_CDN }));
  loadPromise.catch(() => {});
  const py = await Promise.race([
    loadPromise,
    new Promise((_, reject) => {
      initTimer = setTimeout(() => reject(new Error('Timed out initializing Pyodide WASM runtime.')), 60000);
    }),
  ]).finally(() => {
    if (initTimer) clearTimeout(initTimer);
  });
  if (!py || typeof py.runPython !== 'function' || !py.FS || typeof py.FS.writeFile !== 'function') {
    throw new Error('Pyodide runtime failed to initialize.');
  }
  // Inject both Python modules into the Pyodide filesystem so we can
  // `import report_checks` / `import poetry_checks` cleanly from any caller.
  py.runPython('import sys; sys.path.insert(0, "/")');
  py.FS.writeFile('/report_checks.py', REPORT_CHECKS_PY);
  py.FS.writeFile('/poetry_checks.py', POETRY_CHECKS_PY);
  // Eager import of report_checks to surface any syntax errors at boot.
  // poetry_checks is imported lazily because it depends on `pronouncing`
  // which has to be pip-installed on first use.
  py.runPython('import report_checks');
  _pyodide = py;
  const elapsed = ((Date.now() - _loadStartedAt) / 1000).toFixed(1);
  _pyLog('log', `[PyodideRuntime] Ready in ${elapsed}s`);
  return _pyodide;
}

