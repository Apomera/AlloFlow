import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_ecosystem.js', toolId: 'ecosystem', width: 1100, height: 900, appStyles: true });
test.beforeAll(async () => harness.start());
test.afterAll(async () => harness.stop());
test.afterEach(async ({page}) => harness.destroy(page));
test('community cards and key moments stay synchronized with graphs, tables and 3D', async ({page}) => {
  await page.setViewportSize({width:1140,height:940});
  await harness.mount(page,{ecosystem:{tab:'foodweb',tutorialDismissed:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.body.className='theme-default'; document.getElementById('wrap')!.style.cssText='width:100%;height:auto;display:block;padding:16px;background:white';});
  await page.getByRole('button',{name:'Habitat restoration',exact:true}).click();
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  const overview=page.locator('[data-efw-overview]'), canvas=page.locator('.efw-meadow-stage canvas');
  await expect(overview.locator('[data-efw-overview-species]')).toHaveCount(5);
  await expect(overview.locator('polyline[stroke-dasharray]')).toHaveCount(5);
  expect((await overview.locator('polyline').evaluateAll(els=>els.map(el=>el.getAttribute('points')))).join('')).not.toMatch(/NaN|Infinity/);
  const voles=overview.getByRole('button',{name:/Compare Meadow voles/});
  await voles.focus(); await voles.press('Enter');
  await expect(page.getByLabel('Chart group',{exact:true})).toHaveValue('voles');
  const info=await page.evaluate(()=>{const w=window as any;return w.StemLab.ecosystemFoodWeb.insights(w.StemLab.ecosystemFoodWeb.compare(w.__toolData.ecosystem.foodWeb.run.config)).find((x:any)=>x.id==='voles');});
  await overview.getByRole('button',{name:'Inspect largest difference',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-step',String(info.peak.step));
  await expect(page.getByRole('slider',{name:'Food-web comparison time',exact:true})).toHaveValue(String(info.peak.step));
  await overview.getByRole('button',{name:'Inspect first 0.1 difference',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-step',String(info.firstVisible.step));
  await overview.getByRole('button',{name:'Before disturbance',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-step','79');
  await expect(canvas).toHaveAttribute('data-refuge-cover','10');
  await overview.getByRole('button',{name:'At disturbance',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-step','80');
  await expect(canvas).toHaveAttribute('data-refuge-cover','50');
  expect(await overview.locator('.efw-overview-delta').allTextContents()).toEqual(Array(5).fill('Difference 0.0'));
  await overview.getByRole('button',{name:'End',exact:true}).click();
  await overview.screenshot({path:'reports/ecosystem-community-overview/desktop.png'});
  await page.getByRole('button',{name:'Play meadow timeline',exact:true}).click();
  await expect(page.getByRole('button',{name:'Pause meadow timeline',exact:true})).toBeVisible();
  await overview.getByRole('button',{name:'At disturbance',exact:true}).click();
  await expect(page.getByRole('button',{name:'Play meadow timeline',exact:true})).toBeVisible();
  await page.waitForTimeout(250); await expect(canvas).toHaveAttribute('data-step','80');
  for (const theme of ['dark','contrast']) {
    await page.evaluate(theme=>{document.body.className='theme-'+theme; const w=window as any;w.__ctx.theme=theme;w.__ctx.isDark=theme==='dark';w.__ctx.isContrast=theme==='contrast';w.__rerender();},theme);
    await overview.screenshot({path:'reports/ecosystem-community-overview/'+theme+'.png'});
  }
  await page.setViewportSize({width:390,height:844});
  await overview.screenshot({path:'reports/ecosystem-community-overview/mobile.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.setViewportSize({width:320,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByLabel('Disturbance',{exact:true}).selectOption('none');
  await expect(overview).toHaveCount(0);
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await expect(overview).toContainText('The two runs match for this group at every sampled time.');
  await expect(overview.getByRole('button',{name:'Inspect largest difference',exact:true})).toHaveCount(0);
  await expect(overview.getByRole('button',{name:'At disturbance',exact:true})).toHaveCount(0);
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
