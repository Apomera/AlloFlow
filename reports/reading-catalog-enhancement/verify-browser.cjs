const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const req = require('module').createRequire(path.resolve('desktop/web-app/package.json'));
(async () => {
  const css = await req('postcss')([req('tailwindcss')({content:[{raw:fs.readFileSync('reading_library_module.js','utf8'),extension:'js'}],corePlugins:{preflight:true}})]).process('@tailwind base; @tailwind utilities;', {from:undefined});
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const art='<svg xmlns="http://www.w3.org/2000/svg" width="600" height="800"><rect width="600" height="800" fill="#d1fae5"/><circle cx="300" cy="270" r="150" fill="#059669"/><text x="300" y="520" text-anchor="middle" font-size="42" fill="#064e3b">Picture book</text></svg>';
  const books=Array.from({length:8},(_,i)=>({slug:'picture-'+i,title:'Picture story '+(i+1),language:'English',langCode:'en',level:1,sourceId:'storyweaver',authors:['Catalog test author'],cover:'/cover.svg',file:'books/picture-'+i+'.json',pageCount:2,license:'CC BY 4.0'}));
  await page.route('**/*',async route=>{
    const u=new URL(route.request().url());
    if(u.pathname.endsWith('index.json')) return route.fulfill({json:{books}});
    if(u.pathname.endsWith('index_cards.json')) return route.fulfill({json:{books:[]}});
    if(u.pathname.includes('/books/')) return route.fulfill({json:{...books[0],pages:[{n:1,img:'/cover.svg',imgCaption:'A green tree',text:'A tree grows in the garden.'},{n:2,img:'/cover.svg',text:'The tree grows taller.'}]}});
    if(u.pathname.endsWith('.svg')) return route.fulfill({contentType:'image/svg+xml',body:art});
    if(u.pathname==='/') return route.fulfill({contentType:'text/html',body:'<!doctype html><html><body><div id="root"></div></body></html>'});
    return route.abort();
  });
  await page.goto('http://reading.test/');
  await page.addStyleTag({content:css.css});
  await page.addScriptTag({path:'desktop/web-app/node_modules/react/umd/react.production.min.js'});
  await page.addScriptTag({path:'desktop/web-app/node_modules/react-dom/umd/react-dom.production.min.js'});
  await page.addScriptTag({path:'reading_library_module.js'});
  const mount=()=>page.evaluate(()=>{ window.readerRoot=window.readerRoot||ReactDOM.createRoot(document.getElementById('root')); readerRoot.render(React.createElement(AlloModules.ReadingLibrary,{isOpen:true,onClose:()=>window.wasClosed=true,addToast:()=>{}})); });
  await mount();
  await page.getByRole('button').filter({hasText:/Stories/}).click();
  const large=page.getByRole('button',{name:'Large pictures',exact:true});
  await large.click();
  assert.equal(await large.getAttribute('aria-pressed'),'true');
  assert.equal(await page.evaluate(()=>localStorage.getItem('allo_reading_catalog_size')),'large');
  assert.equal(await page.locator('button img').first().evaluate(el=>getComputedStyle(el).height),'320px');
  assert.equal(await page.locator('button img').first().evaluate(el=>getComputedStyle(el).objectFit),'contain');
  await page.screenshot({path:'reports/reading-catalog-enhancement/catalog-desktop.png'});
  await page.getByRole('button').filter({hasText:'Picture story 1'}).first().click();
  await page.getByRole('button',{name:'Enlarge picture',exact:true}).click();
  const zoom=page.getByRole('slider',{name:'Picture zoom'});
  await zoom.fill('250');
  assert.equal(await zoom.getAttribute('aria-valuetext'),'250%');
  assert.equal(await page.getByRole('region',{name:'Enlarged picture'}).locator('img').evaluate(el=>el.style.width),'250%');
  await page.getByRole('button',{name:'Fit picture',exact:true}).click();
  assert.equal(await zoom.inputValue(),'100');
  await zoom.focus(); await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button',{name:'Enlarge picture',exact:true}).count(),1);
  assert.equal(await page.evaluate(()=>window.wasClosed),undefined);
  assert.equal(await page.getByRole('button',{name:'Enlarge picture',exact:true}).evaluate(el=>el===document.activeElement),true);
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await large.click();
  const card=page.getByRole('button').filter({hasText:'Picture story 1'}).first();
  await card.scrollIntoViewIfNeeded();
  assert.equal(await page.locator('[data-testid="reading-catalog-scroll"]').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
  await page.screenshot({path:'reports/reading-catalog-enhancement/catalog-mobile.png'});
  await card.click();
  await page.getByRole('button',{name:'Enlarge picture',exact:true}).click();
  await page.getByRole('slider',{name:'Picture zoom'}).fill('300');
  const region=page.getByRole('region',{name:'Enlarged picture'});
  await region.scrollIntoViewIfNeeded();
  await region.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('region',{name:'Enlarged picture'}).count(),1);
  assert.equal(await region.evaluate(el=>el.scrollWidth>el.clientWidth),true);
  assert.equal(await page.getByRole('dialog',{name:'Reading Library',exact:true}).evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
  await page.screenshot({path:'reports/reading-catalog-enhancement/picture-mobile.png'});
  await region.locator('img').dispatchEvent('error');
  await page.getByRole('status').filter({hasText:'This illustration could not load'}).waitFor();
  assert.deepEqual(errors,[]);
  fs.writeFileSync('reports/reading-catalog-enhancement/browser-results.json',JSON.stringify({passed:true,checks:['cover sizing and preservation','saved preference','picture zoom and reset','Escape keeps reader open and restores focus','mobile catalog scrolling','mobile zoom overflow containment','image failure fallback','no browser errors'],errors},null,2));
  await browser.close();
  console.log('Reading catalog browser checks passed');
})().catch(e=>{console.error(e);process.exitCode=1; setTimeout(()=>process.exit(1),1000)});

