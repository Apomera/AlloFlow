#!/usr/bin/env node
/** Build the shared AlloFlow Educator Growth & Evaluation module. */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'educator_evaluation_source.jsx');
const OUTPUT = path.join(ROOT, 'educator_evaluation_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop', 'web-app', 'public', 'educator_evaluation_module.js');
const STANDALONE_SOURCE = path.join(ROOT, 'educator-evaluation.html');
const STANDALONE_OUT = path.join(ROOT, 'desktop', 'web-app', 'public', 'educator-evaluation.html');
const TMP = path.join(ROOT, '_tmp_educator_evaluation_entry.jsx');

if (!fs.existsSync(SOURCE)) {
  console.error('Source not found:', SOURCE);
  process.exit(1);
}

const source = fs.readFileSync(SOURCE, 'utf8');
fs.writeFileSync(TMP, `/* global React */\n${source}\nwindow.__educatorEvaluationExports = { EducatorEvaluationPanel };\n`, 'utf8');

try {
  execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (error) {
  try { fs.unlinkSync(TMP); } catch (_) {}
  console.error('esbuild failed');
  process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf8')
  .replace(/\/\*.*global.*\*\/\n/g, '')
  .replace(/window\.__educatorEvaluationExports\s*=\s*\{[^}]+\};?\s*/, '')
  .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow Educator Growth & Evaluation Module
 * Auto-generated by _build_educator_evaluation_module.js. Do not edit manually.
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.EducatorEvaluation) {
    console.log('[CDN] EducatorEvaluation already loaded, skipping');
    return;
  }
  var React = window.React;
  if (!React) { console.error('[EducatorEvaluation] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.EducatorEvaluation = {
    EducatorEvaluationPanel: EducatorEvaluationPanel,
    _testing: {
      AE_DOMAINS: AE_DOMAINS,
      AE_COMPONENTS: AE_COMPONENTS,
      aeWeightProfile: aeWeightProfile,
      aeObservationScore: aeObservationScore,
      aeOverallScore: aeOverallScore,
      aeRoundedScore: aeRoundedScore,
      aeBand: aeBand,
      aeRatingLabel: aeRatingLabel,
      aeCompletionSummary: aeCompletionSummary,
      aeTeacherStatus: aeTeacherStatus,
      aeStepOfObservation: aeStepOfObservation,
      aeCsv: aeCsv,
      aeNormalizeWorkspace: aeNormalizeWorkspace,
      AE_MIN_TREND_COHORT: AE_MIN_TREND_COHORT,
      AE_MAX_CYCLE_SNAPSHOTS: AE_MAX_CYCLE_SNAPSHOTS,
      aeTeacherTrendPoints: aeTeacherTrendPoints,
      aeDistinctTeacherMedian: aeDistinctTeacherMedian,
      aeCohortMetric: aeCohortMetric
    }
  };
  console.log('[CDN] EducatorEvaluation loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf8');
fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf8');

// The standalone shell bundles its own production React runtime so the page
// can be hosted or opened locally without relying on a third-party CDN.
const STANDALONE_BUNDLE = path.join(ROOT, 'educator_evaluation_standalone.js');
const STANDALONE_BUNDLE_OUT = path.join(ROOT, 'desktop', 'web-app', 'public', 'educator_evaluation_standalone.js');
const STANDALONE_ENTRY = path.join(ROOT, '_tmp_educator_evaluation_standalone.jsx');
const reactImport = path.join(ROOT, 'desktop', 'web-app', 'node_modules', 'react', 'index.js').replace(/\\/g, '/');
const reactDomImport = path.join(ROOT, 'desktop', 'web-app', 'node_modules', 'react-dom', 'client.js').replace(/\\/g, '/');
// Bundle the repo's single QR implementation so the standalone page can render
// the Share-by-QR card without any network dependency. The library declares a
// module-scoped `qrcode`, so attach it to window for the panel's feature check.
const qrSource = fs.readFileSync(path.join(ROOT, 'qrcode.js'), 'utf8');
fs.writeFileSync(STANDALONE_ENTRY, `import React from ${JSON.stringify(reactImport)};\nimport { createRoot } from ${JSON.stringify(reactDomImport)};\n${qrSource}\nif (typeof window !== 'undefined') window.qrcode = window.qrcode || qrcode;\n${source}\ncreateRoot(document.getElementById('educator-evaluation-root')).render(React.createElement(EducatorEvaluationPanel, { standalone: true }));\n`, 'utf8');
require('esbuild').buildSync({
  entryPoints: [STANDALONE_ENTRY],
  outfile: STANDALONE_BUNDLE,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'eof',
  define: { 'process.env.NODE_ENV': '"production"' },
});
fs.copyFileSync(STANDALONE_BUNDLE, STANDALONE_BUNDLE_OUT);
fs.unlinkSync(STANDALONE_ENTRY);
if (fs.existsSync(STANDALONE_SOURCE)) fs.copyFileSync(STANDALONE_SOURCE, STANDALONE_OUT);
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines) and standalone bundle`);