#!/usr/bin/env node
/**
 * Build udl_walkthrough_module.js from udl_walkthrough_source.jsx
 * (UDL Walkthrough — admin/coach observation tool, MVP, Aug 2026.)
 *
 * Mirrors _build_seating_chart_module.js: esbuild JSX -> createElement,
 * IIFE wrapper with a11y live region, writes udl_walkthrough_module.js +
 * syncs to desktop/web-app/public/.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'udl_walkthrough_source.jsx');
const OUTPUT = path.join(ROOT, 'udl_walkthrough_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'udl_walkthrough_module.js');
const TMP = path.join(ROOT, '_tmp_udl_walkthrough_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__udlWalkthroughExports = { UdlWalkthroughPanel, udlwalkFeedbackFromSession, udlwalkFeedbackText, udlwalkNextTeacherCode, udlwalkTeacherDisplay, UDLWALK_LOOK_FORS, UDLWALK_STUDENT_INDICATORS };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling udl_walkthrough_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch(_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__udlWalkthroughExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow UDL Walkthrough Module
 *
 * Auto-generated by _build_udl_walkthrough_module.js — DO NOT EDIT MANUALLY.
 * Source: udl_walkthrough_source.jsx
 *
 * Growth-framed classroom walkthroughs on the CAST UDL Guidelines 3.0
 * structure: 27 doorway-observable look-fors + 8 student-moment indicators,
 * per-visit feedback card, JSON export/import. All data stays on the device;
 * no AI in the loop. UDL-aligned look-fors, NOT a validated instrument.
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.UdlWalkthrough) {
    console.log('[CDN] UdlWalkthrough already loaded, skipping');
    return;
  }
  (function() {
    if (document.getElementById('allo-live-udlwalk')) return;
    var liveRegion = document.createElement('div');
    liveRegion.id = 'allo-live-udlwalk';
    liveRegion.setAttribute('aria-live', 'polite');
    liveRegion.setAttribute('aria-atomic', 'true');
    liveRegion.setAttribute('role', 'status');
    liveRegion.className = 'sr-only';
    liveRegion.style.cssText = 'position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);border:0';
    document.body.appendChild(liveRegion);
  })();
  var React = window.React;
  if (!React) { console.error('[UdlWalkthrough] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.UdlWalkthrough = {
    UdlWalkthroughPanel: UdlWalkthroughPanel,
    // Pure seams exposed for unit tests. Not part of the public contract.
    _testing: {
      udlwalkFeedbackFromSession: udlwalkFeedbackFromSession,
      udlwalkFeedbackText: udlwalkFeedbackText,
      udlwalkNextTeacherCode: udlwalkNextTeacherCode,
      udlwalkTeacherDisplay: udlwalkTeacherDisplay,
      UDLWALK_LOOK_FORS: UDLWALK_LOOK_FORS,
      UDLWALK_STUDENT_INDICATORS: UDLWALK_STUDENT_INDICATORS
    }
  };
  console.log('[CDN] UdlWalkthrough loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[UdlWalkthrough] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
