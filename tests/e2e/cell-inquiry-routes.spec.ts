import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_cell.js', toolId: 'cell', width: 1100, height: 900, appStyles: true });
test.beforeAll(async () => harness.start());
test.afterAll(async () => harness.stop());
test('inquiry routes guide evidence, resume notes, and remain usable on a phone', async ({ page }) => {
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await harness.mount(page, { cell: { mode: 'compare', interiorStudyFocus: true } }, undefined, { expectCanvas: false });
  const cards = page.locator('[data-cell-inquiry-cards]');
  await expect(cards).toBeVisible();
  await cards.screenshot({ path: 'reports/cell-enhancement/inquiry-hub-desktop.png' });
  await expect(cards).toHaveCSS('background-color', 'rgb(247, 251, 251)');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addStyleTag({ content: '#wrap { max-width:100%; }' });
  expect(await cards.evaluate(el => el.getBoundingClientRect().width)).toBeLessThanOrEqual(390);
  expect(await cards.evaluate(el => el.scrollWidth > el.clientWidth + 2)).toBe(false);
  await cards.screenshot({ path: 'reports/cell-enhancement/inquiry-hub-phone.png' });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('[data-cell-start-inquiry="balance"]').click();
  const guide = page.locator('[data-cell-inquiry-guide]');
  await expect(guide).toBeVisible();
  await expect(page.locator('[data-cell-current-activity]')).toHaveText('Inside the Cell');
  await guide.getByText('Record an observation', { exact: true }).click();
  const response = guide.getByLabel('What did you observe?', { exact: true });
  await expect(guide.getByRole('button', { name: 'Save observation & continue' })).toBeDisabled();
  await response.fill('The membrane controls exchange with the surroundings.');
  await guide.getByRole('button', { name: 'Save observation & continue' }).click();
  await expect(page.locator('[data-cell-current-activity]')).toHaveText('Cell Processes');
  await expect(guide).toContainText('1/3 observations recorded');
  await expect(page.locator('#cell-process-tab-transport')).toHaveAttribute('aria-selected','true');
  await guide.getByRole('button', { name: 'Go to activity' }).click();
  await expect(page.locator('[data-cell-processes-workspace]')).toBeFocused();
  await guide.getByText('Record an observation', { exact: true }).click();
  await response.fill('The diagram separates water channels from ATP-powered pumps.');
  await guide.getByRole('button', { name: 'Save observation & continue' }).click();
  await expect(page.locator('[data-cell-current-activity]')).toHaveText('Osmosis Lab');
  await guide.getByText('Record an observation', { exact: true }).click();
  await response.fill('At equal concentrations, changing permeability kept net flow at zero.');
  await guide.getByRole('button', { name: 'Record observation', exact: true }).click();
  await expect(guide).toContainText('3/3 observations recorded');
  const pending = page.waitForEvent('download');
  await guide.getByRole('button', { name: 'Download inquiry notes' }).click();
  const downloaded = await pending;
  expect(downloaded.suggestedFilename()).toBe('cell-inquiry-balance.txt');
  const chunks: Buffer[] = []; const stream = await downloaded.createReadStream();
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks).toString('utf8')).toContain('net flow at zero');
  await guide.getByRole('button', { name: 'Pause route' }).click();
  await expect(guide).toHaveCount(0);
  await page.locator('[data-cell-navigation]').getByRole('button', { name: /Hub/ }).click();
  await page.locator('[data-cell-start-inquiry="balance"]').click();
  await expect(guide).toContainText('3/3 observations recorded');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addStyleTag({ content: '#wrap { width:100%; }' });
  await guide.screenshot({ path: 'reports/cell-enhancement/inquiry-guide-phone.png' });
  expect(await guide.evaluate(el => el.scrollWidth > el.clientWidth + 2)).toBe(false);
  await guide.getByRole('button', { name: /Inspect a boundary/ }).click();
  await guide.getByText('Edit this step’s observation', { exact: true }).click();
  await expect(response).toHaveValue('The membrane controls exchange with the surroundings.');
  await response.fill('Revised membrane observation.');
  await expect(guide).toContainText('2/3 observations recorded');
  await guide.getByRole('button', { name: 'Save observation & continue' }).click();
  await expect(guide).toContainText('3/3 observations recorded');
  expect(errors).toEqual([]);
});
