#!/usr/bin/env node
'use strict';

/**
 * Generates vendor/lucide-promo-subset.min.js containing only the Lucide icons
 * actually referenced by the root promotional website HTML/JS pages.
 *
 * Usage:
 *   node dev-tools/build_promo_lucide_subset.cjs          # regenerate bundle
 *   node dev-tools/build_promo_lucide_subset.cjs --check  # fail if stale or missing icons
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_BUNDLE = path.join(ROOT, 'vendor', 'lucide-1.31.0.umd.min.js');
const OUTPUT_BUNDLE = path.join(ROOT, 'vendor', 'lucide-promo-subset.min.js');

const PROMO_FILES = [
    'index.html', 'about.html', 'principles.html', 'tour.html', 'tools.html',
    'features.html', 'library.html', 'students.html', 'remediation.html',
    'ways-to-use.html', 'for-districts.html', 'calculator.html', 'manuals.html',
    'feedback.html', 'accessibility_demo.html', 'whitepaper.html',
    'site.js', 'tool-finder.js', 'manuals.js', 'feedback.js'
];

function toPascal(kebab) {
    return kebab.split('-').map((part) => part ? part[0].toUpperCase() + part.slice(1) : '').join('');
}

function collectUsedIcons() {
    const used = new Set();
    for (const rel of PROMO_FILES) {
        const full = path.join(ROOT, rel);
        if (!fs.existsSync(full)) continue;
        const text = fs.readFileSync(full, 'utf8');
        for (const match of text.matchAll(/data-lucide=["'`]([a-z0-9-]+)["'`]/g)) {
            used.add(match[1]);
        }
        // Catch dynamic icon property literals used to build data-lucide="..." (e.g. TUTORIALS in index.html).
        for (const match of text.matchAll(/\bicon\s*:\s*['"]([a-z0-9-]+)['"]/g)) {
            used.add(match[1]);
        }
    }
    return [...used].sort();
}

function buildBundle() {
    const lucide = require(SOURCE_BUNDLE);
    const names = collectUsedIcons();
    const icons = {};
    const missing = [];

    for (const name of names) {
        const pascal = toPascal(name);
        if (lucide.icons && lucide.icons[pascal]) {
            icons[name] = lucide.icons[pascal];
        } else {
            missing.push(name);
        }
    }

    if (missing.length) {
        throw new Error('Unknown Lucide icon names referenced by promo pages: ' + missing.join(', '));
    }

    const iconsJson = JSON.stringify(icons);
    const code =
`/*! Lucide Promo Subset (extracted from lucide@1.31.0, ISC License) — ${names.length} icons. Generated by dev-tools/build_promo_lucide_subset.cjs */
(function(g){'use strict';var NS='http://www.w3.org/2000/svg',I=${iconsJson},D={xmlns:NS,width:24,height:24,viewBox:'0 0 24 24',fill:'none',stroke:'currentColor','stroke-width':2,'stroke-linecap':'round','stroke-linejoin':'round'};function mk(n,el,extra){var nodes=I[n];if(!nodes)return null;var svg=document.createElementNS(NS,'svg'),k,i,at,cls=['lucide','lucide-'+n];for(k in D)svg.setAttribute(k,String(D[k]));if(extra)for(k in extra)svg.setAttribute(k,String(extra[k]));if(el&&el.attributes){for(i=0;i<el.attributes.length;i++){at=el.attributes[i];if(at.name==='class'){if(at.value)cls.push(at.value);}else{svg.setAttribute(at.name,at.value);}}}svg.setAttribute('class',cls.join(' ').trim());if(!svg.hasAttribute('aria-label')&&!svg.hasAttribute('aria-labelledby')&&!svg.hasAttribute('title'))svg.setAttribute('aria-hidden','true');for(i=0;i<nodes.length;i++){var t=nodes[i][0],p=nodes[i][1],c=document.createElementNS(NS,t);for(k in p)c.setAttribute(k,String(p[k]));svg.appendChild(c);}return svg;}function createIcons(o){o=o||{};var r=o.root||document,a=o.nameAttr||'data-lucide',ex=o.attrs||null,list=r.querySelectorAll('['+a+']');for(var i=0;i<list.length;i++){var el=list[i];if(el.tagName&&el.tagName.toLowerCase()==='svg')continue;var nm=el.getAttribute(a),svg=mk(nm,el,ex);if(svg&&el.parentNode)el.parentNode.replaceChild(svg,el);}}g.lucide={icons:I,createIcons:createIcons};})(typeof globalThis!=='undefined'?globalThis:window);
`;
    return { code, count: names.length, names };
}

function main() {
    const checkOnly = process.argv.includes('--check');
    const { code, count } = buildBundle();
    if (checkOnly) {
        if (!fs.existsSync(OUTPUT_BUNDLE)) {
            console.error('PROMO LUCIDE SUBSET CHECK: FAIL (missing vendor/lucide-promo-subset.min.js)');
            process.exit(1);
        }
        const current = fs.readFileSync(OUTPUT_BUNDLE, 'utf8');
        if (current !== code) {
            console.error('PROMO LUCIDE SUBSET CHECK: FAIL (vendor/lucide-promo-subset.min.js is out of sync; run node dev-tools/build_promo_lucide_subset.cjs)');
            process.exit(1);
        }
        console.log(`PROMO LUCIDE SUBSET CHECK: PASS (${count} icons, ${(Buffer.byteLength(code) / 1024).toFixed(1)} KB)`);
        return;
    }
    fs.writeFileSync(OUTPUT_BUNDLE, code, 'utf8');
    console.log(`Built vendor/lucide-promo-subset.min.js (${count} icons, ${(Buffer.byteLength(code) / 1024).toFixed(1)} KB)`);
}

if (require.main === module) main();
module.exports = { collectUsedIcons, buildBundle };
