import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import checks from '../dev-tools/authored_batch_originality_checks.cjs';

const { originalityFindings, topFrame, keyLongestShare } = checks;
const authoredDir = path.join(import.meta.dirname, '..', 'dev-tools', 'authored');
const manifestPath = path.join(authoredDir, 'test_prep_independent_additions_manifest.json');
const baselinePath = path.join(import.meta.dirname, 'fixtures', 'test_prep_authored_length_baseline.json');

function readBatch(file) {
  return JSON.parse(fs.readFileSync(path.join(authoredDir, file), 'utf8'));
}

function stagedBatchFiles() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const registered = new Set();
  for (const entries of Object.values(manifest.packs)) {
    for (const entry of entries) for (const file of entry.files) registered.add(file);
  }
  return fs.readdirSync(authoredDir)
    .filter((name) => /_batch\d+\.json$/.test(name) && !registered.has(name))
    .sort();
}

function registeredBatchFiles() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const out = [];
  for (const entries of Object.values(manifest.packs)) {
    for (const entry of entries) out.push(...entry.files);
  }
  return out.sort();
}

// A gate that has only ever seen healthy input is an untested gate. These
// calibrate in both directions against real corpus files: the staged batches
// are the known-bad fixture, the registered ones are the known-good.
describe('authored-batch originality gate', () => {
  it('rejects every staged batch that was built to defeat the structural checks', () => {
    const staged = stagedBatchFiles();
    // 15 packs x 3 batches = 4,500 items. If this count moves, someone either
    // registered a staged batch or added new ones; both deserve a look rather
    // than a silent pass.
    expect(staged.length).toBe(45);
    const missed = staged.filter((file) => originalityFindings(readBatch(file)).length === 0);
    expect(missed, 'staged batches the gate failed to flag').toEqual([]);
  }, 120_000);

  it('names the specific defect rather than failing vaguely', () => {
    const findings = originalityFindings(readBatch('speech_language_pathology_5331_batch3.json'));
    expect(findings.join(' | ')).toMatch(/templated prompts/);
    expect(findings.join(' | ')).toMatch(/boilerplate answer options/);
    expect(findings.join(' | ')).toMatch(/templated rationales/);
  }, 120_000);

  it('does not fire on the template checks for genuinely authored registered batches', () => {
    // Length is excluded here only to keep this assertion about templates. The
    // recorded length debt was cleared on 2026-08-17 and the baseline is now
    // empty, so the length check below runs against the real 45% limit for every
    // registered batch. The TEMPLATE checks have no legacy and must be clean
    // everywhere, including across the remediated distractors.
    const offenders = [];
    for (const file of registeredBatchFiles()) {
      const items = readBatch(file);
      const template = originalityFindings(items).filter((finding) => !/answer-length tell/.test(finding));
      if (template.length) offenders.push(file + ': ' + template.join('; '));
    }
    expect(offenders).toEqual([]);
  }, 120_000);

  it('separates authored from generated by a wide margin, not a hair', () => {
    const good = topFrame(readBatch('audiology_5343_batch3.json'), (item) => item.prompt).share;
    const bad = topFrame(readBatch('speech_language_pathology_5331_batch3.json'), (item) => item.prompt).share;
    expect(good).toBeLessThan(0.10);
    expect(bad).toBeGreaterThan(0.90);
  }, 120_000);

  it('ratchets recorded length debt down only, and admits no new entries', () => {
    const baseline = JSON.parse(fs.readFileSync(baselinePath, 'utf8'));
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    const packIds = {};
    for (const stem of Object.keys(manifest.packs)) {
      packIds[stem] = JSON.parse(fs.readFileSync(
        path.join(import.meta.dirname, '..', 'test_prep', stem + '_pack.json'), 'utf8')).id;
    }
    const worsened = [];
    for (const [stem, entries] of Object.entries(manifest.packs)) {
      for (const entry of entries) {
        const items = entry.files.flatMap((file) => readBatch(file));
        const key = packIds[stem] + '/' + entry.id;
        const recorded = baseline.batches[key];
        const share = keyLongestShare(items).share;
        if (recorded === undefined) {
          // Not debt-listed, so it must satisfy the real limit.
          if (share > checks.MAX_KEY_LONGEST_SHARE) worsened.push(key + ' exceeds the limit at ' + share.toFixed(3));
        } else if (share > recorded + 0.005) {
          worsened.push(key + ' rose from ' + recorded + ' to ' + share.toFixed(3));
        }
      }
    }
    expect(worsened).toEqual([]);
  }, 30_000);
});
