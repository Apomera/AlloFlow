const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const root = 'C:/Users/cabba/OneDrive/Desktop/UDL-Tool-Updated';
const reportDir = path.join(root, 'reports/universe-flight-2026-09-29/neighbor-cards/unit');
const runLabel = process.argv[2] || 'inspector';
if (!/^[a-z0-9-]+$/.test(runLabel)) throw new Error('Invalid run label.');
fs.mkdirSync(reportDir, { recursive: true });
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const sourceFiles = { renderer: path.join(root, 'stem_lab/universe_flight_scene.js'), ui: path.join(root, 'stem_lab/stem_tool_universe.js'), test: path.join(root, 'tests/universe_flight_inspector.test.js') };
const pins = () => Object.fromEntries(Object.entries(sourceFiles).map(([key, file]) => [key, hash(file)]));
const before = pins();
const reportFile = path.join(reportDir, runLabel + '-results.json');
const summaryFile = path.join(reportDir, runLabel + '-summary.json');
const logFile = path.join(reportDir, runLabel + '.log');
for (const file of [reportFile, summaryFile, logFile]) if (fs.existsSync(file)) throw new Error('Choose a fresh run label.');
const output = fs.openSync(logFile, 'w');
const temp = path.join(__dirname, 'unit-temp'); fs.mkdirSync(temp, { recursive: true });
const args = ['node_modules/vitest/vitest.mjs', 'run', '--config', path.join(__dirname, 'inspector-node.config.mjs'), '--configLoader=native', '--pool=forks', '--maxWorkers=1', '--reporter=verbose', '--reporter=json', '--outputFile=' + reportFile];
const child = spawn(process.execPath, args, { cwd: root, windowsHide: true, env: { ...process.env, TEMP: temp, TMP: temp, NODE_OPTIONS: '--max-old-space-size=256 --max-semi-space-size=4' }, stdio: ['ignore', output, output] });
fs.closeSync(output);
child.on('error', error => { console.error(error); process.exitCode = 1; });
child.on('exit', code => {
  const report = fs.existsSync(reportFile) ? JSON.parse(fs.readFileSync(reportFile, 'utf8')) : {};
  const after = pins();
  const summary = { exitCode: code, tests: report.numTotalTests, passed: report.numPassedTests, failed: report.numFailedTests, before, after, unchanged: JSON.stringify(before) === JSON.stringify(after) };
  fs.writeFileSync(summaryFile, JSON.stringify(summary, null, 2) + '\n');
  for (const name of ['inspector-node.config.mjs', 'run-inspector-unit.cjs', 'inspector-counts.json', 'maintain-inspector-test.cjs', 'baseline-inspector.test.js']) fs.copyFileSync(path.join(__dirname, name), path.join(reportDir, name));
  fs.copyFileSync(sourceFiles.test, path.join(reportDir, 'executed-inspector.test.js'));
  console.log(JSON.stringify(summary));
  process.exitCode = code || (summary.unchanged ? 0 : 1);
});
