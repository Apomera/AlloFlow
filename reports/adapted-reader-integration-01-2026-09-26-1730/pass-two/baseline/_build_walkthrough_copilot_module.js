#!/usr/bin/env node
/**
 * Build walkthrough_copilot_cdn_module.js from walkthrough_copilot_source.jsx.
 *
 * Mirrors _build_udl_walkthrough_module.js: esbuild JSX -> createElement, IIFE
 * wrapper with an a11y live region, writes the module and syncs it to
 * desktop/web-app/public/.
 *
 * Difference from the other tool builds: this module BUNDLES the three logic
 * files verbatim (core, fixtures, scenarios) ahead of the panel. They are
 * already self-registering IIFEs, and the unit tests exercise those same files
 * directly, so bundling rather than reimplementing keeps the CDN build and the
 * tested logic from drifting apart.
 *
 * The output filename is deliberately NOT walkthrough_copilot_module.js: that
 * name belongs to the hand-written core. Overwriting it would clobber the file
 * the tests and the standalone page load.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'walkthrough_copilot_source.jsx');
const CORE = path.join(ROOT, 'walkthrough_copilot_module.js');
const FIXTURES = path.join(ROOT, 'walkthrough_copilot_fixtures.js');
const SCENARIOS = path.join(ROOT, 'walkthrough_copilot_scenarios.js');
const SCRIPT_SOURCE = path.join(ROOT, 'walkthrough_script_source_module.js');
const OUTPUT = path.join(ROOT, 'walkthrough_copilot_cdn_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'walkthrough_copilot_cdn_module.js');
const TMP = path.join(ROOT, '_tmp_walkthrough_copilot_entry.jsx');

for (const required of [SOURCE, CORE, FIXTURES, SCENARIOS, SCRIPT_SOURCE]) {
    if (!fs.existsSync(required)) { console.error('Not found:', required); process.exit(1); }
}

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__wcopExports = { WalkthroughCopilotPanel, WcopSuggestion, WcopIntro, WcopSetup, WcopAffirm, WcopManualEntry, WcopFlag, WcopFrozenNotes, WCOP_STAGES, WCOP_STEPS, WCOP_ADVISORY_QUESTIONS };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling walkthrough_copilot_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch (_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__wcopExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const logic = [CORE, FIXTURES, SCENARIOS, SCRIPT_SOURCE]
    .map((file) => '/* bundled from ' + path.basename(file) + ' */\n' + fs.readFileSync(file, 'utf-8').trim())
    .join('\n\n');

const outputCode = `/**
 * AlloFlow Walkthrough Copilot Module
 *
 * Auto-generated by _build_walkthrough_copilot_module.js - DO NOT EDIT MANUALLY.
 * Source: walkthrough_copilot_source.jsx
 * Bundled logic: walkthrough_copilot_module.js, walkthrough_copilot_fixtures.js,
 *                walkthrough_copilot_scenarios.js
 *
 * Formative walkthrough and coaching support. Turns shorthand observation notes
 * into evidence-based coaching feedback the observer writes and approves. Never
 * assigns a rating, calculates a summative score, or makes an employment
 * recommendation. Practice scenarios are synthetic and ship their own
 * suggestions, so no AI provider is contacted.
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.WalkthroughCopilot
      && window.AlloModules.WalkthroughCopilot.WalkthroughCopilotPanel) {
    console.log('[CDN] WalkthroughCopilot already loaded, skipping');
    return;
  }
  (function() {
    if (document.getElementById('allo-live-wcop')) return;
    var liveRegion = document.createElement('div');
    liveRegion.id = 'allo-live-wcop';
    liveRegion.setAttribute('aria-live', 'polite');
    liveRegion.setAttribute('aria-atomic', 'true');
    liveRegion.setAttribute('role', 'status');
    liveRegion.className = 'sr-only';
    liveRegion.style.cssText = 'position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);border:0';
    document.body.appendChild(liveRegion);
  })();

${logic}

  var React = window.React;
  if (!React) { console.error('[WalkthroughCopilot] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  // The bundled core already registered its API under this key. Merge rather
  // than replace, so the panel and the core logic share one namespace and
  // neither clobbers the other.
  var wcopCoreApi = window.AlloModules.WalkthroughCopilot || {};
  var wcopMerged = {};
  Object.keys(wcopCoreApi).forEach(function(k) { wcopMerged[k] = wcopCoreApi[k]; });
  wcopMerged.WalkthroughCopilotPanel = WalkthroughCopilotPanel;
  wcopMerged._testing = {
    WcopSuggestion: WcopSuggestion,
    WcopIntro: WcopIntro,
    WcopSetup: WcopSetup,
    WcopAffirm: WcopAffirm,
    WcopManualEntry: WcopManualEntry,
    WcopFlag: WcopFlag,
    WcopFrozenNotes: WcopFrozenNotes,
    WCOP_STAGES: WCOP_STAGES,
    WCOP_STEPS: WCOP_STEPS,
    WCOP_ADVISORY_QUESTIONS: WCOP_ADVISORY_QUESTIONS
  };
  window.AlloModules.WalkthroughCopilot = wcopMerged;
  console.log('[CDN] WalkthroughCopilot loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[WalkthroughCopilot] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
