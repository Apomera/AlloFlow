test.afterEach(async ({ page }) => { await harness.destroy(page); });
const setRange = async (page: any, id: string, value: number) => page.locator(id).evaluate((input: HTMLInputElement, v: number) => {
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, String(v)); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true }));
}, value);

test('primer links to a real rendered archipelago; practice and private futures preserve both expeditions', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1100 });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await harness.mount(page, { evoLab: { view: 'livingIsland' } });
  await expect(page.locator('[data-primer-context]')).toContainText('fictional organisms, not rabbits');
  const primer = await page.evaluate(() => (window as any).StemLab.evoIslandModel.create(2026));
  await harness.mount(page, { evoLab: { view: 'livingIsland', island: primer } });
  await page.getByRole('button', { name: 'Explore Island Connections · advanced →', exact: true }).click();
  await expect(page.locator('[data-archipelago-scene]')).toHaveAttribute('data-archipelago-scene', 'ready');
  await expect(page.locator('[data-arch-deme]')).toHaveCount(3);
  const contexts = (await harness.glContexts(page)).filter(c => c.connected && !c.lost); expect(contexts).toHaveLength(1); expect(contexts[0].draws).toBeGreaterThan(0);
  expect((await harness.glScene(page))?.meshes).toBeGreaterThan(100);
  await page.screenshot({ path: report + '/archipelago-overview-desktop.png' });
  await page.getByRole('button', { name: 'Advance one generation', exact: true }).click();
  const original = await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.archipelago));
  const first = JSON.parse(original);
  await setRange(page, '#ea-probe-shell', .9); await setRange(page, '#ea-probe-beak', .8);
  const probability = await page.locator('[data-probe-opening]').getAttribute('data-probe-opening');
  expect(Number(probability)).toBeCloseTo(.08 + .84 / (1 + Math.exp(1)), 10);
  await page.getByRole('button', { name: 'Test island connections', exact: true }).click();
  await expect(page.locator('[data-future="a"]')).toContainText('Isolated islands'); await expect(page.locator('[data-future="b"]')).toContainText('Connected islands');
  expect(await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.archipelago))).toBe(original);
  expect(await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.island))).toBe(JSON.stringify(primer));
  await page.locator('#ea-prediction').fill('Isolation may reduce variation within islands.');
  await page.locator('#ea-explanation').fill('Compare both the marker and inherited traits; this is one fictional run.');
  await page.getByRole('button', { name: 'Save island evidence to journal', exact: true }).click();
  const note = await page.evaluate(() => JSON.parse(localStorage.getItem('evoLab.progress.v1')!).notes.archipelagoEvidence.text);
  expect(note).toContain('Private comparison G1→G6: migration'); expect(note).toContain('My prediction: Isolation may reduce variation within islands.'); expect(note).toContain('genome-wide');
  await page.locator('[data-arch-island="2"]').click();
  await page.locator('.ea-scene-wrap').screenshot({ path: report + '/archipelago-mist-3d.png' });
  await page.getByRole('button', { name: '← Living Island primer', exact: true }).click();
  await page.getByRole('button', { name: 'Explore Island Connections · advanced →', exact: true }).click();
  await expect(page.locator('#ea-prediction')).toHaveValue('Isolation may reduce variation within islands.');
  await expect(page.locator('#ea-explanation')).toHaveValue('Compare both the marker and inherited traits; this is one fictional run.');
  await page.getByRole('button', { name: 'Advance one generation', exact: true }).click();
  const next = await page.evaluate(() => (window as any).__toolData.evoLab.archipelago);
  const expected = await page.evaluate(w => (window as any).StemLab.evoArchipelagoModel.step(w), first);
  expect(next).toEqual(expected); expect(errors).toEqual([]);
});

test('recorded migrants and actual parent copies remain correct while navigating history and queued rainfall', async ({ page }) => {
  await harness.mount(page, { evoLab: { view: 'archipelago' } });
  const fixture = await page.evaluate(() => {
    const m = (window as any).StemLab.evoArchipelagoModel; let w = m.create(21); w.settings.migration = .4; w.settings.mutation = 0;
    for (let i = 0; i < 3; i++) w = m.step(w); return w;
  });
  await harness.mount(page, { evoLab: { view: 'archipelago', archipelago: fixture } });
  const round = fixture.history[3].round;
  await expect(page.locator('[data-migrant-arrivals]')).toHaveText(String(round.migrants.length));
  await expect(page.locator('[data-migrant-parents]')).toHaveText(String(round.migrants.filter((m: any) => m.gametes > 0).length));
  const migrant = round.migrants.find((m: any) => m.gametes > 0);
  await page.locator('[data-migrant="' + migrant.id + '"]').click();
  await expect(page.locator('[data-arch-inspector]')).toHaveAttribute('data-arch-inspector', String(migrant.id));
  await expect(page.locator('[data-arch-inspector]')).toContainText(migrant.gametes + ' gametes passed to actual offspring');
  await expect(page.locator('[data-arch-inspector]')).toContainText('earlier cohort');
  const original = await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.archipelago));
  await page.getByRole('button', { name: 'Visit this individual’s birth generation', exact: true }).click();
  await expect(page.locator('[data-arch-generation]')).toHaveText('G2');
  expect(await page.evaluate(() => JSON.stringify((window as any).__toolData.evoLab.archipelago))).toBe(original);
  await page.getByRole('button', { name: 'Return to present', exact: true }).click();
  await page.locator('[data-arch-island="0"]').click();
  const child = fixture.history[3].demes[0].birds[0];
  await page.selectOption('#ea-resident', String(child.id));
  await expect(page.locator('[data-arch-inspector]')).toContainText('Two actual parents');
  for (const id of child.parents) await expect(page.locator('[data-arch-inspector]').getByRole('button', { name: new RegExp('^#' + id + ' ·') })).toHaveCount(1);
  await setRange(page, '#ea-generation', 1);
  const before = await page.locator('[data-arch-diversity]').textContent();
  await setRange(page, '#ea-rain-0', .9);
  await expect(page.locator('[data-arch-generation]')).toHaveText('G1');
  expect(await page.locator('[data-arch-diversity]').textContent()).toBe(before);
  const queued = await page.evaluate(() => (window as any).__toolData.evoLab.archipelago);
  expect(queued.history).toEqual(fixture.history); expect(queued.rng).toBe(fixture.rng); expect(queued.settings.rainfall[0]).toBe(.9);
  await page.locator('summary').filter({ hasText: /^Explore island geography$/ }).click();
  await page.locator('.ea-map').screenshot({ path: report + '/archipelago-geography.png' });
});

test('phone users can investigate founder samples with keyboard controls and no WebGL', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(() => { const get = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(type: string, ...args: any[]) { return type.includes('webgl') ? null : (get as any).call(this, type, ...args); } as any; });
  await harness.mount(page, { evoLab: { view: 'archipelago' } }, undefined, { expectCanvas: false });
  await page.evaluate(() => { document.getElementById('wrap')!.style.width = '100%'; document.body.style.padding = '0'; });
  await expect(page.locator('[data-archipelago-scene]')).toHaveAttribute('data-archipelago-scene', 'fallback');
  await page.locator('summary').filter({ hasText: /^Start a different expedition$/ }).click();
  await page.getByRole('button', { name: 'New seed · six founders on Mist', exact: true }).click();
  await expect(page.locator('[data-arch-deme="2"] td').first()).toHaveText('6');
  await page.locator('#ea-probe-shell').focus(); await page.keyboard.press('Home');
  await expect(page.locator('#ea-probe-shell')).toHaveValue('0');
  await page.getByRole('button', { name: 'Advance one generation', exact: true }).click();
  await expect(page.locator('[data-arch-deme="2"] td').first()).toHaveText('24');
  await expect(page.locator('[data-migrant-arrivals]')).toHaveText('0');
  await page.getByLabel('Trait-dependent breeding weights', { exact: true }).uncheck();
  await expect(page.locator('[data-probe-bird-weight]')).toHaveText('1.000'); await expect(page.locator('[data-probe-plant-weight]')).toHaveText('1.000');
  await page.addScriptTag({ path: 'node_modules/axe-core/axe.min.js' });
  const violations = await page.evaluate(async () => (window as any).axe.run('[data-archipelago]', { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }).then((r: any) => r.violations.map((v: any) => ({ id: v.id, targets: v.nodes.map((n: any) => n.target) }))));
  expect(violations).toEqual([]);
  const overflow = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth })); expect(overflow.scroll).toBeLessThanOrEqual(overflow.width + 1);
  await page.setViewportSize({ width: 390, height: 1200 });
  await page.locator('[data-reciprocal-probe]').screenshot({ path: report + '/archipelago-probe-phone.png' });
});
