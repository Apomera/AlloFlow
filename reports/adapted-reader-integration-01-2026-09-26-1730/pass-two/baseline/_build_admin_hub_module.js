#!/usr/bin/env node
/**
 * Build admin_hub_module.js from admin_hub_source.jsx
 * (Leadership Hub — admin tools container shell, Aug 2026.)
 * Mirrors _build_udl_walkthrough_module.js.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'admin_hub_source.jsx');
const OUTPUT = path.join(ROOT, 'admin_hub_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'admin_hub_module.js');
const TMP = path.join(ROOT, '_tmp_admin_hub_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__adminHubExports = { AdminHubPanel };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling admin_hub_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch(_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__adminHubExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow Leadership Hub Module
 * Auto-generated by _build_admin_hub_module.js — DO NOT EDIT MANUALLY.
 * Source: admin_hub_source.jsx
 * Container shell for the admin tool suite (walkthrough, dispro, meetings).
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.AdminHub) {
    console.log('[CDN] AdminHub already loaded, skipping');
    return;
  }
  var React = window.React;
  if (!React) { console.error('[AdminHub] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.AdminHub = { AdminHubPanel: AdminHubPanel, maybeDriveBackup: _adminHubMaybeDriveBackup };
  console.log('[CDN] AdminHub loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[AdminHub] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
