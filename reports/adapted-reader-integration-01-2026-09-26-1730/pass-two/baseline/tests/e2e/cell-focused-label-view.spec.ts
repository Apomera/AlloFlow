import {test,expect} from '@playwright/test';
import {GlHarness} from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_cell.js',toolId:'cell',width:1200,height:1000,appStyles:true});
test.beforeAll(()=>harness.start());test.afterAll(()=>harness.stop());test.afterEach(async({page})=>harness.destroy(page));
for(const width of [320,1200])test('focused labels retain slots and all navigation at '+width,async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});await page.setViewportSize({width,height:1000});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await harness.mount(page,{cell:{mode:'observe',selectedOrganism:'plantcell',paused:true,zoom:3}},undefined,{expectCanvas:false});
 await page.addStyleTag({content:'body{background:#f8fafc}#wrap{width:100%;max-width:1200px;display:block}'});
 const canvas=page.locator('[data-cell-sim-canvas]'),panel=page.locator('[data-cell-explanation-panel]');
 const labels=()=>canvas.evaluate((c:any)=>c._cellSimGetAnatomyLabels());
 await page.locator('[data-cell-anatomy-item="Chloroplast"]').click();
 const full=await labels(),view=await canvas.evaluate((c:any)=>c._cellSimGetObservationView());
 expect(full.length).toBeGreaterThan(3);
 const shape=(b:any)=>({name:b.name,x:b.x,y:b.y,width:b.width,height:b.height});
 const toggle=panel.getByRole('checkbox',{name:'Show only selected label',exact:true});
 await expect(toggle).not.toBeChecked();await toggle.focus();await page.keyboard.press('Space');
 await expect(toggle).toBeChecked();await expect(toggle).toBeFocused();
 await expect.poll(async()=>(await labels()).map((b:any)=>b.name)).toEqual(['Chloroplast']);
 expect(shape((await labels())[0])).toEqual(shape(full.find((b:any)=>b.name==='Chloroplast')));
 expect(await canvas.evaluate((c:any)=>c._cellSimGetObservationView())).toEqual(view);
 await panel.screenshot({path:'reports/cell-structure-explorer/focused-panel-'+width+'.png'});
 await panel.getByRole('button',{name:'Back to microscope'}).click();
 await page.locator('[data-cell-stage]').screenshot({path:'reports/cell-structure-explorer/focused-dish-'+width+'.png'});
 const hidden=full.find((b:any)=>b.name!=='Chloroplast'),rect=(await canvas.boundingBox())!;
 await page.mouse.move(rect.x+hidden.x+hidden.width/2,rect.y+hidden.y+hidden.height/2);
 expect((await labels()).some((b:any)=>b.hovered&&b.name===hidden.name)).toBe(false);
 await panel.getByRole('button',{name:'Next structure',exact:true}).click();
 await expect.poll(async()=>(await labels())[0]?.name).toBe('Nucleus');
 expect(shape((await labels())[0])).toEqual(shape(full.find((b:any)=>b.name==='Nucleus')));
 await panel.getByRole('combobox',{name:'Jump to structure'}).selectOption('Endoplasmic Reticulum');
 await expect.poll(async()=>(await labels()).map((b:any)=>b.name)).toEqual(['Endoplasmic Reticulum']);
 await toggle.uncheck();await expect.poll(async()=>(await labels()).length).toBe(full.length);
 expect((await labels()).map(shape)).toEqual(full.map(shape));
 await toggle.check();await panel.getByRole('button',{name:'Close structure explanation'}).click();
 await expect.poll(async()=>(await labels()).length).toBe(full.length);
 await canvas.evaluate((c:any)=>c._cellSimSelectOrganism('amoeba',true));
 await expect.poll(async()=>(await labels()).length).toBeGreaterThan(1);
 const amoebaCount=(await labels()).length;
 await panel.getByRole('combobox',{name:'Jump to structure'}).selectOption('Nucleus');
 await expect(toggle).toBeChecked();await expect.poll(async()=>(await labels()).length).toBe(1);
 await toggle.uncheck();await expect.poll(async()=>(await labels()).length).toBe(amoebaCount);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect(errors).toEqual([]);
});
test('saved focused-label preference does not hide play structures',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});await page.setViewportSize({width:390,height:1000});
 await harness.mount(page,{cell:{mode:'play',focusSelectedLabel:true,playAsOrganism:'plantcell',selectedOrganism:'plantcell',paused:true,showPlayInstructions:false,playMission:{organismId:'plantcell',startSuccess:0,predictionSkipped:true},_cellExt:{successByOrganism:{plantcell:0},tutorialsSeen:{plantcell:true}}}},undefined,{expectCanvas:false});
 await page.addStyleTag({content:'#wrap{width:100%;display:block}'});
 const canvas=page.locator('[data-cell-sim-canvas]'),panel=page.locator('[data-cell-explanation-panel]');
 await expect.poll(()=>canvas.evaluate((c:any)=>c._cellSimGetAnatomyLabels().length)).toBeGreaterThan(1);
 const count=await canvas.evaluate((c:any)=>c._cellSimGetAnatomyLabels().length);
 await panel.getByRole('combobox',{name:'Jump to structure'}).selectOption('Chloroplast');
 expect(await canvas.evaluate((c:any)=>c._cellSimGetAnatomyLabels().length)).toBe(count);
 await expect(panel.getByRole('checkbox',{name:'Show only selected label'})).toHaveCount(0);
});
