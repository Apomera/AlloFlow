#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'view_directions_result_source.jsx');
const OUTPUT = path.join(ROOT, 'view_directions_result_module.js');
const PUBLIC = path.join(ROOT, 'desktop', 'web-app', 'public', 'view_directions_result_module.js');

function compileJsx(source) {
  const result = babel.transformSync(source, {
    plugins: ['@babel/plugin-transform-react-jsx'],
    configFile: false,
    babelrc: false,
  });
  return result.code;
}

function buildDirectionsResultModule(source) {
  const compiled = compileJsx(source);
  return `/**
 * AlloFlow Directions Result View Module
 * Auto-generated by _build_view_directions_result_module.js — DO NOT EDIT.
 * Source: view_directions_result_source.jsx
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.DirectionsResult) {
    console.log('[CDN] DirectionsResult already loaded, skipping');
    return;
  }
  var React = window.React;
  if (!React) { console.error('[DirectionsResult] React not found on window'); return; }

  var _lazyIcon = function(name) {
    return function(props) {
      var Icon = window.AlloIcons && window.AlloIcons[name];
      return Icon ? React.createElement(Icon, props) : null;
    };
  };
  var ArrowRight = _lazyIcon('ArrowRight');
  var CheckCircle2 = _lazyIcon('CheckCircle2');
  var ClipboardList = _lazyIcon('ClipboardList');

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.DirectionsResult = { DirectionsResultView: DirectionsResultView };
  console.log('[CDN] DirectionsResult loaded');
})();
`;
}

module.exports = { buildDirectionsResultModule };

if (require.main === module) {
  if (!fs.existsSync(SOURCE)) {
    console.error('Source not found:', SOURCE);
    process.exit(1);
  }
  const output = buildDirectionsResultModule(fs.readFileSync(SOURCE, 'utf8'));
  fs.writeFileSync(OUTPUT, output, 'utf8');
  fs.mkdirSync(path.dirname(PUBLIC), { recursive: true });
  fs.writeFileSync(PUBLIC, output, 'utf8');
  console.log('Built view_directions_result_module.js and public mirror (' + Buffer.byteLength(output) + ' bytes)');
}
