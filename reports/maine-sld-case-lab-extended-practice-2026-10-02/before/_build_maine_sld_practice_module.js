#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');
const ROOT = __dirname;
const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8');
const data = JSON.parse(read('maine_sld_case_data.json'));
if (data.scoreRows.length !== 52 || data.cases.length !== 3 || data.formSteps.length !== 9 || data.sources.length < 3) throw new Error('Incomplete reviewed case data.');
const compiled = esbuild.transformSync(read('maine_sld_practice_source.jsx'), { loader: 'jsx', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment', target: 'es2020', charset: 'utf8', legalComments: 'none' }).code;
const output = `/* AlloFlow Maine SLD Case Lab. Generated by _build_maine_sld_practice_module.js. */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.MaineSldPractice) return;
  var React = window.React;
  if (!React) throw new Error('Maine SLD Case Lab requires React.');
  ${read('maine_sld_practice_core.js')}
  const MAINE_SLD_CASE_DATA = ${JSON.stringify(data)};
  ${compiled}
  window.AlloModules = window.AlloModules || {};
  window.AlloModules.MaineSldPractice = { MaineSldPracticePanel: MaineSldPracticePanel, _testing: { data: MAINE_SLD_CASE_DATA, Core: window.AlloSldPracticeCore } };
})();
`;
const file = 'maine_sld_practice_module.js';
fs.writeFileSync(path.join(ROOT, file), output);
for (const dir of ['desktop/web-app/public', 'desktop/app-build', 'desktop/web-app/build']) {
  const resolved = path.join(ROOT, dir);
  if (fs.existsSync(resolved)) fs.writeFileSync(path.join(resolved, file), output);
}
console.log(`Built ${file}: ${data.scoreRows.length} results, ${data.cases.length} cases, ${Buffer.byteLength(output)} bytes.`);
