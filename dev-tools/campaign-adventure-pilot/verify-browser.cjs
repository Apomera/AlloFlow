const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {createServer}=require('./server.cjs');
const {build,verifyPreservation}=require('./build.cjs');
const artifacts=path.join(__dirname,'evidence');
async function main(){
  build(true);
  const protectedPaths=Object.keys(JSON.parse(fs.readFileSync(path.join(__dirname,'preservation.json'),'utf8')).files);
  const fingerprint=()=>Object.fromEntries(protectedPaths.map(f=>[f,require('node:crypto').createHash('sha256').update(fs.readFileSync(path.join(__dirname,'../..',f))).digest('hex')]));
  const beforeFiles=fingerprint();
  let historicalPreservation;
  try{historicalPreservation=verifyPreservation();}catch(error){
    if(!process.argv.includes('--behavior-only'))throw error;
    historicalPreservation={status:'baseline drift; behavior checks only',message:error.message};
  }
  fs.mkdirSync(artifacts,{recursive:true});
  const server=createServer({testing:true});await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port;
  let browser;
  const results={base,checkedAt:new Date().toISOString(),historicalPreservation,checks:[],errors:[],screenshots:[]};
  try{
    browser=await chromium.launch({headless:true});
    const context=await browser.newContext({viewport:{width:1365,height:950},reducedMotion:'reduce'});
    const page=await context.newPage();
    page.on('pageerror',error=>results.errors.push(error.message));
    const external=[];
    page.on('request',request=>{if(!request.url().startsWith(base))external.push(request.url());});
    await page.goto(base);await page.getByRole('button',{name:'Begin Watershed Steward',exact:true}).waitFor();
    await page.addScriptTag({url:base+'/vendor/axe.js'});
    const homeAxe=await page.evaluate(async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>v.id);});
    results.axeHome=homeAxe;assert.equal(homeAxe.length,0,'Home accessibility violations');
    assert.equal(await page.evaluate(()=>[...document.querySelectorAll('.card-art')].every(c=>c.firstElementChild.getBoundingClientRect().width>=c.getBoundingClientRect().width-2)),true,'Campaign art does not fill its card');
    await page.evaluate(()=>{
      localStorage.setItem('allo_adventure_save','DO NOT TOUCH ADVENTURE');
      localStorage.setItem('labToolData','DO NOT TOUCH STEM');
      localStorage.setItem('alloflow-adventure-audio-v1','DO NOT TOUCH AUDIO');
    });
    await page.screenshot({path:path.join(artifacts,'field-station.png'),fullPage:true});results.screenshots.push('field-station.png');
    await page.getByRole('button',{name:'Begin Watershed Steward',exact:true}).click();
    await page.locator('[data-action="tech:bufferPlant:forestBuffer"]').click();
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.metrics.find(m=>m.label==='Hours left').value),13);
    await page.locator('[data-action="end-year"]').click();
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.progress),1);
    const saved=await page.evaluate(()=>window.CampaignPilot.snapshot().run);
    await page.reload();await page.getByRole('button',{name:'Resume Watershed Steward',exact:true}).click();
    assert.deepEqual(await page.evaluate(()=>window.CampaignPilot.snapshot().run),saved);
    results.checks.push('Watershed: fieldwork, annual result, reload and exact resume');
    await page.getByText('About this pilot and its isolation checks',{exact:true}).click();
    const before=await page.evaluate(()=>window.CampaignPilot.snapshot().run);
    await page.getByRole('button',{name:'Simulate narrator outage'}).click();
    await page.locator('#narration-status').filter({hasText:'Optional narration unavailable'}).waitFor();
    assert.deepEqual(await page.evaluate(()=>window.CampaignPilot.snapshot().run),before);
    await page.getByRole('button',{name:'Simulate malformed narration'}).click();
    await page.locator('#narration-status').filter({hasText:'Optional narration unavailable'}).waitFor();
    assert.deepEqual(await page.evaluate(()=>window.CampaignPilot.snapshot().run),before);
    await page.getByRole('button',{name:'Use authored narration'}).click();
    await page.getByText('About this pilot and its isolation checks',{exact:true}).click();
    results.checks.push('Narrator outage and malformed response: authored scene remains playable; no state changes');
    await page.screenshot({path:path.join(artifacts,'watershed-review.png'),fullPage:true});results.screenshots.push('watershed-review.png');
    for(let year=1;year<=10;year++){
      await page.locator('[data-action="continue"]').click();
      if(year<10)await page.locator('[data-action="end-year"]').click();
    }
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.ended),true);
    await page.getByRole('button',{name:'Replay the latest year'}).click();
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.phase),'year');
    await page.getByRole('button',{name:'← Field station',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Resume Watershed Steward',exact:true}).count(),2);
    results.checks.push('Watershed: complete ten years; replay creates a separate saved branch');
    await page.getByRole('button',{name:'Begin Grove Journey',exact:true}).click();
    await page.locator('[data-action="offspring"]').click();
    await page.getByLabel('What changed, and what might you try next?').fill('I saw new arrivals, but none are established yet.');
    await page.getByRole('button',{name:'Save field note',exact:true}).click();
    const groveSaved=await page.evaluate(()=>window.CampaignPilot.snapshot().run);
    await page.reload();await page.getByRole('button',{name:'Resume Grove Journey',exact:true}).click();
    assert.deepEqual(await page.evaluate(()=>window.CampaignPilot.snapshot().run),groveSaved);
    await page.locator('[data-action="offspring"]').click();
    await page.screenshot({path:path.join(artifacts,'grove-journey.png'),fullPage:true});results.screenshots.push('grove-journey.png');
    await page.setViewportSize({width:390,height:844});
    await page.addScriptTag({url:base+'/vendor/axe.js'});
    const grovePhoneAxe=await page.evaluate(async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.html)}));});
    results.axeGrovePhone=grovePhoneAxe;assert.equal(grovePhoneAxe.length,0,'Grove phone accessibility violations');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Grove phone overflow');
    await page.screenshot({path:path.join(artifacts,'grove-phone.png'),fullPage:true});results.screenshots.push('grove-phone.png');
    await page.setViewportSize({width:1365,height:950});
    for(let year=2;year<8;year++)await page.locator('[data-action="offspring"]').click();
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.ended),true);
    const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download journal',exact:true}).click();const download=await downloadEvent;
    await download.saveAs(path.join(artifacts,'grove-journal.json'));
    const journal=JSON.parse(fs.readFileSync(path.join(artifacts,'grove-journal.json'),'utf8'));assert.equal(journal.commands.length,8);assert.equal(journal.notes.length,1);
    results.checks.push('Grove: complete eight years, field note, exact resume and downloadable journal');
    await page.addScriptTag({url:base+'/vendor/axe.js'});
    let axe=await page.evaluate(async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({html:n.html,summary:n.failureSummary}))}));});
    results.axeDesktop=axe;assert.equal(axe.length,0,'Desktop accessibility violations');
    await page.getByRole('button',{name:'Replay the latest year'}).click();
    // Delayed narration for an old run must not appear after returning to the station.
    await page.evaluate(()=>window.CampaignPilot.setNarrator(()=>new Promise(resolve=>{window.resolveOldNarration=resolve;})));
    await page.getByRole('button',{name:'← Field station',exact:true}).click();
    await page.evaluate(()=>window.resolveOldNarration?.('STALE NARRATION MUST NOT DISPLAY'));
    await page.getByRole('button',{name:'Begin Watershed Steward',exact:true}).click();
    assert.equal(await page.getByText('STALE NARRATION MUST NOT DISPLAY').count(),0);
    await page.evaluate(()=>window.CampaignPilot.setNarrator(null));
    results.checks.push('Late narration cannot leak into a different run');
    await page.getByRole('button',{name:'Sound off',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Sound on',exact:true}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'Sound on',exact:true}).click();
    results.checks.push('Unmodified Adventure soundscape starts and stops');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(artifacts,'watershed-phone.png'),fullPage:true});results.screenshots.push('watershed-phone.png');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Phone has horizontal overflow');
    // Native keyboard input must reach an actual map control and activate a real decision.
    await page.locator('[data-location="forestBuffer"]').focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator('[data-location="forestBuffer"]').getAttribute('aria-pressed'),'true');
    await page.keyboard.press('Tab');assert.equal(await page.evaluate(()=>document.activeElement.tagName),'BUTTON');
    await page.locator('[data-action="tech:bufferPlant:forestBuffer"]').focus();await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.metrics.find(m=>m.label==='Hours left').value),13);
    axe=await page.evaluate(async()=>{const r=await window.axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({html:n.html,summary:n.failureSummary}))}));});
    results.axePhone=axe;assert.equal(axe.length,0,'Phone accessibility violations');
    results.checks.push('Phone: no horizontal overflow in either campaign; keyboard map selection and decision; home/desktop/phone axe checks');
    const beforeOptional=await page.evaluate(()=>window.CampaignPilot.snapshot().run);
    await page.evaluate(()=>window.CampaignPilot.setNarrator(()=>'<img src=x onerror=alert(1)>'));
    await page.locator('#optional-text').filter({hasText:'<img src=x onerror=alert(1)>'}).waitFor();
    assert.equal(await page.locator('#optional-text img').count(),0);
    assert.deepEqual(await page.evaluate(()=>window.CampaignPilot.snapshot().run),beforeOptional);
    await page.evaluate(()=>window.CampaignPilot.setNarrator(null));
    await page.getByLabel('What changed, and what might you try next?').fill('A draft stays while I inspect another reach.');
    await page.locator('[data-location="riverMainstem"]').click();
    assert.equal(await page.getByLabel('What changed, and what might you try next?').inputValue(),'A draft stays while I inspect another reach.');
    results.checks.push('Optional prose is text-only and cannot change state; note drafts survive inspecting the map');
    await page.evaluate(()=>{window.savedSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new Error('Simulated quota failure');};});
    await page.locator('[data-action="end-year"]').click();
    assert.equal(await page.evaluate(()=>window.CampaignPilot.snapshot().view.phase),'review');
    assert.match(await page.locator('#notice').textContent(),/could not save/);
    await page.evaluate(()=>{Storage.prototype.setItem=window.savedSetItem;});
    results.checks.push('Storage failure preserves the playable in-memory run and shows a recovery message');
    const sentinels=await page.evaluate(()=>['allo_adventure_save','labToolData','alloflow-adventure-audio-v1'].map(k=>[k,localStorage.getItem(k)]));
    assert.deepEqual(sentinels,[['allo_adventure_save','DO NOT TOUCH ADVENTURE'],['labToolData','DO NOT TOUCH STEM'],['alloflow-adventure-audio-v1','DO NOT TOUCH AUDIO']]);
    assert.equal(external.length,0);assert.equal(results.errors.length,0,results.errors.join('\n'));
    results.checks.push('Original save sentinels unchanged; no external requests or browser errors');
    assert.deepEqual(fingerprint(),beforeFiles,'Protected files changed during browser verification');
    results.protectedFilesStableDuringRun=protectedPaths.length;results.ok=true;
  }catch(error){results.ok=false;results.failure=error.stack;throw error;}
  finally{fs.writeFileSync(path.join(artifacts,'browser-results.json'),JSON.stringify(results,null,2)+'\n');await browser?.close();await new Promise(resolve=>server.close(resolve));console.log(JSON.stringify(results,null,2));}
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
