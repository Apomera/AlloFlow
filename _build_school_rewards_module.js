#!/usr/bin/env node
/**
 * Build school_rewards_module.js from school_rewards_source.jsx
 * (School Rewards & Store — Leadership Hub tool, Sep 2026.)
 * Mirrors _build_admin_hub_module.js.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'school_rewards_source.jsx');
const OUTPUT = path.join(ROOT, 'school_rewards_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'school_rewards_module.js');
const TMP = path.join(ROOT, '_tmp_school_rewards_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__schoolRewardsExports = { SchoolRewardsPanel };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling school_rewards_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { stdio: 'inherit', cwd: ROOT });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch(_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__schoolRewardsExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow School Rewards & Store Module
 * Auto-generated by _build_school_rewards_module.js — DO NOT EDIT MANUALLY.
 * Source: school_rewards_source.jsx
 * Leadership Hub tool: launcher, deployment check, and setup checklist for the
 * school-owned Google Workspace rewards repository (apps_script/school_rewards).
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.SchoolRewards) {
    console.log('[CDN] SchoolRewards already loaded, skipping');
    return;
  }
  var React = window.React;
  if (!React) { console.error('[SchoolRewards] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.SchoolRewards = {
    SchoolRewardsPanel: SchoolRewardsPanel,
    _testing: {
      srNormalizePortalUrl: srNormalizePortalUrl,
      srSetupSnippet: srSetupSnippet,
      srParseThresholds: srParseThresholds,
      srReadClassroomRoster: srReadClassroomRoster,
      srRosterTemplateCsv: srRosterTemplateCsv,
      srRecognitionCsv: srRecognitionCsv,
      srRecognitionText: srRecognitionText,
      srHandoffText: srHandoffText,
      srHandoffHtml: srHandoffHtml,
      srHandoffSteps: srHandoffSteps,
      SR_THEME_STYLES: SR_THEME_STYLES,
      SR_FILES: SR_FILES,
      SR_STEP_ORDER: SR_STEP_ORDER,
      SR_PORTAL_URL_KEY: SR_PORTAL_URL_KEY,
      SR_SETUP_KEY: SR_SETUP_KEY
    }
  };
  console.log('[CDN] SchoolRewards loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[SchoolRewards] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
