const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const report=path.resolve('reports/universe-flight-2026-09-29');
(async()=>{
  const browser=await chromium.launch({args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('file:///'+path.join(report,'preview.html').replaceAll('\\','/'));
  await page.waitForFunction(()=>document.querySelector('.uf-transport button')?.disabled===false);
  await page.getByRole('button',{name:'Select destination: Amber star',exact:true}).click();
  const before=await page.locator('.uf-readouts').innerText();
  const radii=[];
  for(const choice of ['1','2','4']){
    await page.locator('#uf-arrival-distance').selectOption(choice);
    radii.push(await page.locator('.uf-plan-readouts dd').first().innerText());
    assert.equal(await page.locator('.uf-readouts').innerText(),before,'Planning does not move the camera');
  }
  assert.deepEqual(radii,['0.6 ly','1.2 ly','2.4 ly']);
  await page.getByRole('button',{name:'Match pace to this trip',exact:true}).click();
  const estimate=await page.locator('.uf-plan-readouts dd').nth(2).innerText();
  assert.match(estimate,/seconds of playback/);
  assert.ok(parseInt(estimate,10)>=40&&parseInt(estimate,10)<=50,'Pace targets roughly 45 playback seconds');
  assert.equal(await page.locator('.uf-readouts').innerText(),before);
  await page.locator('.uf-approach-plan').screenshot({path:path.join(report,'approach-planner-desktop.png')});
  await page.getByRole('button',{name:'Fly to destination',exact:true}).click();
  await page.waitForTimeout(700);
  await page.getByRole('button',{name:'Pause travel',exact:true}).click();
  const progress=await page.getByRole('progressbar',{name:'Guided approach progress'}).getAttribute('value');
  assert.ok(Number(progress)>0);
  assert.equal(await page.locator('#uf-arrival-distance').isDisabled(),true);
  await page.waitForTimeout(300);
  assert.equal(await page.getByRole('progressbar',{name:'Guided approach progress'}).getAttribute('value'),progress);
  await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).click();
  const boxes=await page.evaluate(()=>['.uf-route-progress','.uf-overlay-toggle'].map(s=>{const r=document.querySelector(s).getBoundingClientRect();return {top:r.top,bottom:r.bottom};}));
  assert.ok(boxes[0].bottom<=boxes[1].top,'Fullscreen progress clears overlay controls');
  await page.locator('.uf-stage').screenshot({path:path.join(report,'approach-progress-fullscreen.png')});
  await page.getByRole('button',{name:'Hide overlay',exact:true}).click();
  assert.equal(await page.locator('.uf-route-progress').isVisible(),false);
  await page.getByRole('button',{name:'Show overlay',exact:true}).click();
  await page.getByRole('button',{name:'Toggle full screen for the 3D view'}).click();
  await page.getByRole('button',{name:'End guided approach',exact:true}).click();
  assert.equal(await page.locator('#uf-arrival-distance').isDisabled(),false);
  await page.locator('#uf-speed').evaluate(input=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'100');input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true}));});
  await page.getByRole('button',{name:'Fly to destination',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.uf-arrival-message'),{},{timeout:15000});
  assert.equal(await page.locator('.uf-transport button').first().innerText(),'Start travel');
  assert.equal(await page.locator('#uf-target-info .uf-target-readouts dd').first().innerText(),'2.4 ly');
  assert.match(await page.locator('.uf-plan-readouts dd').nth(2).innerText(),/Already within/);
  const arrivedReadout=await page.locator('.uf-readouts').innerText();
  await page.getByRole('button',{name:'Fly to destination',exact:true}).click();
  assert.match(await page.locator('.uf-arrival-message').innerText(),/Already within this viewing distance/);
  assert.equal(await page.locator('.uf-readouts').innerText(),arrivedReadout,'An already-reached approach does not move the camera');
  await page.setViewportSize({width:320,height:800});
  await page.locator('.uf-approach-plan').screenshot({path:path.join(report,'approach-planner-phone.png')});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(report,'approach-check.json'),JSON.stringify({errors,radii,estimate,checks:['stationary planning','pace match','progress','pause','fullscreen','clean view','cancel','wide arrival','mobile layout']},null,2));
  await browser.close();console.log('Approach planner checks passed.');
})().catch(e=>{console.error(e);process.exit(1);});
