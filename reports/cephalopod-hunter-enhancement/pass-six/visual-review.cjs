const fs=require('fs'),path=require('path'),{chromium}=require('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:1100}}),errors=[];
    page.setDefaultTimeout(90000);
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
    const url=fs.readFileSync(path.join(__dirname,'../preview-url.txt'),'utf8').trim();
    await page.goto(url+'?species=humboldtSquid&mode=observe');
    const canvas=page.locator('canvas[role=application]');
    await canvas.waitFor();
    await page.waitForFunction(()=>parseInt(document.querySelector('[data-hud=time]')?.textContent||'0')>=2);
    await page.getByRole('button',{name:'Inspect [F]',exact:true}).click();
    await page.getByRole('button',{name:'Anatomy labels',exact:true}).click();
    await page.waitForTimeout(800);
    await canvas.screenshot({path:path.join(__dirname,'squid-profile.png')});
    await page.getByRole('button',{name:'Orbit right',exact:true}).click();
    await page.getByRole('button',{name:'Higher',exact:true}).click();
    await page.waitForTimeout(700);
    await canvas.screenshot({path:path.join(__dirname,'squid-three-quarter.png')});
    await page.getByRole('button',{name:'Closer',exact:true}).click();
    await page.getByRole('button',{name:'Closer',exact:true}).click();
    await page.waitForTimeout(700);
    await canvas.screenshot({path:path.join(__dirname,'squid-eye-detail.png')});
    for(let i=0;i<10;i++)await page.getByRole('button',{name:'Orbit right',exact:true}).click();
    await page.waitForTimeout(700);
    await canvas.screenshot({path:path.join(__dirname,'squid-opposite-eye.png')});
    for(let i=0;i<10;i++)await page.getByRole('button',{name:'Orbit left',exact:true}).click();
    await page.getByRole('button',{name:'Farther',exact:true}).click();
    await page.getByRole('button',{name:'Farther',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>{document.getElementById('wrap').style.width='100%';window.dispatchEvent(new Event('resize'));});
    await page.waitForTimeout(800);
    await canvas.screenshot({path:path.join(__dirname,'phone-inspection.png')});
    await page.setViewportSize({width:1280,height:1100});
    await page.evaluate(()=>{document.getElementById('wrap').style.width='1100px';window.dispatchEvent(new Event('resize'));});
    await page.getByRole('button',{name:'Return to dive',exact:true}).click();
    await canvas.focus();await page.keyboard.down('KeyW');
    await page.waitForTimeout(1000);await page.keyboard.up('KeyW');
    await page.waitForTimeout(500);
    await canvas.screenshot({path:path.join(__dirname,'pursuit-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>{document.getElementById('wrap').style.width='100%';window.dispatchEvent(new Event('resize'));});
    await page.waitForTimeout(800);
    await canvas.screenshot({path:path.join(__dirname,'pursuit-phone.png')});
    const result={errors,fixture:'Standard inspection, orbit/zoom and forward controls. No mesh, material or actor placement overrides.',screenshots:['squid-profile.png','squid-three-quarter.png','squid-eye-detail.png','squid-opposite-eye.png','phone-inspection.png','pursuit-desktop.png','pursuit-phone.png']};
    fs.writeFileSync(path.join(__dirname,'capture-results.json'),JSON.stringify(result,null,2)+'\n');
    console.log(JSON.stringify(result));if(errors.length)process.exitCode=1;
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
