const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),{spawn}=require('node:child_process');
const repo=process.env.WC_REPO || process.cwd();
const expected=process.argv[2];
if(!/^[0-9a-f]{64}$/.test(expected||''))throw Error('Expected current runtime SHA-256 argument.');
const out=path.resolve(__dirname,process.argv[3]||'unit-final');
if(path.dirname(out)!==__dirname)throw Error('Output must be a new direct scratch child.');
if(fs.existsSync(out))throw Error('Use a new output directory.');
const rels=['stem_lab/stem_tool_watercycle.js','desktop/web-app/public/stem_lab/stem_tool_watercycle.js','tests/watercycle_coalescence_visual.test.js'];
const config=path.join(__dirname,'coalescence-vitest.config.mjs');
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const stamp=file=>{const bytes=fs.readFileSync(file);return{path:file,bytes:bytes.length,sha256:hash(bytes)};};
const observed=()=>[...rels.map(rel=>stamp(path.join(repo,rel))),stamp(config),stamp(__filename)];
const before=observed();
if(before[0].sha256!==expected||before[1].sha256!==expected)throw Error('Runtime or mirror differs from requested candidate.');
fs.mkdirSync(out);
const loaded=path.join(out,'loaded-source.json'),raw=path.join(out,'vitest-results.json'),log=path.join(out,'vitest.log');
const args=[path.join(repo,'node_modules/vitest/vitest.mjs'),'run','--config',config,'--reporter=json','--outputFile',raw];
const receipt={startedAt:new Date().toISOString(),expectedSha256:expected,command:{executable:process.execPath,args,cwd:repo},before};
fs.writeFileSync(path.join(out,'unit-receipt.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({started:true,expectedSha256:expected,out}));
const child=spawn(process.execPath,args,{cwd:repo,env:{...process.env,WATER_CYCLE_COALESCENCE_LOADED_REPORT:loaded},windowsHide:true,stdio:['ignore','pipe','pipe']});
const append=chunk=>{fs.appendFileSync(log,chunk);process.stdout.write(chunk);};
child.stdout.on('data',append);child.stderr.on('data',append);
let launchError=null;child.on('error',error=>{launchError=String(error);});
child.on('close',(code,signal)=>{
  receipt.completedAt=new Date().toISOString();receipt.exitCode=code;receipt.signal=signal;receipt.launchError=launchError;receipt.after=observed();
  try{
    if(code!==0||signal||launchError)throw Error('Vitest did not exit successfully.');
    if(JSON.stringify(receipt.before)!==JSON.stringify(receipt.after))throw Error('Tested input bytes changed during the run.');
    const results=JSON.parse(fs.readFileSync(raw,'utf8')),load=JSON.parse(fs.readFileSync(loaded,'utf8'));
    const assertions=results.testResults.flatMap(suite=>suite.assertionResults||[]);
    if(!results.success||!assertions.length||assertions.some(row=>row.status!=='passed')||results.numFailedTests||results.numPendingTests||results.numTodoTests||results.numRuntimeErrorTestSuites)throw Error('Raw Vitest result contains nonpassing assertions.');
    for(let i=0;i<2;i++)if(load.loadedRuntimes[i].path!==rels[i]||load.loadedRuntimes[i].sha256!==before[i].sha256||load.loadedRuntimes[i].bytes!==before[i].bytes)throw Error('Loaded runtime stamp mismatch.');
    if(load.loadedTest.path!==rels[2]||load.loadedTest.sha256!==before[2].sha256||load.loadedTest.bytes!==before[2].bytes)throw Error('Loaded test stamp mismatch.');
    receipt.passed=true;receipt.tests=assertions.length;receipt.rawResults=stamp(raw);receipt.loadedSource=stamp(loaded);
  }catch(error){receipt.passed=false;receipt.verificationError=String(error);}
  fs.writeFileSync(path.join(out,'unit-receipt.json'),JSON.stringify(receipt,null,2)+'\n');
  console.log(JSON.stringify({passed:receipt.passed,tests:receipt.tests,out,error:receipt.verificationError}));
  process.exitCode=receipt.passed?0:1;
});
