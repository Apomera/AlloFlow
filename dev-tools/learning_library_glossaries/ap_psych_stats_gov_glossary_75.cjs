function makeEntry({
  id,
  term,
  definition,
  aliases,
  chapterId,
  chapterTitle,
  domainId,
  sectionId,
  sectionHeading,
  references,
}) {
  return {
    id,
    term,
    definition,
    aliases,
    chapterIds: [chapterId],
    domainIds: [domainId],
    linkage: {
      occurrences: [
        {
          chapterId,
          chapterTitle,
          domainId,
          domain: chapterTitle,
          sectionId,
          sectionHeading,
        },
      ],
    },
    reviewStatus: 'source-reviewed-editorial-pass',
    references: [...references],
  };
}

