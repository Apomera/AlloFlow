import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import { GlHarness } from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_ecosystem.js',toolId:'ecosystem',width:1100,height:900,appStyles:true});
test.beforeAll(async()=>harness.start());test.afterAll(async()=>harness.stop());test.afterEach(async({page})=>harness.destroy(page));
test('saved evidence survives new setups, exports, reopens, and never silently overwrites a full notebook',async({page})=>{
  await page.setViewportSize({width:1140,height:940});
  await harness.mount(page,{ecosystem:{tab:'foodweb',tutorialDismissed:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.body.className='theme-default';document.getElementById('wrap')!.style.cssText='width:100%;height:auto;display:block;padding:16px;background:white';});
  const notebook=page.locator('[data-efw-notebook]');
  await expect(notebook).toContainText('0 of 12 observations saved');
  await page.getByLabel('Your prediction (optional)',{exact:true}).fill('Removing foxes may increase grazing.');
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await page.getByLabel('Chart group',{exact:true}).selectOption('foxes');
  await page.getByLabel('Explain an indirect change',{exact:true}).fill('Fox biomass is zero; prey and plants respond indirectly.');
  const save=page.getByRole('button',{name:'Save observation',exact:true});
  await save.click();
  const original=await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb.notebook[0]));
  await expect(notebook).toContainText('Observation 1 · Red foxes');
  await page.getByRole('button',{name:'Habitat restoration',exact:true}).click();
  await expect(page.locator('[data-efw-results]')).toHaveCount(0);
  await expect(notebook).toContainText('Fox biomass is zero');
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await page.getByLabel('Explain an indirect change',{exact:true}).fill('Refuge cover rose from 10% to 50%.');
  await save.click();
  expect(await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb.notebook[0]))).toBe(original);
  await notebook.screenshot({path:'reports/ecosystem-field-notebook/desktop.png'});
  await page.getByRole('tab',{name:/Quiz/}).click();await page.getByRole('tab',{name:/Food web/}).click();
  await expect(notebook).toContainText('2 of 12 observations saved');
  await notebook.getByRole('button',{name:'Reopen observation 1',exact:true}).focus();
  await notebook.getByRole('button',{name:'Reopen observation 1',exact:true}).press('Enter');
  await expect(page.getByLabel('Disturbance',{exact:true})).toHaveValue('remove');
  await expect(page.getByLabel('Chart group',{exact:true})).toHaveValue('foxes');
  await expect(page.getByLabel('Explain an indirect change',{exact:true})).toHaveValue('Fox biomass is zero; prey and plants respond indirectly.');
  await expect(page.locator('[data-efw-results]')).toContainText('Prediction before this run: Removing foxes may increase grazing.');
  await expect(page.locator('.efw-meadow-stage canvas')).toHaveAttribute('data-biomass-foxes','0');
  const downloadPromise=page.waitForEvent('download');await notebook.getByRole('button',{name:'Export field notebook',exact:true}).click();
  const download=await downloadPromise;await download.saveAs('reports/ecosystem-field-notebook/example-notebook.txt');
  const txt=fs.readFileSync('reports/ecosystem-field-notebook/example-notebook.txt','utf8');
  expect(txt).toContain('OBSERVATION 1');expect(txt).toContain('OBSERVATION 2');expect(txt).toContain('Refuge cover rose from 10% to 50%.');
  await page.setViewportSize({width:390,height:844});await notebook.screenshot({path:'reports/ecosystem-field-notebook/mobile.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  for(let i=2;i<12;i++)await save.click();
  await expect(save).toBeDisabled();await expect(notebook.locator('[data-efw-note]')).toHaveCount(12);
  expect(await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb.notebook[0]))).toBe(original);
  await notebook.getByRole('button',{name:'Remove observation 2',exact:true}).click();await expect(save).toBeEnabled();await save.click();
  await expect(notebook.locator('[data-efw-note="13"]')).toHaveCount(1);await expect(notebook.locator('[data-efw-note="2"]')).toHaveCount(0);
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
