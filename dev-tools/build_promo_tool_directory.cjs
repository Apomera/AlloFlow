#!/usr/bin/env node
'use strict';
// build_promo_tool_directory.cjs — publish every STEM tool's shareable deep link on tools.html.
//
// WHY THIS EXISTS (2026-09-03):
//   147 STEM tools have a working deep link. /_redirects maps /<slug> -> /app/?tool=<id>, and
//   AlloFlowANTI resolves the same ids at boot, both generated from tool_index.json by
//   build_stem_deep_links.cjs. So a slug can never point at a tool that does not exist.
//
//   None of that reached a visitor. The tool finder curates 33 tools, 16 of which carry an
//   "Open instantly" link; the other 131 tools were reachable only by reading _redirects in the
//   repository. Asked for a link to share for Sourcebook, there was no page to look it up on —
//   and Sourcebook is not named anywhere on the site.
//
//   This block closes that: one generated directory, grouped the way the STEM Lab groups its own
//   tools, every entry a link that opens the tool. Regenerated from the registry, so a tool added
//   tomorrow appears here without anyone remembering to add it.
//
// SOURCES
//   tool_index.json  labels + sections (build_tool_index.cjs)
//   _redirects       slug per tool id  (build_stem_deep_links.cjs)
//   Both are generated. This script invents nothing; a tool with no slug is skipped and reported.
//
// USAGE
//   node dev-tools/build_promo_tool_directory.cjs           rewrite the block in tools.html
//   node dev-tools/build_promo_tool_directory.cjs --check   exit 1 if the block is stale
//
// The promo site is GitHub Pages serving main, so pushing tools.html publishes immediately.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PAGE = path.join(ROOT, 'tools.html');
const INDEX = path.join(ROOT, 'tool_index.json');
const REDIRECTS = path.join(ROOT, '_redirects');
const APP_ORIGIN = 'https://alloflow-cdn.pages.dev';

const CHECK = process.argv.includes('--check');
const BEGIN = '        <!-- __ALLO_TOOL_DIRECTORY_BEGIN__ (generated by dev-tools/build_promo_tool_directory.cjs — do not hand-edit this block) -->';
const END = '        <!-- __ALLO_TOOL_DIRECTORY_END__ -->';
// Anchor: the directory sits between the search results and the "what happens when you launch"
// explainer, so a visitor whose search missed sees the complete list before the launch guidance.
const ANCHOR = '        <section class="tool-access-section" aria-labelledby="access-heading">';

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// ── inputs ───────────────────────────────────────────────────────────────────
const tools = JSON.parse(fs.readFileSync(INDEX, 'utf8')).tools || [];
const slugById = new Map();
for (const line of fs.readFileSync(REDIRECTS, 'utf8').split(/\r?\n/)) {
  const m = /^\/([a-z0-9-]+)\s+\/app\/\?tool=([A-Za-z0-9]+)\s+302$/.exec(line.trim());
  if (m) slugById.set(m[2], m[1]);
}
if (!tools.length || !slugById.size) throw new Error('Refusing to publish an empty directory');

const skipped = [];
const groups = new Map();
for (const tool of tools) {
  const slug = slugById.get(tool.id);
  if (!slug) { skipped.push(tool.id); continue; }
  // Tools registered outside the categorised catalog (the shelves, Tool Forge) carry no section.
  // They are real tools with real links, so they are listed rather than dropped — under a heading
  // that says what they are instead of inventing a subject for them.
  const section = (tool.section || '').trim() || 'Also in the STEM Lab';
  if (!groups.has(section)) groups.set(section, []);
  groups.get(section).push({ label: tool.label || tool.id, slug });
}

const UNSECTIONED = 'Also in the STEM Lab';
const names = [...groups.keys()].filter((n) => n !== UNSECTIONED).sort((a, b) => a.localeCompare(b));
if (groups.has(UNSECTIONED)) names.push(UNSECTIONED);
const listed = [...groups.values()].reduce((n, g) => n + g.length, 0);

// ── render ───────────────────────────────────────────────────────────────────
const out = [];
out.push(BEGIN);
out.push('        <section class="tool-directory-section" aria-labelledby="directory-heading">');
out.push('            <div class="section-inner">');
out.push('                <div class="section-header">');
out.push('                    <h2 id="directory-heading">Every STEM tool, with a link you can share</h2>');
out.push('                    <p>Each link opens that tool directly — no account, no signup, nothing to install. Copy one');
out.push('                        into an assignment, a sub plan, or a message to a colleague and it opens on the tool they need.</p>');
out.push('                </div>');
out.push('                <p class="tool-directory-count">' + listed + ' tools across ' + names.length + ' areas of the STEM Lab.</p>');
for (const name of names) {
  const items = groups.get(name).sort((a, b) => a.label.localeCompare(b.label));
  const slugId = 'dir-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  out.push('                <div class="tool-directory-group">');
  out.push('                    <h3 id="' + slugId + '">' + esc(name) + '</h3>');
  out.push('                    <ul class="tool-directory-list" aria-labelledby="' + slugId + '">');
  for (const item of items) {
    out.push('                        <li><a href="' + APP_ORIGIN + '/' + item.slug + '">' + esc(item.label) + '</a></li>');
  }
  out.push('                    </ul>');
  out.push('                </div>');
}
out.push('            </div>');
out.push('        </section>');
out.push('');
out.push(END);
const block = out.join('\n');

// ── splice ───────────────────────────────────────────────────────────────────
const before = fs.readFileSync(PAGE, 'utf8');
const eol = before.includes('\r\n') ? '\r\n' : '\n';
const body = before.replace(/\r\n/g, '\n');
let next;
const b = body.indexOf(BEGIN.trim());
const e = body.indexOf(END.trim());
if (b >= 0 && e > b) {
  next = body.slice(0, body.lastIndexOf('\n', b) + 1) + block + '\n' + body.slice(e + END.trim().length + 1);
} else {
  const at = body.indexOf(ANCHOR);
  if (at < 0) throw new Error('Could not find the insertion anchor in tools.html: ' + ANCHOR.trim());
  next = body.slice(0, at) + block + '\n\n' + body.slice(at);
}

const changed = next !== body;
console.log('Tool directory: ' + listed + ' linked tools in ' + names.length + ' groups.');
if (skipped.length) console.log('  no deep-link slug (skipped): ' + skipped.length + ' -> ' + skipped.join(', '));
if (CHECK) {
  if (changed) {
    console.error('\nbuild_promo_tool_directory: FAIL — the published directory is stale.');
    console.error('Run `node dev-tools/build_promo_tool_directory.cjs` to regenerate it.');
    process.exit(1);
  }
  console.log('\nbuild_promo_tool_directory: OK — tools.html matches the registry.');
  process.exit(0);
}
if (!changed) { console.log('\nAlready current; nothing written.'); process.exit(0); }
fs.writeFileSync(PAGE, eol === '\r\n' ? next.replace(/\n/g, '\r\n') : next, 'utf8');
console.log('\nWrote tools.html');
