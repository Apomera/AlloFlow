import {test,expect} from '@playwright/test';
import {GlHarness} from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_ecosystem.js',toolId:'ecosystem',width:1100,height:900,appStyles:true});
test.beforeAll(async()=>harness.start());test.afterAll(async()=>harness.stop());test.afterEach(async({page})=>harness.destroy(page));
test('soil cycle connects paired samples, forest-floor inspection, saved evidence and exports',async({page})=>{
  await page.setViewportSize({width:1140,height:1050});
  await harness.mount(page,{ecosystem:{tab:'foodweb',tutorialDismissed:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.body.className='theme-default';document.getElementById('wrap')!.style.cssText='width:100%;height:auto;display:block;padding:16px;background:white';});
  const cycle=page.locator('[data-efw-soil-cycle]');await expect(cycle).toHaveCount(0);
  await page.getByRole('button',{name:'Decomposer decline',exact:true}).click();
  await expect(page.getByLabel('Enable soil nutrient cycle',{exact:true})).toBeChecked();
  await expect(page.getByLabel('Starting decomposer biomass',{exact:true})).toHaveValue('8');
  await expect(cycle.locator('[data-efw-soil-pool]')).toHaveCount(3);
  const meadow=page.locator('[data-efw-meadow]'),canvas=meadow.locator('canvas'),stage=meadow.locator('.efw-meadow-stage');
  await expect(canvas).toHaveAttribute('data-soil-enabled','true');
  await expect(canvas).toHaveAttribute('data-soil-decomposers','8');
  await meadow.getByRole('button',{name:'Inspect forest floor',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-camera-mode','soil');
  await stage.screenshot({path:'reports/ecosystem-soil-cycle/forest-floor.jpg',type:'jpeg',quality:90});
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await page.getByLabel('Soil cycle timeline',{exact:true}).fill('80');
  const expected=await page.evaluate(()=>{const w=window as any;return w.StemLab.ecosystemFoodWeb.compare(w.__toolData.ecosystem.foodWeb.run.config);});
  for(const key of ['detritus','decomposers','nutrients']){
    await expect(canvas).toHaveAttribute('data-soil-'+key,String(expected.experiment[80].soil[key]));
    await expect(cycle.locator('[data-efw-soil-pool="'+key+'"]')).toHaveAttribute('data-baseline',String(expected.baseline[80].soil[key]));
    await expect(cycle.locator('[data-efw-soil-pool="'+key+'"]')).toHaveAttribute('data-experiment',String(expected.experiment[80].soil[key]));
  }
  await meadow.getByLabel('Meadow scene data',{exact:true}).selectOption('baseline');
  await expect(canvas).toHaveAttribute('data-soil-decomposers',String(expected.baseline[80].soil.decomposers));
  await meadow.getByLabel('Meadow scene data',{exact:true}).selectOption('experiment');
  await stage.screenshot({path:'reports/ecosystem-soil-cycle/decomposer-decline.jpg',type:'jpeg',quality:90});
  await cycle.screenshot({path:'reports/ecosystem-soil-cycle/nutrient-cycle.jpg',type:'jpeg',quality:90});
  await page.getByRole('button',{name:'Save observation',exact:true}).click();
  await expect(page.locator('[data-efw-note-soil]')).toHaveCount(1);
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Export comparison CSV',exact:true}).click();
  await (await downloadEvent).saveAs('reports/ecosystem-soil-cycle/comparison.csv');
  await page.setViewportSize({width:390,height:844});
  await cycle.screenshot({path:'reports/ecosystem-soil-cycle/mobile-cycle.jpg',type:'jpeg',quality:88});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.emulateMedia({reducedMotion:'reduce'});await expect(meadow).toContainText('Reduced motion is on');
  await page.getByRole('button',{name:'Shared-prey web',exact:true}).click();
  await expect(cycle).toHaveCount(0);await expect(canvas).toHaveAttribute('data-soil-enabled','false');await expect(canvas).toHaveAttribute('data-camera-mode','habitat');
  await page.getByRole('button',{name:'Reopen observation 1',exact:true}).click();
  await expect(page.getByLabel('Soil cycle timeline',{exact:true})).toHaveValue('80');
  await expect(canvas).toHaveAttribute('data-soil-decomposers',String(expected.experiment[80].soil.decomposers));
  await page.getByLabel('Disturbance',{exact:true}).selectOption('clearLitter');await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await page.getByLabel('Soil cycle timeline',{exact:true}).fill('80');await expect(canvas).toHaveAttribute('data-soil-litter','0');
  await page.getByLabel('Starting decomposer biomass',{exact:true}).fill('0');await expect(canvas).toHaveAttribute('data-soil-fungi','0');
  await page.getByLabel('Enable soil nutrient cycle',{exact:true}).uncheck();await expect(page.getByLabel('Disturbance',{exact:true})).toHaveValue('none');
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
