// @vitest-environment jsdom
import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

// Contrast theme. Dynamic Assessment opens this tool as "fractions" while the generated rules name "fractionViz", so that
// path read yellow on white at about 1:1. The host also paints every button black, which erased the filled strip parts and
// the selected tab. Only a browser can prove the pixels (see the contrast_bh report); here the rules are applied to real markup.
const DIR = process.env.FRACTIONS_HC_DIR || path.join(process.cwd(), 'stem_lab');
const src = fs.readFileSync(path.join(DIR, 'stem_tool_fractions.js'), 'utf8');

// Run the file's own two style blocks, in order, as the browser does.
function loadCss() {
  document.head.innerHTML = '';
  for (const [a, b] of [['// WCAG 1.4.3 high contrast (generated by gen_hc.cjs)', '// end WCAG 1.4.3 high contrast'], ['// Tool-owned contrast rules', '// end tool-owned contrast rules']]) {
    const i = src.indexOf(a), j = src.indexOf(b);
    if (i >= 0 && j > i) new Function(src.slice(i, j))();
  }
  const css = (id) => (document.getElementById(id) || { textContent: '' }).textContent;
  return { gen: css('allo-fractions-hc-css'), extra: css('allo-fractions-hc-extra-css') };
}
const { gen, extra } = loadCss();
const rules = extra.split('}').filter(Boolean).flatMap((r) => r.split('{')[0].split(/,(?=\.theme-contrast)/).map((sel) => ({ sel, body: r.split('{')[1] })));
const hits = (el) => rules.filter((r) => { try { return el.matches(r.sel); } catch (e) { return false; } }).map((r) => r.body).join(';');
function mount(shell, inner) {
  document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}">${inner}</div></div>`;
  return document.body.querySelector('[data-stem-tool-shell]').firstElementChild;
}

describe('Fraction Lab contrast theme', () => {
  it('leaves the generated block alone and adds its own after the end marker', () => {
    expect(gen).toContain('[data-stem-tool-shell="fractionViz"]');
    expect(gen).not.toContain('[data-stem-tool-shell="fractions"]');
    expect(extra, 'allo-fractions-hc-extra-css is missing').not.toBe('');
    expect(src.indexOf("st.id = 'allo-fractions-hc-extra-css'")).toBeGreaterThan(src.indexOf('// end WCAG 1.4.3 high contrast'));
  });
  it('repeats every generated rule for the shell Dynamic Assessment opens', () => {
    expect(extra.split('[data-stem-tool-shell="fractions"]').length).toBeGreaterThanOrEqual(gen.split('[data-stem-tool-shell="fractionViz"]').length);
    expect(hits(mount('fractions', '<div class="fraction-lab-control-card">x</div>'))).toContain('background-color:#000!important');
    expect(hits(mount('fractions', '<div class="fraction-lab-panel">x</div>'))).toContain('background:#000!important');
    expect(hits(mount('fractions', '<output class="fraction-lab-value-chip">8</output>'))).toContain('background-color:#000!important');
  });
  for (const shell of ['fractions', 'fractionViz']) {
    describe(`in the ${shell} shell`, () => {
      it('keeps the filled strip parts visible, except under the host hover', () => {
        expect(hits(mount(shell, '<button class="fraction-lab-strip-segment is-filled"></button>'))).toContain('background-color:#ffff00');
        expect(hits(mount(shell, '<button class="fraction-lab-strip-segment is-empty"></button>'))).not.toContain('#ffff00');
      });
      it('shows which tab and which model are selected, with black ink inside', () => {
        const nav = mount(shell, '<div class="fraction-lab-navigation"><button aria-selected="true"><span>Learn</span></button><button aria-selected="false"><span>Practice</span></button></div>');
        const [on, off] = nav.querySelectorAll('button');
        expect(hits(on)).toContain('background-color:#ffff00');
        expect(hits(on.firstElementChild)).toContain('color:#000');
        expect(hits(off)).toBe('');
        const tog = mount(shell, '<div class="fraction-lab-mode-toggle"><button aria-pressed="true">Pie</button></div>');
        expect(hits(tog.firstElementChild)).toContain('background-color:#ffff00');
      });
      it('tells empty pie and strip parts from filled ones', () => {
        document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}"><svg><path id="e" fill="#fecdd3"></path><path id="f" fill="#f43f5e"></path></svg></div></div>`;
        expect(hits(document.getElementById('e'))).toContain('fill:#000');
        expect(hits(document.getElementById('f'))).toBe('');
      });
      it('keeps the compare line on white, its dark ink needs it', () => {
        document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}"><svg id="s" data-compare-line="true"></svg></div></div>`;
        expect(hits(document.getElementById('s'))).toContain('background:#fff');
      });
      it('lights up the number line model, whose ink is dark on the flattened card', () => {
        document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}"><svg><line id="l" stroke="#0f172a"></line><text id="t" fill="#0f172a">0</text><text id="u" fill="#64748b">1/2</text></svg></div></div>`;
        expect(hits(document.getElementById('l'))).toContain('stroke:#fff');
        expect(hits(document.getElementById('t'))).toContain('fill:#ffff00');
        expect(hits(document.getElementById('u'))).toContain('fill:#ffff00');
      });
      it('keeps the signed map on white, with its zero tick dark', () => {
        document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}"><section aria-labelledby="signed-number-line-title"><svg id="s"><line id="z" stroke="#0f172a"></line><line id="m" stroke="#94a3b8"></line><text id="t" fill="#475569">1</text></svg></section></div></div>`;
        expect(hits(document.getElementById('s'))).toContain('background:#fff');
        expect(hits(document.getElementById('z'))).toBe('');
        expect(hits(document.getElementById('m'))).toContain('stroke:#000');
        expect(hits(document.getElementById('t'))).toContain('fill:#000');
      });
      it('leaves the compare line ink dark on its white surface', () => {
        document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}"><svg data-compare-line="true"><text id="t" fill="#0f172a">A</text></svg></div></div>`;
        expect(hits(document.getElementById('t'))).toBe('');
      });
      it('halos white slice numbers, so they read on any palette', () => {
        document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${shell}"><svg><text id="t" style="fill: white;">1</text></svg></div></div>`;
        expect(hits(document.getElementById('t'))).toContain('stroke:#000');
      });
      it('flattens a pale gradient card with text, but not a gradient button or an empty progress bar', () => {
        expect(hits(mount(shell, '<div class="bg-gradient-to-br from-red-50 to-orange-50"><h4>Pizza Shop</h4></div>'))).toContain('background-color:#000');
        expect(hits(mount(shell, '<button class="bg-gradient-to-r from-rose-700 to-pink-700">Go</button>'))).toBe('');
        expect(hits(mount(shell, '<div class="h-full bg-gradient-to-r from-rose-700 to-pink-700"></div>'))).toBe('');
      });
      it('turns dark emphasis the host does not force yellow', () => {
        expect(hits(mount(shell, '<b class="text-emerald-800">Accommodations:</b>'))).toContain('color:#ffff00');
        expect(hits(mount(shell, '<pre class="text-slate-800">report</pre>'))).toContain('color:#ffff00');
      });
    });
  }
  it('only ever applies inside the contrast theme', () => {
    document.body.innerHTML = '<div data-stem-tool-shell="fractions"><button class="fraction-lab-strip-segment is-filled"></button></div>';
    expect(hits(document.querySelector('button'))).toBe('');
  });
  it('does not touch Dynamic Assessment presets', () => {
    expect(src).toContain("window.StemLab.registerTool('fractions', fracPlugin)");
    expect(extra).not.toMatch(/display\s*:\s*none/);
  });
});
