// @vitest-environment jsdom
import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

// stem_tool_geo.js holds two tools. Contrast theme, geoQuiz: Leaflet's white attribution strip and map labels under the
// host's forced yellow (1.0-1.4:1); attribution is a licence requirement. geometryProver: an inline gradient helper bar
// and a pale SVG canvas with violet ink. The generated block (allo-geo-hc-css) is replaced by gen_hc.cjs, so these
// rules live in the tool's own block outside it.
const DIR = process.env.GEO_HC_DIR || path.join(process.cwd(), 'stem_lab');
const src = fs.readFileSync(path.join(DIR, 'stem_tool_geo.js'), 'utf8');
const m = /st\.id = 'allo-geo-hc-extra-css';\s*st\.textContent = ("(?:[^"\\]|\\.)*");/.exec(src);
const css = m ? JSON.parse(m[1]) : '';
const rules = css.split('}').filter(Boolean).map((r) => { const [sel, body] = r.split('{'); return { sel, body }; });
const bodyFor = (el) => rules.filter((r) => el.matches(r.sel)).map((r) => r.body).join(';');
function mount(tool, inner) {
  document.body.innerHTML = `<div class="theme-contrast"><div data-stem-tool-shell="${tool}">${inner}</div></div>`;
  return document.body.querySelector('[data-stem-tool-shell]').firstElementChild;
}

describe('stem_tool_geo.js contrast block', () => {
  it('exists, outside the generated markers, scoped to one of the two shells', () => {
    expect(m, 'allo-geo-hc-extra-css is missing').not.toBeNull();
    const a = src.indexOf('// WCAG 1.4.3 high contrast (generated by gen_hc.cjs)');
    const b = src.indexOf('// end WCAG 1.4.3 high contrast');
    expect(a).toBeGreaterThan(-1);
    expect(m.index < a || m.index > b).toBe(true);
    for (const r of rules) expect(/^\.theme-contrast \[data-stem-tool-shell="(geoQuiz|geometryProver)"\] /.test(r.sel), r.sel).toBe(true);
  });
});

describe('geoQuiz contrast theme: map text', () => {
  it('puts the attribution strip on opaque black with yellow, underlined links', () => {
    const strip = mount('geoQuiz', '<div class="leaflet-control-attribution leaflet-control">Tiles <a href="https://www.esri.com">Esri</a></div>');
    expect(bodyFor(strip)).toContain('background:#000!important');
    expect(bodyFor(strip)).toContain('color:#ff0!important');
    expect(bodyFor(strip.querySelector('a'))).toContain('text-decoration:underline!important');
  });
  it('never hides the attribution', () => {
    expect(/leaflet-control-attribution[^{]*\{[^}]*(display:\s*none|visibility:\s*hidden|opacity:\s*0)/.test(css)).toBe(false);
  });
  it('repaints the white city labels', () => {
    const tip = mount('geoQuiz', '<div class="leaflet-tooltip leaflet-tooltip-top" style="opacity: 0.9;">Amman</div>');
    expect(bodyFor(tip)).toContain('background:#000!important');
    expect(bodyFor(tip)).toContain('opacity:1!important');
  });
});

describe('geometryProver contrast theme', () => {
  it('flattens the helper bar gradient (React serialises it as rgb)', () => {
    const bar = mount('geometryProver', '<div class="flex" style="background: linear-gradient(90deg, rgb(245, 243, 255), rgb(237, 233, 254)); border-color: rgb(196, 181, 253);">x</div>');
    expect(bodyFor(bar)).toContain('background:#000!important');
  });
  it('makes the SVG canvas a black panel with bright ink', () => {
    const svg = mount('geometryProver', '<svg class="cursor-crosshair select-none" style="background: rgb(250, 245, 255);"><text style="fill: rgb(167, 139, 250);">Click to place points</text><line stroke="#6d28d9"></line><rect fill="#f5f3ff"></rect></svg>');
    expect(bodyFor(svg)).toContain('background:#000!important');
    expect(bodyFor(svg.querySelector('text'))).toContain('fill:#ff0!important');
    expect(bodyFor(svg.querySelector('line'))).toContain('stroke:#fff!important');
    expect(bodyFor(svg.querySelector('rect'))).toContain('fill:#000!important');
  });
  it('keeps the right-angle colour cue separate from the other angle labels', () => {
    const svg = mount('geometryProver', '<svg class="cursor-crosshair"><text id="r" style="fill: rgb(5, 150, 105);">90.0</text><rect id="sq" fill="none" stroke="#7c3aed"></rect></svg>');
    expect(rules.filter((r) => svg.querySelector('#r').matches(r.sel)).pop().body).toContain('fill:#0f0!important');
    expect(bodyFor(svg.querySelector('#sq'))).toContain('stroke:#0f0!important');
  });
});
