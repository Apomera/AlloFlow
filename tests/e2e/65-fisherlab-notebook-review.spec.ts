import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_fisherlab.js', toolId: 'fisherLab', width: 1180, height: 980, appStyles: true, extraScripts: ['desktop/web-app/node_modules/axe-core/axe.min.js'] });
test.beforeAll(async () => { await harness.start(); });
test.afterAll(async () => { await harness.stop(); });
test.afterEach(async ({ page }) => { await harness.destroy(page); });
test('opens the next missing field and distinguishes saved writing, edits, reverts and deletion', async ({ page }) => {
  await harness.mount(page, {}, undefined, { expectCanvas: false });
  const overview = page.locator('[data-fisherlab-notebook-overview]');
  await expect(overview.getByRole('button', { name: 'Download all current notes' })).not.toBeVisible();
  await overview.locator('summary').click();
  await expect(overview.getByRole('button', { name: 'Download all current notes' })).toBeDisabled();
  const topic = overview.locator('[data-notebook-topic="navigation"]');
  await topic.getByRole('button').click();
  const claim = page.getByLabel('My claim', { exact: true });
  await expect(claim).toBeFocused();
  await claim.fill('A slower speed takes longer.');
  await expect(topic.locator('[data-notebook-save-state]')).toHaveText('Unsaved changes');
  await expect(overview.locator('summary')).toContainText('1 unsaved');
  const note = page.locator('[data-fisherlab-learning-note]');
  await note.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(topic.locator('[data-notebook-save-state]')).toHaveText('Saved copy matches');
  await claim.fill('A revised draft.');
  await expect(topic.locator('[data-notebook-save-state]')).toHaveText('Unsaved changes');
  await claim.fill('A slower speed takes longer.');
  await expect(topic.locator('[data-notebook-save-state]')).toHaveText('Saved copy matches');
  await expect(note.locator('[data-learning-note-status]')).toContainText('matches the last saved copy');
  await topic.getByRole('button').click();
  await expect(page.getByLabel('Evidence & reasoning', { exact: true })).toBeFocused();
  await claim.fill('');
  await expect(topic.locator('[data-notebook-save-state]')).toHaveText('Unsaved changes');
  await expect(topic).toContainText('0 of 3 parts have writing');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('fisherLab.learningNotes.v1')!).navigation.claim)).toBe('A slower speed takes longer.');
  await claim.fill('My current draft.');
  await overview.screenshot({ path: 'scratch/fisherlab-notebook-review-desktop.png' });
});
test('combined download includes current drafts while saved copies and active journeys survive', async ({ page }) => {
  await harness.mount(page, {}, undefined, { expectCanvas: false });
  await page.getByRole('button', { name: 'Start guided investigation', exact: true }).click();
  await page.locator('[data-fisherlab-journey]').getByLabel('My prediction', { exact: false }).fill('Preserve this investigation.');
  const overview = page.locator('[data-fisherlab-notebook-overview]');
  await overview.locator('summary').click();
  await overview.getByRole('button', { name: 'Open Navigation math note' }).click();
  let note = page.locator('[data-fisherlab-learning-note]');
  await note.getByLabel('My claim', { exact: true }).fill('Saved navigation claim.');
  await note.getByRole('button', { name: 'Save note', exact: true }).click();
  await note.getByLabel('My claim', { exact: true }).fill('Latest navigation draft.');
  await overview.getByRole('button', { name: 'Open Evidence & sampling note' }).click();
  await expect(page.getByLabel('My claim', { exact: true })).toBeFocused();
  await note.getByLabel('My claim', { exact: true }).fill('Latest sampling draft.');
  const downloadEvent = page.waitForEvent('download');
  await overview.getByRole('button', { name: 'Download all current notes' }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe('fisherlab-learning-notebook.txt');
  let text = '';
  for await (const chunk of (await download.createReadStream())!) text += chunk.toString();
  expect(text).toContain('Latest navigation draft.');
  expect(text).toContain('Latest sampling draft.');
  expect(text).not.toContain('Saved navigation claim.');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('fisherLab.learningNotes.v1')!).navigation.claim)).toBe('Saved navigation claim.');
  await page.getByRole('button', { name: 'Continue investigation', exact: true }).click();
  await expect(page.locator('[data-fisherlab-journey]').getByLabel('My prediction', { exact: false })).toHaveValue('Preserve this investigation.');
});
test('failed saves remain marked unsaved and review is accessible on mobile with large text', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 850 });
  await harness.mount(page, {}, undefined, { expectCanvas: false });
  await page.evaluate(() => { document.getElementById('wrap')!.style.width = '360px'; });
  await page.getByRole('button', { name: 'Large text', exact: true }).click();
  const overview = page.locator('[data-fisherlab-notebook-overview]');
  await overview.locator('summary').focus();
  await page.keyboard.press('Enter');
  await overview.getByRole('button', { name: 'Open Measurement & uncertainty note' }).click();
  const note = page.locator('[data-fisherlab-learning-note]');
  await note.getByLabel('My claim', { exact: true }).fill('Keep this draft.');
  await page.evaluate(() => {
    const old = Storage.prototype.setItem;
    (window as any).__restoreStorage = () => { Storage.prototype.setItem = old; };
    Storage.prototype.setItem = function(key, value) { if (key === 'fisherLab.learningNotes.v1') throw new Error('quota'); return old.call(this, key, value); };
  });
  await note.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(note.locator('[data-learning-note-status]')).toContainText('Could not save');
  await expect(overview.locator('[data-notebook-topic="measurement"] [data-notebook-save-state]')).toHaveText('Unsaved changes');
  const metric = await overview.evaluate(el => ({ client: el.clientWidth, scroll: el.scrollWidth, right: el.getBoundingClientRect().right }));
  expect(metric.scroll).toBeLessThanOrEqual(metric.client + 1);
  expect(metric.right).toBeLessThanOrEqual(360);
  const violations = await page.evaluate(async () => (await (window as any).axe.run('[data-fisherlab-notebook-overview]', { runOnly: { type: 'rule', values: ['color-contrast', 'button-name', 'label', 'aria-valid-attr-value', 'aria-allowed-attr'] } })).violations.map((v: any) => v.id));
  expect(violations).toEqual([]);
  await overview.screenshot({ path: 'scratch/fisherlab-notebook-review-mobile.png' });
  await page.evaluate(() => (window as any).__restoreStorage());
  await note.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(overview.locator('[data-notebook-topic="measurement"] [data-notebook-save-state]')).toHaveText('Saved copy matches');
});
