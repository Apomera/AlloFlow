import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';

const harness = new GlHarness({toolFile:'stem_lab/stem_tool_ecosystem.js',toolId:'ecosystem',width:1100,height:900,appStyles:true});
test.beforeAll(async()=>harness.start());
test.afterAll(async()=>harness.stop());
test.afterEach(async({page})=>harness.destroy(page));

test('woodland lighting changes the rendered scene while preserving evidence and camera controls',async({page})=>{
  await page.setViewportSize({width:1140,height:1000});
  await harness.mount(page,{ecosystem:{tab:'foodweb',tutorialDismissed:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.body.className='theme-default';document.getElementById('wrap')!.style.cssText='width:100%;height:auto;display:block;padding:16px;background:white';});
  await page.getByRole('button',{name:'Habitat restoration',exact:true}).click();
  const meadow=page.locator('[data-efw-meadow]'),canvas=meadow.locator('canvas'),stage=meadow.locator('.efw-meadow-stage');
  const lighting=meadow.getByRole('combobox',{name:'Woodland lighting',exact:true});
  await expect(canvas).toHaveAttribute('data-lighting','daylight');
  await expect(canvas).toHaveAttribute('data-grass-tufts','2400');
  expect(Number(await canvas.getAttribute('data-root-count'))).toBeGreaterThan(400);
  const setup=await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb));
  const originalCanvas=await canvas.elementHandle();
  const day=await stage.screenshot({path:'reports/ecosystem-forest-lighting/daylight.jpg',type:'jpeg',quality:88});
  await lighting.selectOption('golden');
  await expect(canvas).toHaveAttribute('data-lighting','golden');
  const golden=await stage.screenshot({path:'reports/ecosystem-forest-lighting/golden-hour.jpg',type:'jpeg',quality:88});
  expect(golden.equals(day)).toBe(false);
  await lighting.focus();await lighting.press('ArrowDown');
  await expect(lighting).toHaveValue('overcast');
  await expect(canvas).toHaveAttribute('data-lighting','overcast');
  const overcast=await stage.screenshot({path:'reports/ecosystem-forest-lighting/overcast.jpg',type:'jpeg',quality:88});
  expect(overcast.equals(golden)).toBe(false);
  expect(await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb))).toBe(setup);
  expect(await originalCanvas!.evaluate(el=>el===document.querySelector('[data-efw-meadow] canvas'))).toBe(true);
  await lighting.selectOption('golden');
  await meadow.getByRole('button',{name:/Red foxes/}).click();
  await meadow.getByRole('button',{name:'Inspect selected group',exact:true}).click();
  await stage.screenshot({path:'reports/ecosystem-forest-lighting/fox-inspection.jpg',type:'jpeg',quality:88});
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-refuge-cover','50');
  const results=await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb));
  await lighting.selectOption('daylight');
  await expect(canvas).toHaveAttribute('data-lighting','daylight');
  expect(await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb))).toBe(results);
  await meadow.getByRole('combobox',{name:'Meadow scene data',exact:true}).selectOption('baseline');
  await expect(canvas).toHaveAttribute('data-refuge-cover','10');
  await meadow.getByRole('combobox',{name:'Meadow scene data',exact:true}).selectOption('experiment');
  await expect(canvas).toHaveAttribute('data-refuge-cover','50');
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(meadow).toContainText('Reduced motion is on');
  await lighting.selectOption('overcast');
  await expect(canvas).toHaveAttribute('data-lighting','overcast');
  await meadow.getByRole('button',{name:'Reset camera',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await stage.screenshot({path:'reports/ecosystem-forest-lighting/mobile.jpg',type:'jpeg',quality:88});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Hide 3D meadow',exact:true}).click();
  await expect(canvas).toHaveCount(0);
  await page.getByRole('button',{name:'Show 3D meadow',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-lighting','daylight');
  await expect(canvas).toHaveAttribute('data-refuge-cover','50');
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
