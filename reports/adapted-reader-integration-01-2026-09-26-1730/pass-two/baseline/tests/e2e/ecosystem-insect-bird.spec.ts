import {test,expect} from '@playwright/test';
import {GlHarness} from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_ecosystem.js',toolId:'ecosystem',width:1100,height:900,appStyles:true});
test.beforeAll(async()=>harness.start());test.afterAll(async()=>harness.stop());test.afterEach(async({page})=>harness.destroy(page));
test('optional insect–bird pathway reaches visuals, shared evidence, exports and saved observations',async({page})=>{
  await page.setViewportSize({width:1140,height:1050});
  await harness.mount(page,{ecosystem:{tab:'foodweb',tutorialDismissed:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.body.className='theme-default';document.getElementById('wrap')!.style.cssText='width:100%;height:auto;display:block;padding:16px;background:white';});
  await expect(page.locator('.efw-node')).toHaveCount(5);
  await page.getByRole('button',{name:'Insect food shortage',exact:true}).click();
  const meadow=page.locator('[data-efw-meadow]'),canvas=meadow.locator('canvas'),stage=meadow.locator('.efw-meadow-stage');
  await expect(page.getByLabel('Include Caterpillars',{exact:true})).toBeChecked();
  await expect(page.getByLabel('Include Blue tits',{exact:true})).toBeChecked();
  await expect(page.locator('.efw-node')).toHaveCount(7);
  await expect(canvas).toHaveAttribute('data-biomass-caterpillars','20');
  await expect(canvas).toHaveAttribute('data-biomass-bluetits','5');
  await expect(page.locator('[data-efw-relationships]')).toContainText('Caterpillars → Blue tits');
  await stage.screenshot({path:'reports/ecosystem-insect-bird/community.jpg',type:'jpeg',quality:88});
  await meadow.getByRole('button',{name:'Inspect selected group',exact:true}).click();
  await stage.screenshot({path:'reports/ecosystem-insect-bird/blue-tit.jpg',type:'jpeg',quality:88});
  await meadow.getByRole('button',{name:/Caterpillars/}).click();
  await expect(canvas).toHaveAttribute('data-selected-species','caterpillars');
  await stage.screenshot({path:'reports/ecosystem-insect-bird/caterpillar.jpg',type:'jpeg',quality:88});
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await expect(page.locator('[data-efw-overview-species]')).toHaveCount(7);
  await page.getByLabel('Chart group',{exact:true}).selectOption('bluetits');
  const timeline=meadow.getByRole('slider',{name:'Meadow timeline',exact:true});
  await timeline.fill('120');
  const expected=await page.evaluate(()=>{const w=window as any;return w.StemLab.ecosystemFoodWeb.compare(w.__toolData.ecosystem.foodWeb.run.config).experiment[120].values.bluetits;});
  await expect(canvas).toHaveAttribute('data-biomass-bluetits',String(expected));
  await page.getByLabel('Explain an indirect change',{exact:true}).fill('Fewer caterpillars means less insect food for birds.');
  await page.getByRole('button',{name:'Save observation',exact:true}).click();
  await expect(page.locator('[data-efw-note]')).toHaveCount(1);
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Export comparison CSV',exact:true}).click();
  const download=await downloadEvent;await download.saveAs('reports/ecosystem-insect-bird/comparison.csv');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.efw-network').screenshot({path:'reports/ecosystem-insect-bird/mobile-food-web.jpg',type:'jpeg',quality:90});
  const boxes=await page.locator('.efw-node').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height};}));
  for(let i=0;i<boxes.length;i++)for(let j=i+1;j<boxes.length;j++){const a=boxes[i],b=boxes[j];expect(a.x+a.w<=b.x||b.x+b.w<=a.x||a.y+a.h<=b.y||b.y+b.h<=a.y).toBe(true);}
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.emulateMedia({reducedMotion:'reduce'});await expect(meadow).toContainText('Reduced motion is on');
  await page.getByRole('button',{name:'Shared-prey web',exact:true}).click();await expect(page.locator('.efw-node')).toHaveCount(5);
  await page.getByRole('button',{name:'Reopen observation 1',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-biomass-bluetits',String(expected));await expect(timeline).toHaveValue('120');
  await page.getByLabel('Disturbance',{exact:true}).selectOption('remove');await page.getByLabel('Affected group',{exact:true}).selectOption('caterpillars');
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-glyphs-caterpillars','0');
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
