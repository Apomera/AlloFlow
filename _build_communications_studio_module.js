#!/usr/bin/env node
/**
 * Build communications_studio_module.js from communications_studio_source.jsx
 * (Communications Studio — teacher family/staff communications, Sept 2026.)
 *
 * Mirrors _build_udl_walkthrough_module.js: esbuild JSX -> createElement,
 * IIFE wrapper with an a11y live region, writes communications_studio_module.js
 * + syncs to desktop/web-app/public/. Pure helpers are exposed under
 * `_testing` for the unit suite; the public contract is the panel only.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'communications_studio_source.jsx');
const OUTPUT = path.join(ROOT, 'communications_studio_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'communications_studio_module.js');
const TMP = path.join(ROOT, '_tmp_communications_studio_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__communicationsStudioExports = { CommunicationsStudioPanel, csScrubPII, csFindLikelyNames, csReadability, csParseGrid, csBuildPrompt, csParseBatch, csDraftToHtml, CS_TEMPLATES, CS_TONES, CS_LANGUAGES, CS_FAMILY_TARGET_GRADE, CS_DISCLOSURE };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling communications_studio_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch (_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__communicationsStudioExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow Communications Studio Module
 *
 * Auto-generated by _build_communications_studio_module.js — DO NOT EDIT MANUALLY.
 * Source: communications_studio_source.jsx
 *
 * Family updates, batch report-card comments, recommendation letters and
 * replies to families, drafted only from teacher-entered notes. Codename-first
 * (PII scrubbed, likely names flagged), evidence-only prompts, never sends:
 * copy, print, or Send to my Drive through the Class Mailbox. Nothing typed is
 * persisted.
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.CommunicationsStudio) {
    console.log('[CDN] CommunicationsStudio already loaded, skipping');
    return;
  }
  (function() {
    if (document.getElementById('allo-live-commstudio')) return;
    var liveRegion = document.createElement('div');
    liveRegion.id = 'allo-live-commstudio';
    liveRegion.setAttribute('aria-live', 'polite');
    liveRegion.setAttribute('aria-atomic', 'true');
    liveRegion.setAttribute('role', 'status');
    liveRegion.className = 'sr-only';
    liveRegion.style.cssText = 'position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);border:0';
    document.body.appendChild(liveRegion);
  })();
  var React = window.React;
  if (!React) { console.error('[CommunicationsStudio] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.CommunicationsStudio = {
    CommunicationsStudioPanel: CommunicationsStudioPanel,
    // Pure seams exposed for unit tests. Not part of the public contract.
    _testing: {
      csScrubPII, csRosterIndex, csSummarizeDashboardStudent, csReadTeacherComments, csEvidenceLine, csBuildEvidence, csRollupLine, csNormalizeCodename: csScrubPII,
      csFindLikelyNames: csFindLikelyNames,
      csReadability: csReadability,
      csParseGrid: csParseGrid,
      csBuildPrompt: csBuildPrompt,
      csParseBatch: csParseBatch,
      csDraftToHtml: csDraftToHtml,
      CS_TEMPLATES: CS_TEMPLATES,
      CS_TONES: CS_TONES,
      CS_LANGUAGES: CS_LANGUAGES,
      CS_FAMILY_TARGET_GRADE: CS_FAMILY_TARGET_GRADE,
      CS_DISCLOSURE: CS_DISCLOSURE
    }
  };
  console.log('[CDN] CommunicationsStudio loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[CommunicationsStudio] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
