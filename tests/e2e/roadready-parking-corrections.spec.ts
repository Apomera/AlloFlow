import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_roadready.js', toolId: 'roadReady', width: 1100, height: 780, appStyles: true, preScripts: ['stem_lab/stem_lab_module.js'], probes: "window.__testHooks={};document.documentElement.classList.add('theme-dark');" });
test.beforeAll(async () => { await harness.start(); });
test.afterAll(async () => { await harness.stop(); });
test.afterEach(async ({ page }) => { await harness.destroy(page); });
test('the instructor follows corrections, requires securing, and returns to step one on reset', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 });
  await harness.mount(page, { roadReady: { view: 'parking', reducedMotion: true, badges: { park_master: true } } }, undefined, { expectCanvas: false });
  await page.evaluate(() => { document.getElementById('wrap')!.style.width = '100%'; });
  const coach = page.getByRole('region', { name: 'Parking instructor' });
  const pose = async (x: number) => page.evaluate(x => Object.assign((window as any).__testHooks.parking.carRef.current, { x, y: 167.5, heading: -Math.PI / 2, steering: 0, speed: 0 }), x);
  await expect(coach).toContainText('Step 1 of 5');
  await pose(285);
  await expect(coach).toContainText('Step 5 of 5');
  expect(await page.evaluate(() => !!(window as any).__testHooks.parking.carRef.current.parkingBrake)).toBe(false);
  await pose(280);
  await expect(coach).toContainText('Keep clear of the curb and no more than 18 inches away.');
  await pose(285);
  await expect(coach).not.toContainText('Keep clear of the curb and no more than 18 inches away.');
  await expect(coach).toContainText('then select Park + parking brake');
  const coachBox = await coach.boundingBox();
  const controlsBox = await page.getByRole('group', { name: 'Parking controls' }).boundingBox();
  const metricsBox = await page.getByRole('region', { name: 'Live parking measurements' }).boundingBox();
  expect(coachBox!.y).toBeLessThan(controlsBox!.y);
  expect(controlsBox!.y).toBeLessThan(metricsBox!.y);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await page.screenshot({ path: 'reports/roadready-review/parking-adaptive-coach-320.png', fullPage: true, scale: 'css' });
  await page.getByRole('button', { name: 'Park + parking brake', exact: true }).click();
  await expect(coach).toContainText('All 5 steps complete');
  await page.getByRole('button', { name: 'Reset practice', exact: true }).click();
  await expect(coach).toContainText('Step 1 of 5');
  await expect(coach).not.toContainText('Keep clear of the curb');
  expect(await page.evaluate(() => (window as any).__events.errors)).toEqual([]);
});
