#!/usr/bin/env node
/* Builds the shared classroom presenter and offline export runtime. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const ROOT = __dirname;
function buildWordPracticeModule() {
  const parts = ['word_practice_core.js', 'word_practice_media.js', 'word_practice_ui.js'];
  const body = parts.map(file => fs.readFileSync(path.join(ROOT, file), 'utf8')).join('\n\n');
  const output = '// Generated by _build_word_practice_module.js. Edit word_practice_{core,media,ui}.js.\n' +
    '(function () {\nif (window.AlloModules && window.AlloModules.WordPractice) return;\n' + body + '\n})();\n';
  new vm.Script(output, { filename: 'word_practice_module.js' });
  return output;
}
function writeWordPracticeModule(check) {
  const output = buildWordPracticeModule();
  for (const target of ['word_practice_module.js', 'desktop/web-app/public/word_practice_module.js']) {
    const filename = path.join(ROOT, target);
    const current = fs.existsSync(filename) ? fs.readFileSync(filename, 'utf8') : '';
    if (current === output) continue;
    if (check) throw new Error(target + ' differs from its sources. Run node _build_word_practice_module.js.');
    const temp = filename + '.' + process.pid + '.tmp';
    fs.writeFileSync(temp, output);
    fs.renameSync(temp, filename);
  }
  console.log(check ? 'Word practice build is current.' : 'Built word_practice_module.js and Desktop copy.');
}
if (require.main === module) writeWordPracticeModule(process.argv.includes('--check'));
module.exports = { buildWordPracticeModule, writeWordPracticeModule };
