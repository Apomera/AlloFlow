import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
import { mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

test.describe.configure({ mode: 'serial', retries: 0, timeout: 90000 });
const out = path.resolve('reports/micro-lab-deeper-inquiry-2026-09-27');
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_microbiology.js', toolId: 'microbiology', width: 1280, height: 960, layout: 'document' });
test.beforeAll(async () => { mkdirSync(out, { recursive: true }); await harness.start(); });
test.afterAll(async () => { await harness.stop(); });
test.afterEach(async ({ page }) => { await harness.unmount(page); });
async function mount(page: any, tab: string, seed = {}) {
  await page.setViewportSize({ width: 1280, height: 960 });
  await harness.mount(page, { microbiology: { tab, ...seed } }, undefined, { expectCanvas: false });
  await page.addStyleTag({ content: '#wrap{width:100%!important}body{margin:0;font-family:system-ui,sans-serif}button,input,select,textarea{font-family:inherit}' });
}
const state = (page: any) => page.evaluate(() => (window as any).__toolData.microbiology);
async function noOverflow(page: any) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true); }

test('investigates an ambiguous specimen, records bounded reasoning, and exports drafts', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await mount(page, 'mystery');
  await page.getByRole('button', { name: /F An honest unknown/ }).click();
  await page.getByRole('button', { name: '+ Size and shape', exact: true }).click();
  await page.getByRole('button', { name: '+ Cell structure and chemistry', exact: true }).click();
  await page.getByRole('button', { name: '+ Behavior and reproduction', exact: true }).click();
  await page.getByRole('radio', { name: 'Bacterium', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Cell structure and chemistry', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Behavior and reproduction', exact: true }).check();
  await page.getByRole('radio', { name: /^The evidence supports a broad group/ }).check();
  await page.getByRole('textbox', { name: 'My evidence and reasoning', exact: true }).fill('The cells lack nuclei and divide independently. Both domains fit; membrane chemistry or DNA evidence could distinguish them.');
  await page.getByRole('button', { name: 'Check my evidence', exact: true }).click();
  await expect(page.locator('.micro-mystery-review')).toContainText('Reconsider the classification');
  await expect(page.getByRole('button', { name: 'Record specimen report', exact: true })).toBeDisabled();
  await page.getByRole('radio', { name: 'Not enough evidence to distinguish bacteria from archaea', exact: true }).check();
  await page.getByRole('button', { name: 'Check my evidence', exact: true }).click();
  await page.getByRole('button', { name: 'Record specimen report', exact: true }).click();
  await expect(page.locator('.micro-mystery-progress')).toHaveText('1/6 reports recorded');
  const original = (await state(page)).mysteryLab.cases.unresolved.record;
  await page.getByRole('textbox', { name: 'My evidence and reasoning', exact: true }).fill('My next question is which membrane lipids this cell contains.');
  expect((await state(page)).mysteryLab.cases.unresolved.record).toEqual(original);
  await page.locator('.micro-mystery-header').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'mystery-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow(page);
  await page.screenshot({ path: path.join(out, 'mystery-phone.png') });
  await page.getByRole('button', { name: 'Practice with the microscope', exact: true }).click();
  await page.getByRole('tab', { name: 'Mystery specimens', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'My evidence and reasoning', exact: true })).toHaveValue(/next question/);
  const promise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download specimen reports', exact: true }).click();
  const download = await promise; await download.saveAs(path.join(out, 'specimen-report.txt'));
  const text = readFileSync(path.join(out, 'specimen-report.txt'), 'utf8');
  expect(text).toContain('Both domains fit'); expect(text).toContain('My next question');
  expect(text).toContain('Current cited observations');
  expect(text).toContain('Current conclusion about limits');
  expect(text).not.toContain('Freshwater drifter');
  const saved = await state(page); await harness.unmount(page);
  await page.evaluate(data => (window as any).__mount({ microbiology: data }), saved);
  await expect(page.locator('.micro-mystery-record')).toContainText('Both domains fit');
  expect(errors).toEqual([]);
});

test('sweeps one variable and keeps saved responses fixed while preparing another trial', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await mount(page, 'growthLab', { growthLab: { profile: 'ecoli', tempC: 37, pH: 7, oxygen: 100 } });
  await page.getByRole('button', { name: 'Use current conditions as control', exact: true }).click();
  await page.getByText('Explore one variable across a range', { exact: true }).click();
  await page.getByRole('button', { name: 'Run variable sweep', exact: true }).click();
  const saved = (await state(page)).growthInvestigation.sweep;
  await expect(page.locator('.micro-growth-sweep-table tbody tr')).toHaveCount(10);
  const curve = await page.locator('.micro-growth-sweep-figure path').getAttribute('d');
  await page.locator('.micro-growth-sweep-figure').screenshot({ path: path.join(out, 'growth-sweep-desktop.png') });
  await page.locator('#gl-tempC').focus(); await page.keyboard.press('Home');
  await page.getByLabel('Variable to sweep', { exact: true }).selectOption('oxygen');
  expect((await state(page)).growthInvestigation.sweep).toEqual(saved);
  expect(await page.locator('.micro-growth-sweep-figure path').getAttribute('d')).toBe(curve);
  await page.getByRole('button', { name: 'Use this setting as the next trial: Temperature 30 °C', exact: true }).click();
  expect((await state(page)).growthLab.tempC).toBe(30);
  expect((await state(page)).growthInvestigation.control.tempC).toBe(37);
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow(page);
  await page.locator('.micro-growth-sweep-figure').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'growth-sweep-phone.png') });
  const promise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download notebook', exact: true }).click();
  const download = await promise; await download.saveAs(path.join(out, 'sweep-notebook.txt'));
  expect(readFileSync(path.join(out, 'sweep-notebook.txt'), 'utf8')).toContain('Variable to sweep: Temperature');
  expect(errors).toEqual([]);
});

