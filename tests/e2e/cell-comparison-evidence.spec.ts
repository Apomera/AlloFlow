import {test,expect} from '@playwright/test';
import {GlHarness} from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_cell.js',toolId:'cell',width:1200,height:1000,appStyles:true});
test.beforeAll(()=>harness.start());test.afterAll(()=>harness.stop());test.afterEach(async({page})=>harness.destroy(page));
for(const width of [280,1200])test('collect reference evidence and preserve writing at '+width,async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.emulateMedia({reducedMotion:'reduce'});await page.setViewportSize({width,height:1000});
 await harness.mount(page,{cell:{mode:'compare',_cellPicked:true,_cellCategory:'browse'}},undefined,{expectCanvas:false});
 await page.addStyleTag({content:'body{background:#f8fafc}#wrap{width:100%;max-width:1200px;display:block}'});
 const lab=page.locator('[data-cell-comparison-lab]'),tray=lab.locator('[data-cell-compare-kept]');
 const movement=lab.getByRole('button',{name:'Keep Movement as evidence',exact:true});
 await movement.focus();await page.keyboard.press('Enter');
 await expect(movement).toBeFocused();await expect(movement).toHaveAttribute('aria-pressed','true');
 await lab.getByRole('button',{name:'Keep Cell organization as evidence',exact:true}).click();
 await expect(tray.locator('[data-cell-compare-kept-item]')).toHaveCount(2);
 for(const field of ['claim','evidence','reasoning']){
  const input=lab.getByLabel('Comparison '+field,{exact:true});
  await input.focus();await input.pressSequentially('Words stay separate. ',{delay:10});await input.press('Enter');await input.pressSequentially('Next line. ',{delay:10});
  await expect(input).toHaveValue('Words stay separate. \nNext line. ');
 }
 await expect(tray.locator('[data-cell-compare-kept-item]')).toHaveCount(2);
 await lab.getByRole('button',{name:'Shared descriptions',exact:true}).click();
 await expect(lab.locator('[data-cell-comparison-property=movement]')).toHaveCount(0);
 await expect(tray.locator('[data-cell-compare-kept-item=movement]')).toContainText('Pseudopod extension');
 await lab.getByRole('button',{name:'Swap organisms',exact:true}).click();
 await expect(tray.locator('[data-cell-compare-kept-item=movement] p').first()).toContainText('Paramecium: Ciliary propulsion');
 await expect(lab.getByLabel('Comparison claim',{exact:true})).toHaveValue('Words stay separate. \nNext line. ');
 await lab.getByRole('button',{name:'Compare cell organization',exact:true}).click();
 await expect(tray.locator('[data-cell-compare-kept-item]')).toHaveCount(0);
 await expect(lab.getByLabel('Comparison claim',{exact:true})).toHaveValue('');
 await lab.getByRole('button',{name:'Compare movement',exact:true}).click();
 await expect(tray.locator('[data-cell-compare-kept-item]')).toHaveCount(2);
 await expect(lab.getByLabel('Comparison evidence',{exact:true})).toHaveValue('Words stay separate. \nNext line. ');
 await lab.getByRole('button',{name:'Review kept evidence (2)',exact:true}).click();
 await expect(lab.locator('#cell-comparison-kept-title')).toBeFocused();
 expect(await tray.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
 await tray.screenshot({path:'reports/cell-comparison-evidence/evidence-'+width+'.png',scale:'css'});
 await lab.locator('[data-cell-comparison-property=movement]').screenshot({path:'reports/cell-comparison-evidence/kept-row-'+width+'.png',scale:'css'});
 await tray.getByRole('button',{name:'Remove Movement from kept evidence',exact:true}).click();
 await expect(lab.locator('#cell-comparison-kept-title')).toBeFocused();
 await expect(tray.locator('[data-cell-compare-kept-item]')).toHaveCount(1);
 await expect(movement).toHaveAttribute('aria-pressed','false');
 await expect(lab.getByLabel('Comparison evidence',{exact:true})).toHaveValue('Words stay separate. \nNext line. ');
 const downloaded=page.waitForEvent('download');await lab.getByRole('button',{name:'Download comparison report',exact:true}).click();
 const download=await downloaded,stream=await download.createReadStream();const chunks:Buffer[]=[];for await(const chunk of stream!)chunks.push(Buffer.from(chunk));
 const report=Buffer.concat(chunks).toString('utf8');const kept=report.split('KEPT REFERENCE EVIDENCE\n')[1].split('CLAIM')[0];
 expect(kept).toContain('Cell organization');expect(kept).not.toContain('Movement');expect(report).toContain('Words stay separate. \nNext line. ');
 await tray.getByRole('button',{name:'Remove Cell organization from kept evidence',exact:true}).click();
 await expect(lab.locator('#cell-comparison-kept-title')).toBeFocused();await expect(tray).toContainText('Choose Keep as evidence');
 await expect(lab.getByLabel('Comparison reasoning',{exact:true})).toHaveValue('Words stay separate. \nNext line. ');
 expect(errors).toEqual([]);
});
