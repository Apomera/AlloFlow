#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');
const write = require('./dev-tools/write_generated_atomic.cjs');
const source = fs.readFileSync(path.join(__dirname, 'lesson_teaching_script_source.jsx'), 'utf8');
const result = babel.transformSync(source, { babelrc: false, configFile: false, sourceType: 'script', comments: true, generatorOpts: { jsescOption: { minimal: true } } });
if (!result?.code) throw new Error('Teaching-script module compilation failed.');
const output = '/* Generated by _build_lesson_teaching_script_module.js; edit the source file. */\n' + result.code + '\n';
const destinations = ['lesson_teaching_script_module.js', 'desktop/web-app/public/lesson_teaching_script_module.js'].map(file => path.join(__dirname, file));
if (process.argv.includes('--check')) {
  const stale = destinations.filter(file => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output);
  if (stale.length) { console.error('Teaching-script generated files are stale: ' + stale.join(', ')); process.exitCode = 1; }
  else console.log('Teaching-script module and mirror are current.');
} else {
  destinations.forEach(file => write(file, output));
  console.log('Built teaching-script module and desktop public mirror.');
}
