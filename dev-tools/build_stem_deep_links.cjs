#!/usr/bin/env node
// build_stem_deep_links.cjs — generate the STEM tool deep-link surface from tool_index.json.
//
// Why this exists:
//   The Cloudflare shell deep link (2026-08-15) shipped with a one-tool allowlist:
//   /water-cycle -> /app/?tool=waterCycle, and _alloReadShellDeepLinkTool hardcoded
//   'watercycle'. Distribution wants a shareable URL per tool (~142 of them), and a
//   hand-kept list of 142 slugs would rot the day a tool is added or renamed. So both
//   artifacts are generated from the same registry the app itself uses:
//
//     tool_index.json  (dev-tools/build_tool_index.cjs, the capability index)
//        │
//        ├─> _redirects + desktop/web-app/public/_redirects
//        │     /<slug>  /app/?tool=<id>  302        (one line per tool, generated block)
//        │
//        └─> AlloFlowANTI.txt  _ALLO_STEM_DEEP_LINK_MAP  (marker-delimited generated
//              const: normalized-request -> canonical tool id, so the reader validates
//              any ?tool= / path form synchronously at boot with no fetch)
//
// Slug rule: camelCase id -> kebab (waterCycle -> water-cycle). The generator asserts
// slug uniqueness and refuses to write anything on a collision.
//
// The generated ANTI block is inside marker comments and replaced wholesale, same
// pattern as the docsuite theme block. The map literal is emitted with NO backticks,
// NO ${, and NO backslashes — it does not currently sit in a template literal, but
// the docsuite incident (a generated backtick terminating a JSX template literal)
// makes that a standing rule for every generated-into-source block in this repo.
//
// Cloudflare Pages allows 2,000 static redirects; ~142 is nowhere near the limit.
//
// Usage:
//   node dev-tools/build_stem_deep_links.cjs           # regenerate both artifacts
//   node dev-tools/build_stem_deep_links.cjs --check   # exit 1 if anything is stale
//   node dev-tools/build_stem_deep_links.cjs --list    # print slug -> id table
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const INDEX = path.join(ROOT, 'tool_index.json');
const ANTI = path.join(ROOT, 'AlloFlowANTI.txt');
const REDIRECTS = [path.join(ROOT, '_redirects'), path.join(ROOT, 'desktop', 'web-app', 'public', '_redirects')];

const CHECK = process.argv.includes('--check');
const LIST = process.argv.includes('--list');

const BEGIN_RE = /\/\/ __ALLO_STEM_DEEP_LINKS_BEGIN__[^\n]*\n/;
const END_MARK = '// __ALLO_STEM_DEEP_LINKS_END__';
const RD_BEGIN = '# __ALLO_STEM_DEEP_LINKS_BEGIN__ (generated by dev-tools/build_stem_deep_links.cjs — do not hand-edit this block)';
const RD_END = '# __ALLO_STEM_DEEP_LINKS_END__';

function kebab(id) {
  return String(id)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .toLowerCase();
}
function normKey(s) {
  return String(s).trim().toLowerCase().replace(/[\s_-]+/g, '');
}

function loadTools() {
  const index = JSON.parse(fs.readFileSync(INDEX, 'utf8'));
  const tools = index.tools || [];
  if (!Array.isArray(tools) || tools.length < 50) {
    throw new Error('tool_index.json looks wrong (' + tools.length + ' tools) — refusing to generate from a broken registry. Rebuild it with dev-tools/build_tool_index.cjs first.');
  }
  const rows = tools
    .filter((t) => t && t.id)
    .map((t) => ({ id: String(t.id), slug: kebab(t.id), label: String(t.label || t.id) }))
    .sort((a, b) => a.slug.localeCompare(b.slug));
  const seen = new Map();
  // Paths already meaning something on the Pages site. A tool slug landing on one
  // of these would shadow a real page (the reader also treats the LAST path
  // segment as a candidate, so 'app' or 'guide' as a tool id would misfire).
  const RESERVED = new Set(['app', 'guide', 'tools', 'launch', 'catalog', 'stem-lab', 'video-studio', 'it-coach', 'test-prep']);
  for (const r of rows) {
    if (seen.has(r.slug)) throw new Error('Slug collision: "' + r.slug + '" from ids ' + seen.get(r.slug) + ' and ' + r.id);
    seen.set(r.slug, r.id);
    if (/[^a-z0-9-]/.test(r.slug)) throw new Error('Slug "' + r.slug + '" (id ' + r.id + ') contains characters unsafe in a path.');
    if (RESERVED.has(r.slug)) throw new Error('Slug "' + r.slug + '" (id ' + r.id + ') shadows a reserved site path.');
  }
  return rows;
}

function redirectsBlock(rows) {
  const lines = [RD_BEGIN];
  for (const r of rows) lines.push('/' + r.slug + ' /app/?tool=' + r.id + ' 302');
  lines.push(RD_END);
  return lines.join('\n');
}

function antiBlock(rows) {
  // normalized request -> canonical id. Both the slug and the raw id normalize to the
  // same key for most tools, but not all (kebab inserts hyphens that normalization
  // strips either way), so one entry per tool covers /water-cycle, ?tool=waterCycle,
  // ?tool=watercycle, and ?tool=water_cycle alike.
  const pairs = rows.map((r) => "'" + normKey(r.id) + "': '" + r.id + "'");
  const body = [];
  for (let i = 0; i < pairs.length; i += 4) body.push('  ' + pairs.slice(i, i + 4).join(', '));
  return (
    '// __ALLO_STEM_DEEP_LINKS_BEGIN__ (generated by dev-tools/build_stem_deep_links.cjs from tool_index.json — do not hand-edit; run the generator)\n' +
    'const _ALLO_STEM_DEEP_LINK_MAP = {\n' + body.join(',\n') + '\n};\n' +
    END_MARK
  );
}

function upsert(content, block, beginRe, endMark, insertAfterRe) {
  const beginMatch = content.match(beginRe);
  if (beginMatch) {
    const start = beginMatch.index;
    const end = content.indexOf(endMark, start);
    if (end < 0) throw new Error('Found a BEGIN marker with no END marker — refusing to guess the block extent.');
    return content.slice(0, start) + block + content.slice(end + endMark.length);
  }
  const anchor = content.match(insertAfterRe);
  if (!anchor) throw new Error('Neither markers nor the insertion anchor found.');
  const at = anchor.index + anchor[0].length;
  return content.slice(0, at) + block + '\n' + content.slice(at);
}

function main() {
  const rows = loadTools();
  if (LIST) {
    for (const r of rows) console.log('/' + r.slug.padEnd(28) + ' -> ' + r.id + '   (' + r.label + ')');
    console.log(rows.length + ' tools');
    return 0;
  }

  let stale = 0;

  // _redirects (both copies)
  for (const rd of REDIRECTS) {
    const current = fs.existsSync(rd) ? fs.readFileSync(rd, 'utf8') : '';
    const block = redirectsBlock(rows);
    let next;
    if (current.includes(RD_BEGIN)) {
      const start = current.indexOf(RD_BEGIN);
      const end = current.indexOf(RD_END, start);
      if (end < 0) throw new Error(rd + ': BEGIN without END');
      next = current.slice(0, start) + block + current.slice(end + RD_END.length);
    } else {
      // Replace the original hand-written water-cycle line with the generated block
      // (the generated block contains the same rule), keep anything else.
      const kept = current
        .split('\n')
        .filter((l) => l.trim() && !/^\/water-cycle\s/.test(l))
        .join('\n');
      next = (kept ? kept + '\n' : '') + block + '\n';
    }
    if (next !== current) {
      stale++;
      if (!CHECK) fs.writeFileSync(rd, next);
    }
  }

  // ANTI map
  const anti = fs.readFileSync(ANTI, 'utf8');
  const block = antiBlock(rows);
  if (/[`\\]|\$\{/.test(block)) throw new Error('Generated ANTI block contains a backtick, backslash, or ${ — refusing.');
  const nextAnti = upsert(anti, block, BEGIN_RE, END_MARK, /const _alloRequestStemPlugin[\s\S]*?\n\};\n/);
  if (nextAnti !== anti) {
    stale++;
    if (!CHECK) fs.writeFileSync(ANTI, nextAnti);
  }

  if (CHECK) {
    if (stale) {
      console.error('build_stem_deep_links: STALE (' + stale + ' artifact(s) differ). Run: node dev-tools/build_stem_deep_links.cjs');
      return 1;
    }
    console.log('build_stem_deep_links: current (' + rows.length + ' tools).');
    return 0;
  }
  console.log('build_stem_deep_links: wrote ' + rows.length + ' deep links into _redirects (x2) and the ANTI map' + (stale ? '' : ' (already current)') + '.');
  return 0;
}

process.exit(main());
