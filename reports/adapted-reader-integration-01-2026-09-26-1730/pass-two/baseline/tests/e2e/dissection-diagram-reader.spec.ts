import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { GlHarness } from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_dissection.js',toolId:'dissection',width:1180,height:900,appStyles:true,preScripts:['stem_lab/stem_lab_module.js']});
const out='reports/dissection-enhancement-2026-09-08';
test.beforeAll(async()=>{await harness.start();await mkdir(out,{recursive:true});});
test.afterAll(async()=>{await harness.stop();});
const base={specimen:'frog',_dissLoadedSpec:'frog',activeLayer:'organs',anatomicalView:'internal',selectedOrgan:'lungs',compareMode:true,reducedMotion:true,soundEnabled:false,organNotes:{'frog|lungs':'A visible sac beside the heart.'},organConfidence:{'frog|lungs':2},exploredOrgans:{'frog|lungs':true},quizScore:1,quizTotal:2};
const snapshot=async(page:any)=>page.evaluate(()=>{const d=(window as any).__ctx.toolData.dissection;return {specimen:d.specimen,layer:d.activeLayer,selected:d.selectedOrgan,compare:d.compareMode,zoom:d.canvasZoom,notes:d.organNotes,confidence:d.organConfidence,explored:d.exploredOrgans,score:d.quizScore,total:d.quizTotal};});
test('diagram reading view zooms independently, traps focus, and restores its opener on Escape',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await harness.mount(page,{dissection:base},undefined,{expectCanvas:false});
  const before=await snapshot(page);
  const opener=page.locator('[data-comparison-specimen="perch"] [data-diagram-open]');await opener.focus();await page.keyboard.press('Enter');
  const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();
  const close=dialog.getByRole('button',{name:'Close diagram'});await expect(close).toBeFocused();
  await expect(dialog).toContainText('two fluids do not mix');await expect(dialog.getByRole('img')).toHaveAccessibleName(/Perch gill concept/);
  await dialog.getByRole('button',{name:'Zoom in',exact:true}).click();await expect(dialog.locator('[data-diagram-zoom]')).toHaveText('150%');
  const viewport=dialog.getByRole('region',{name:'Scrollable diagram'});
  expect(await viewport.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true);
  await viewport.focus();await page.keyboard.press('Tab');await expect(close).toBeFocused();
  await page.keyboard.press('Shift+Tab');await expect(viewport).toBeFocused();
  for(let i=0;i<3;i++)await dialog.getByRole('button',{name:'Zoom in',exact:true}).click();
  await expect(dialog.locator('[data-diagram-zoom]')).toHaveText('300%');await expect(dialog.getByRole('button',{name:'Zoom in',exact:true})).toBeDisabled();
  await dialog.getByRole('button',{name:'Fit diagram'}).click();await expect(dialog.locator('[data-diagram-zoom]')).toHaveText('100%');
  expect(await viewport.evaluate(el=>el.scrollHeight-el.clientHeight)).toBeLessThanOrEqual(2);
  expect(await viewport.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
  await dialog.screenshot({path:out+'/diagram-reader-desktop.png'});
  await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);await expect(opener).toBeFocused();
  expect(await snapshot(page)).toEqual(before);expect(errors).toEqual([]);
});
test('diagram reading view supports phone zoom, keyboard pan, accessible text, and close',async({page})=>{
  await page.setViewportSize({width:320,height:844});
  await harness.mount(page,{dissection:{...base,selectedOrgan:'heart'}},undefined,{expectCanvas:false});
  await page.addStyleTag({content:'#wrap { width:100% !important; max-width:1180px; }'});
  const before=await snapshot(page);const opener=page.locator('[data-comparison-specimen="earthworm"] [data-diagram-open]');await opener.click();
  const dialog=page.getByRole('dialog');await expect(dialog).toContainText('five pairs');
  await dialog.getByRole('button',{name:'Zoom in',exact:true}).click();await dialog.getByRole('button',{name:'Zoom in',exact:true}).click();
  await expect(dialog.locator('[data-diagram-zoom]')).toHaveText('200%');
  const viewport=dialog.getByRole('region',{name:'Scrollable diagram'});await viewport.focus();await page.keyboard.press('ArrowRight');
  await expect.poll(()=>viewport.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0);
  const bounds=await dialog.evaluate(el=>({left:el.getBoundingClientRect().left,right:el.getBoundingClientRect().right,overflow:el.scrollWidth-el.clientWidth}));
  expect(bounds.left).toBeGreaterThanOrEqual(0);expect(bounds.right).toBeLessThanOrEqual(320);expect(bounds.overflow).toBeLessThanOrEqual(1);
  await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
  const audit=await page.evaluate(async()=>(window as any).axe.run({include:[['dialog']]},{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
  expect(audit.violations.map((v:any)=>({id:v.id,targets:v.nodes.map((n:any)=>n.target)}))).toEqual([]);
  await dialog.screenshot({path:out+'/diagram-reader-mobile.png'});
  await dialog.locator('.diss-diagram-reader__scope').scrollIntoViewIfNeeded();
  await dialog.screenshot({path:out+'/diagram-reader-mobile-text.png'});
  await dialog.getByRole('button',{name:'Close diagram'}).click();await expect(dialog).toHaveCount(0);await expect(opener).toBeFocused();
  expect(await snapshot(page)).toEqual(before);
  await opener.click();await expect(page.locator('[data-diagram-zoom]')).toHaveText('100%');await page.keyboard.press('Escape');
});
