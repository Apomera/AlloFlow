#!/usr/bin/env node
/**
 * Build dispro_analyzer_module.js from dispro_analyzer_source.jsx
 * (Disproportionality Analyzer — admin tool, Aug 2026.)
 *
 * Mirrors _build_udl_walkthrough_module.js: esbuild JSX -> createElement,
 * IIFE wrapper with a11y live region, writes dispro_analyzer_module.js +
 * syncs to desktop/web-app/public/.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'dispro_analyzer_source.jsx');
const OUTPUT = path.join(ROOT, 'dispro_analyzer_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'dispro_analyzer_module.js');
const TMP = path.join(ROOT, '_tmp_dispro_analyzer_entry.jsx');

if (!fs.existsSync(SOURCE)) { console.error('Source not found:', SOURCE); process.exit(1); }

const source = fs.readFileSync(SOURCE, 'utf-8');
const entry = `/* global React */\n\n${source}\n\nwindow.__disproAnalyzerExports = { DisproAnalyzerPanel, DisproChart, DisproResults, DisproTrendChart, disproCompute, disproParsePaste, disproResultCsv, disproFmtPct, disproFmtRatio, disproTrendSeries, disproNormalizeAlt, DISPRO_OUTCOME_PRESETS };\n`;
fs.writeFileSync(TMP, entry, 'utf-8');

console.log('Compiling dispro_analyzer_source.jsx with esbuild...');
try {
    execSync(`npx esbuild "${TMP}" --bundle=false --format=esm --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment --outfile="${TMP}.compiled.js" --target=es2020 --charset=utf8`, { cwd: ROOT, stdio: 'inherit' });
} catch (e) {
    console.error('esbuild failed');
    try { fs.unlinkSync(TMP); } catch(_) {}
    process.exit(1);
}

const compiled = fs.readFileSync(TMP + '.compiled.js', 'utf-8')
    .replace(/\/\*.*global.*\*\/\n/g, '')
    .replace(/window\.__disproAnalyzerExports\s*=\s*\{[^}]+\};?\s*/, '')
    .trim();

fs.unlinkSync(TMP);
fs.unlinkSync(TMP + '.compiled.js');

const outputCode = `/**
 * AlloFlow Disproportionality Analyzer Module
 *
 * Auto-generated by _build_dispro_analyzer_module.js — DO NOT EDIT MANUALLY.
 * Source: dispro_analyzer_source.jsx
 *
 * Risk index / risk ratio / composition metrics over aggregate counts,
 * computed entirely on-device. Descriptive only: flags instability, never
 * declares a formal finding (state thresholds under 34 CFR 300.647).
 */
(function() {
  'use strict';
  if (window.AlloModules && window.AlloModules.DisproAnalyzer) {
    console.log('[CDN] DisproAnalyzer already loaded, skipping');
    return;
  }
  (function() {
    if (document.getElementById('allo-live-dispro')) return;
    var liveRegion = document.createElement('div');
    liveRegion.id = 'allo-live-dispro';
    liveRegion.setAttribute('aria-live', 'polite');
    liveRegion.setAttribute('aria-atomic', 'true');
    liveRegion.setAttribute('role', 'status');
    liveRegion.className = 'sr-only';
    liveRegion.style.cssText = 'position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);border:0';
    document.body.appendChild(liveRegion);
  })();
  var React = window.React;
  if (!React) { console.error('[DisproAnalyzer] React not found on window'); return; }

${compiled}

  window.AlloModules = window.AlloModules || {};
  window.AlloModules.DisproAnalyzer = {
    DisproAnalyzerPanel: DisproAnalyzerPanel,
    // Pure seams exposed for unit tests + render smoke. Not public contract.
    _testing: {
      disproCompute: disproCompute,
      disproParsePaste: disproParsePaste,
      disproResultCsv: disproResultCsv,
      disproFmtPct: disproFmtPct,
      disproFmtRatio: disproFmtRatio,
      DisproChart: DisproChart,
      DisproResults: DisproResults,
      DisproTrendChart: DisproTrendChart,
      disproTrendSeries: disproTrendSeries,
      disproNormalizeAlt: disproNormalizeAlt,
      DISPRO_OUTCOME_PRESETS: DISPRO_OUTCOME_PRESETS
    }
  };
  console.log('[CDN] DisproAnalyzer loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
    if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
    fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
    console.log(`Synced to ${DEPLOY_OUT}`);
} catch (e) {
    console.warn('[DisproAnalyzer] Could not sync to desktop/web-app/public/:', e.message);
}
console.log(`Built ${OUTPUT} (${outputCode.split('\n').length} lines)`);
