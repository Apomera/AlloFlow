import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_ecosystem.js',toolId:'ecosystem',width:1100,height:900,appStyles:true});
test.beforeAll(async()=>harness.start());test.afterAll(async()=>harness.stop());test.afterEach(async({page})=>harness.destroy(page));
test('expanded woodland offers landscape and clearing views without changing the model',async({page})=>{
  await page.setViewportSize({width:1140,height:1050});
  await harness.mount(page,{ecosystem:{tab:'foodweb',tutorialDismissed:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.body.className='theme-default';document.getElementById('wrap')!.style.cssText='width:100%;height:auto;display:block;padding:16px;background:white';});
  await page.getByRole('button',{name:'Habitat restoration',exact:true}).click();
  const meadow=page.locator('[data-efw-meadow]'),canvas=meadow.locator('canvas'),stage=meadow.locator('.efw-meadow-stage');
  await expect(canvas).toHaveAttribute('data-camera-mode','habitat');
  expect(Number(await canvas.getAttribute('data-forest-trees'))).toBeGreaterThan(100);
  await expect(canvas).toHaveAttribute('data-landscape-span','100 x 86 scene units');
  await expect(canvas).toHaveAttribute('data-biomass-rabbits','35');
  await stage.screenshot({path:'reports/ecosystem-woodland/clearing.png'});
  const setup=await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb));
  await meadow.getByRole('button',{name:'Forest overview',exact:true}).focus();
  await meadow.getByRole('button',{name:'Forest overview',exact:true}).press('Enter');
  await expect(canvas).toHaveAttribute('data-camera-mode','forest');
  await stage.screenshot({path:'reports/ecosystem-woodland/forest-overview.png'});
  expect(await page.evaluate(()=>JSON.stringify((window as any).__toolData.ecosystem.foodWeb))).toBe(setup);
  await meadow.getByRole('button',{name:'Rotate left',exact:true}).click();
  await stage.screenshot({path:'reports/ecosystem-woodland/forest-rotated.png'});
  await meadow.getByRole('button',{name:'Reset camera',exact:true}).click();
  await meadow.getByRole('button',{name:/Red foxes\s/}).click();
  await meadow.getByRole('button',{name:'Inspect selected group',exact:true}).click();
  await stage.screenshot({path:'reports/ecosystem-woodland/foxes-clearing.png'});
  await page.setViewportSize({width:390,height:844});
  await stage.screenshot({path:'reports/ecosystem-woodland/mobile-detail.png'});
  await meadow.getByRole('button',{name:'Reset camera',exact:true}).click();
  await stage.screenshot({path:'reports/ecosystem-woodland/mobile-clearing.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('button',{name:'Run food-web comparison',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-refuge-cover','50');
  await meadow.getByRole('button',{name:'Forest overview',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-refuge-cover','50');
  await expect(canvas).toHaveAttribute('data-step','240');
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
