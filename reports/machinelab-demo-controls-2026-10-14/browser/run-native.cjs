// Run demo-controls browser QA once and preserve bounded native completion evidence.
const fs=require('fs'),path=require('path'),cp=require('child_process'),crypto=require('crypto');
const root=path.resolve(__dirname,'../../..'),run=process.argv[2]||'run-01';
if(!/^run-\d{2}$/.test(run))throw Error('Use an explicit run-NN evidence directory.');
const out=path.join(__dirname,run);
if(fs.existsSync(out))throw Error('Refusing to overwrite existing evidence: '+out);
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex');
const frozen='f253abaf842de6a16003053526359561b78b3cea1412a9e07f8eb302f1715d7d';
const sources=['stem_lab/stem_tool_machinelab.js','desktop/web-app/public/stem_lab/stem_tool_machinelab.js'];
const runners=['dev-tools/ml_demo_controls_visual_qa.cjs','reports/machinelab-demo-controls-2026-10-14/browser/run-native.cjs'];
const args=['dev-tools/ml_demo_controls_visual_qa.cjs',out];
const before=sources.map(file=>({file,sha256:sha(file)})),startedAt=new Date().toISOString();
if(before.some(row=>row.sha256!==frozen))throw Error('Source or mirror differs from the frozen candidate.');
const runnerBefore=runners.map(file=>({file,sha256:sha(file)}));
fs.mkdirSync(out);
const options='--max-old-space-size=512 --max-semi-space-size=8';
const result=cp.spawnSync(process.execPath,args,{cwd:root,env:{...process.env,NODE_OPTIONS:options},encoding:'utf8',timeout:300000,maxBuffer:8*1024*1024});
fs.writeFileSync(path.join(out,'stdout.log'),(result.stdout||'').replace(/\r\n/g,'\n').trimEnd()+'\n');
fs.writeFileSync(path.join(out,'stderr.log'),result.stderr?(result.stderr.replace(/\r\n/g,'\n').trimEnd()+'\n'):'');
const after=sources.map(file=>({file,sha256:sha(file)})),runnerAfter=runners.map(file=>({file,sha256:sha(file)}));
const unchanged=after.every(row=>row.sha256===frozen)&&JSON.stringify(runnerBefore)===JSON.stringify(runnerAfter);
const receipt={startedAt,completedAt:new Date().toISOString(),command:process.execPath,args,nodeOptions:options,timeoutMs:300000,exitCode:result.status,signal:result.signal,error:result.error?String(result.error):null,frozenSourceSha256:frozen,unchanged,sourceBefore:before,sourceAfter:after,runnerBefore,runnerAfter};
fs.writeFileSync(path.join(out,'native-exit.json'),JSON.stringify(receipt,null,2)+'\n');
process.stdout.write(result.stdout||'');process.stderr.write(result.stderr||'');console.log(JSON.stringify(receipt,null,2));
if(result.error||result.signal||result.status!==0||!unchanged)process.exitCode=1;
