const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const sha = bytes => require('node:crypto').createHash('sha256').update(bytes).digest('hex');
process.chdir(path.resolve(__dirname, '../../..'));
const candidate = JSON.parse(fs.readFileSync(path.join(__dirname, 'candidate.json'), 'utf8'));
const frozen = JSON.parse(fs.readFileSync('reports/alloflow-resume-2026-10-01/readiness-integration/source-freeze.json', 'utf8'));
const source = 'view_word_sounds_preview_source.jsx', file = 'view_word_sounds_preview_module.js';
assert.equal(sha(fs.readFileSync(source)), frozen[source].sha256, 'Preview source not frozen');
for (const target of [file, 'desktop/web-app/public/' + file, 'desktop/web-app/build/' + file]) assert.equal(sha(fs.readFileSync(target)), candidate.files.find(row => row.file === file).sha256, 'Concurrent generated change: ' + target);
cp.execFileSync(process.execPath, ['_build_view_word_sounds_preview_module.js'], { encoding: 'utf8', stdio: 'pipe' });
assert.equal(sha(fs.readFileSync(source)), frozen[source].sha256, 'Source changed during Preview build');
const output = fs.readFileSync(file);
assert(output.equals(fs.readFileSync('desktop/web-app/public/' + file)));
new vm.Script(output.toString('utf8'));
const buildFile = 'desktop/web-app/build/' + file;
assert.equal(sha(fs.readFileSync(buildFile)), candidate.files.find(row => row.file === file).sha256);
const temporary = buildFile + '.readiness-' + process.pid + '.tmp';
fs.writeFileSync(temporary, output); fs.renameSync(temporary, buildFile);
candidate.files = candidate.files.map(row => ({ ...row, sha256: sha(fs.readFileSync(row.file)), bytes: fs.statSync(row.file).size }));
candidate.mirrors = candidate.mirrors.map(row => ({ ...row, sha256: sha(fs.readFileSync(row.file)) }));
candidate.checkedAt = new Date().toISOString(); candidate.head = cp.execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
candidate.previewKeyboardFixRebuiltOnlyPreview = true;
fs.writeFileSync(path.join(__dirname, 'candidate.json'), JSON.stringify(candidate, null, 2) + '\n');
const proposalsPath = path.join(__dirname, 'pin-proposals.json');
const proposals = JSON.parse(fs.readFileSync(proposalsPath, 'utf8'));
const digest = sha(output);
const proposal = proposals.find(row => row.module === file); proposal.sha256 = digest; proposal.proposedUrl = 'https://alloflow-cdn.pages.dev/' + file + '?v=' + digest.slice(0, 8);
fs.writeFileSync(proposalsPath, JSON.stringify(proposals, null, 2) + '\n');
console.log(JSON.stringify({ state: 'Preview-only-rebuild-complete', moduleSha256: digest, sourceSha256: frozen[source].sha256, mirrorsEqual: true }));
