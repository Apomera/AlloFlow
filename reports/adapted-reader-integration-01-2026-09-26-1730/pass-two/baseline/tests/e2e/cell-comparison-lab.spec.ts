import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness = new GlHarness({ toolFile: 'stem_lab/stem_tool_cell.js', toolId: 'cell', width: 1100, height: 900, appStyles: true });
test.beforeAll(async () => harness.start());
test.afterAll(async () => harness.stop());
test('comparison search, filters, pair drafts, and report work on desktop and phone', async ({ page }) => {
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await harness.mount(page, { cell: { mode: 'compare', _cellPicked: true, _cellCategory: 'browse', _cmpA: 99999, _cmpB: -1 } }, undefined, { expectCanvas: false });
  const lab = page.locator('[data-cell-comparison-lab]');
  await expect(lab).toBeVisible();
  await expect(lab.getByLabel('Organism A', { exact: true })).toHaveValue('0');
  await expect(lab.getByLabel('Organism B', { exact: true })).toHaveValue('1');
  await lab.getByLabel('Find organisms').fill('no-such-organism');
  await expect(lab).toContainText('0 matches. Current selections stay available.');
  await expect(lab.getByLabel('Organism A', { exact: true })).toHaveValue('0');
  await lab.getByLabel('Find organisms').fill('bacteria');
  await expect(lab.getByLabel('Organism A', { exact: true }).locator('option')).toContainText(['Amoeba', 'E. coli']);
  await lab.getByRole('button', { name: 'Compare movement', exact: true }).click();
  await lab.getByLabel('Comparison claim', { exact: true }).fill('These organisms move differently.');
  await lab.getByLabel('Comparison evidence', { exact: true }).fill('Amoeba uses pseudopods; Paramecium uses cilia.');
  await lab.getByRole('button', { name: 'Swap organisms', exact: true }).click();
  await expect(lab.getByLabel('Comparison claim', { exact: true })).toHaveValue('These organisms move differently.');
  await lab.getByRole('button', { name: 'Compare cell organization', exact: true }).click();
  await expect(lab.getByLabel('Comparison claim', { exact: true })).toHaveValue('');
  await lab.getByRole('button', { name: 'Compare movement', exact: true }).click();
  await expect(lab.getByLabel('Comparison claim', { exact: true })).toHaveValue('These organisms move differently.');
  await lab.getByRole('button', { name: 'Shared descriptions', exact: true }).click();
  await expect(lab.locator('[data-cell-comparison-property="cellType"]')).toBeVisible();
  await expect(lab.locator('[data-cell-comparison-property="movement"]')).toHaveCount(0);
  const downloaded = page.waitForEvent('download');
  await lab.getByRole('button', { name: 'Download comparison report', exact: true }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toBe('cell-comparison.txt');
  const stream = await download.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const report = Buffer.concat(chunks).toString('utf8');
  expect(report).toContain('These organisms move differently.');
  expect(report).toContain('Movement (different)');
  await lab.screenshot({ path: 'reports/cell-enhancement/comparison-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addStyleTag({ content: '#wrap { width:100%; }' });
  await lab.getByRole('button', { name: 'All properties', exact: true }).click();
  expect(await lab.evaluate(el => el.getBoundingClientRect().width)).toBeLessThanOrEqual(390);
  expect(await lab.evaluate(el => el.scrollWidth > el.clientWidth + 2)).toBe(false);
  await lab.screenshot({ path: 'reports/cell-enhancement/comparison-phone.png' });
  await lab.getByLabel('Organism B', { exact: true }).selectOption('0');
  await expect(lab).toContainText('You selected the same organism twice.');
  await lab.getByRole('button', { name: 'Differences', exact: true }).click();
  await expect(lab).toContainText('No properties match this filter.');
  expect(errors).toEqual([]);
});
