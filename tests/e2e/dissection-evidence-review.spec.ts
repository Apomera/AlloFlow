import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { GlHarness } from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_dissection.js',toolId:'dissection',width:1180,height:900,appStyles:true,preScripts:['stem_lab/stem_lab_module.js']});
const out='reports/dissection-enhancement-2026-09-08';
test.beforeAll(async()=>{await harness.start();await mkdir(out,{recursive:true});});
test.afterAll(async()=>{await harness.stop();});
const base={specimen:'frog',_dissLoadedSpec:'frog',activeLayer:'organs',anatomicalView:'internal',selectedOrgan:'heart',reducedMotion:true,soundEnabled:false,exploredOrgans:{'frog|heart':true},verifiedIdentifications:{'frog|heart':true},quizScore:1,quizTotal:2};
test('draft review and reference starter preserve evidence, confidence, and keyboard focus',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const note='I observed. It is located. This supports the identification because.';
  await harness.mount(page,{dissection:{...base,organNotes:{'frog|heart':note},organConfidence:{'frog|heart':3}}},undefined,{expectCanvas:false});
  const form=page.locator('[data-dissection-evidence]');
  const before=await page.evaluate(()=>{const d=(window as any).__ctx.toolData.dissection;return {explored:d.exploredOrgans,verified:d.verifiedIdentifications,score:d.quizScore,total:d.quizTotal,confidence:d.organConfidence};});
  await expect(form.locator('[data-evidence-draft]')).toHaveAttribute('data-evidence-draft','present');
  await expect(form).toContainText('Draft present · review needed');
  await expect(form.getByRole('progressbar')).toHaveCount(0);
  const summary=form.locator('[data-evidence-review] summary');await summary.focus();await page.keyboard.press('Enter');
  await expect(summary).toBeFocused();await expect(form.locator('.diss-draft-review__steps')).toBeVisible();
  const starter=form.locator('[data-evidence-starter="reference"]');await starter.focus();await page.keyboard.press('Enter');
  await expect(page.locator('#diss-note-heart')).toBeFocused();
  await expect(page.locator('#diss-note-heart')).toHaveValue(note+'\nThe reference states ');
  await starter.click();await expect(page.locator('#diss-note-heart')).toHaveValue(note+'\nThe reference states ');
  expect(await page.evaluate(()=>{const d=(window as any).__ctx.toolData.dissection;return {explored:d.exploredOrgans,verified:d.verifiedIdentifications,score:d.quizScore,total:d.quizTotal,confidence:d.organConfidence};})).toEqual(before);
  await form.screenshot({path:out+'/evidence-draft-desktop.png'});expect(errors).toEqual([]);
});
test('phone draft guidance is accessible, ungraded, and usable before writing',async({page})=>{
  await page.setViewportSize({width:320,height:844});
  await harness.mount(page,{dissection:base},undefined,{expectCanvas:false});
  await page.addStyleTag({content:'#wrap { width:100% !important; max-width:1180px; }'});
  const form=page.locator('[data-dissection-evidence]');
  await expect(form).toContainText('Note not started');await expect(form).toContainText('Confidence not rated');
  await form.locator('[data-evidence-review] summary').click();
  await form.locator('[data-evidence-countercheck] summary').click();
  await expect(form.locator('[data-evidence-countercheck-action]')).toBeEnabled();
  await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
  const audit=await page.evaluate(async()=>(window as any).axe.run({include:[['[data-dissection-evidence]']]},{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
  expect(audit.violations.map((v:any)=>({id:v.id,targets:v.nodes.map((n:any)=>n.target)}))).toEqual([]);
  expect(await form.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
  await form.screenshot({path:out+'/evidence-draft-mobile.png'});
  await form.locator('[data-evidence-countercheck-action]').click();await expect(page.locator('#diss-note-heart')).toBeFocused();
  await expect(page.locator('#diss-note-heart')).toHaveValue('I would revise this identification if I observed ');
  await expect(form).toContainText('Draft present · review needed');
  expect(await page.evaluate(()=>(window as any).__ctx.toolData.dissection.quizScore)).toBe(1);
});
