import { test, expect } from '@playwright/test';
import { GlHarness } from './helpers/stem_gl_harness';
const harness=new GlHarness({toolFile:'stem_lab/stem_tool_roadready.js',toolId:'roadReady',width:1100,height:780,appStyles:true,preScripts:['stem_lab/stem_lab_module.js'],probes:'window.__testHooks={};'});
test.beforeAll(async()=>{await harness.start();});test.afterAll(async()=>{await harness.stop();});test.afterEach(async({page})=>{await harness.destroy(page);});

for(const view of ['threePoint','backingDrill'])test(view+' supports controller motion, safe reset, settings suspension and interruption',async({page})=>{
  await page.addInitScript(()=>{
    const pad={id:'Maneuver controller',index:0,mapping:'standard',connected:true,axes:[0,0,0,0],buttons:Array.from({length:17},()=>({pressed:false,value:0}))};
    (window as any).__pad=pad;Object.defineProperty(navigator,'getGamepads',{value:()=>[pad],configurable:true});
  });
  await harness.mount(page,{roadReady:{view,reducedMotion:true}},undefined,{expectCanvas:false});
  await page.getByRole('button',{name:'Controls',exact:true}).click();
  const settings=page.getByRole('region',{name:'Controls settings'});
  await settings.getByLabel('Input method',{exact:true}).selectOption('controller');
  await settings.getByRole('button',{name:'Close controls settings'}).click();
  const car=()=>page.evaluate(()=>(window as any).__testHooks.maneuverDrill.carRef.current);
  await expect.poll(async()=>!!(await car()).requireParkingNeutral).toBe(false);
  await expect(page.getByRole('button',{name:'Forward',exact:true})).toBeHidden();
  await page.evaluate(()=>{(window as any).__pad.buttons[7]={pressed:true,value:0.5};(window as any).__pad.axes[0]=0.3;});
  await expect.poll(async()=>(await car()).speed).toBeGreaterThan(1);
  await expect.poll(async()=>(await car()).steering).toBeGreaterThan(0.01);
  await page.getByRole('button',{name:'Reset practice',exact:true}).click();
  await expect(page.getByRole('status',{name:'Driving state'})).toContainText('Release');
  expect((await car()).speed).toBe(0);
  await page.evaluate(()=>{(window as any).__pad.buttons[7]={pressed:false,value:0};(window as any).__pad.axes[0]=0;});
  await expect.poll(async()=>!!(await car()).requireParkingNeutral).toBe(false);
  await page.evaluate(()=>{(window as any).__pad.buttons[7]={pressed:true,value:0.5};});
  await expect.poll(async()=>(await car()).speed).toBeGreaterThan(1);
  await page.getByRole('button',{name:'Controls',exact:true}).click();
  await expect.poll(async()=>(await car()).speed).toBe(0);
  const pose=await car();
  await page.waitForTimeout(200);
  expect(await car()).toMatchObject({x:pose.x,y:pose.y,speed:0,settingsPaused:true});
  await page.evaluate(()=>{(window as any).__pad.buttons[7]={pressed:false,value:0};});
  await settings.getByRole('button',{name:'Close controls settings'}).click();
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await expect(page.getByRole('button',{name:'Resume practice',exact:true})).toBeVisible();
  expect((await car()).speed).toBe(0);
  await page.getByRole('button',{name:'Resume practice',exact:true}).click();
  await expect(page.getByRole('button',{name:'Pause practice',exact:true})).toBeVisible();
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});

test('touch pedals release on cancellation, and paused backing cannot finish',async({page})=>{
  await page.setViewportSize({width:320,height:844});
  await harness.mount(page,{roadReady:{view:'backingDrill',reducedMotion:true}},undefined,{expectCanvas:false});
  await page.evaluate(()=>{document.getElementById('wrap')!.style.width='100%';});
  await page.getByRole('button',{name:'Controls',exact:true}).click();
  const settings=page.getByRole('region',{name:'Controls settings'});
  await settings.getByLabel('Input method',{exact:true}).selectOption('touch');
  await settings.getByRole('button',{name:'Close controls settings'}).click();
  const reverse=page.getByRole('button',{name:'Reverse',exact:true});
  await expect(reverse).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>!!(window as any).__testHooks.maneuverDrill.carRef.current.requireParkingNeutral)).toBe(false);
  await reverse.focus();await page.keyboard.down('Space');
  await expect.poll(()=>page.evaluate(()=>(window as any).__testHooks.maneuverDrill.carRef.current.speed)).toBeLessThan(-1);
  await page.keyboard.up('Space');
  const pedal=await reverse.boundingBox();
  await page.mouse.move(pedal!.x+pedal!.width/2,pedal!.y+pedal!.height/2);await page.mouse.down();
  await expect.poll(()=>page.evaluate(()=>!!(window as any).__testHooks.maneuverDrill.keysRef.current.s)).toBe(true);
  await reverse.dispatchEvent('pointercancel',{pointerId:1});
  expect(await page.evaluate(()=>!!(window as any).__testHooks.maneuverDrill.keysRef.current.s)).toBe(false);
  await page.mouse.up();
  await page.getByRole('button',{name:'Pause practice',exact:true}).click();
  await expect(page.getByRole('status',{name:'Driving state'})).toContainText('Practice paused');
  await page.evaluate(()=>Object.assign((window as any).__testHooks.maneuverDrill.carRef.current,{x:300,y:431,speed:0,heading:-Math.PI/2}));
  await page.waitForTimeout(250);
  expect(await page.evaluate(()=>(window as any).__testHooks.maneuverDrill.doneRef.current)).toBe(false);
  await expect(reverse).toBeDisabled();
  await page.getByRole('button',{name:'Resume practice',exact:true}).click();
  await expect(page.getByRole('status',{name:'Practice progress'})).toContainText('Practice complete');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await page.screenshot({path:'reports/roadready-review/maneuver-touch-controls-320.png',fullPage:true,scale:'css',animations:'disabled'});
  expect(await page.evaluate(()=>(window as any).__events.errors)).toEqual([]);
});
