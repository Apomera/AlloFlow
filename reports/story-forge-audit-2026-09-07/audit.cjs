const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const root = process.cwd();
const out = __dirname;
(async () => {
 const browser = await chromium.launch({headless:true});
 const context = await browser.newContext({viewport:{width:1280,height:900}});
 const page = await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.route('http://storyforge.audit/**',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="en"><head><title>Story Forge audit</title></head><body><div id="root"></div></body></html>'}));
 await page.goto('http://storyforge.audit/');
 await page.addStyleTag({path:path.join(root,'dev-tools/.cache/sweep-tailwind.css')});
 await page.addScriptTag({path:path.join(root,'desktop/web-app/node_modules/react/umd/react.development.js')});
 await page.addScriptTag({path:path.join(root,'desktop/web-app/node_modules/react-dom/umd/react-dom.development.js')});
 await page.addScriptTag({path:path.join(root,'story_forge_module.js')});
 const strings=JSON.parse(fs.readFileSync('ui_strings.js','utf8'));
 await page.evaluate(strings=>{
  window.auditToasts=[];
  window.auditProps={isOpen:true,onClose:()=>{},codename:'Audit Student',gradeLevel:'5',t:key=>key.split('.').reduce((v,k)=>v&&v[k],strings)||key,addToast:(...a)=>window.auditToasts.push(a)};
  window.auditRoot=ReactDOM.createRoot(document.getElementById('root'));
  window.auditRoot.render(React.createElement(window.AlloModules.StoryForge,window.auditProps));
 },strings);
 await page.locator('#sf-title').waitFor();
 await page.screenshot({animations:'disabled',path:path.join(out,'desktop-plan.png')});
 const measurements=[];
 async function capture(name){
  await page.screenshot({animations:'disabled',path:path.join(out,name+'.png')});
  measurements.push(await page.evaluate(name=>({name,viewport:{w:innerWidth,h:innerHeight},regions:[...document.querySelectorAll('[role="region"]')].map(e=>({label:e.getAttribute('aria-label'),height:Math.round(e.getBoundingClientRect().height),scrollHeight:e.scrollHeight})),buttons:[...document.querySelectorAll('button')].filter(e=>e.getBoundingClientRect().width>0).map(e=>({text:e.textContent.trim(),disabled:e.disabled})),text:document.body.innerText}),name));
 }
 await page.setViewportSize({width:390,height:844}); await capture('mobile-plan');
 await page.locator('#sf-title').fill('The Hidden Bridge');
 await page.locator('[data-sf-phase-step="write"]').click();
 await capture('mobile-draft');
 const textareas=await page.locator('textarea').evaluateAll(es=>es.map(e=>({id:e.id,label:e.getAttribute('aria-label'),placeholder:e.placeholder})));
 await page.locator('textarea[id^="sf-paragraph-text"]').first().fill('Mira discovered a hidden bridge in the forest. She helped her friend cross the river and together they returned safely home.');
 await page.locator('[data-sf-phase-step="review"]').click();await capture('mobile-review');
 await page.getByRole('button',{name:'Submit Self-Assessment',exact:true}).click();
 await page.locator('[data-sf-phase-step="illustrate"]').click();await capture('mobile-design');
 await page.locator('[data-sf-phase-step="narrate"]').click();await capture('mobile-audio');
 await page.locator('[data-sf-phase-step="export"]').click();await capture('mobile-publish');
 await page.setViewportSize({width:1280,height:900});await capture('desktop-publish');
 await page.locator('[data-sf-phase-step="write"]').click();
 await page.locator('textarea[id^="sf-paragraph-text"]').first().fill('Mira changed her mind and built a new bridge. Her friends helped carry wood and they finished together before sunset.');
 await page.locator('[data-sf-phase-step="review"]').click();
 await page.getByRole('button',{name:'Start fresh review',exact:true}).click();
 await page.getByRole('button',{name:'Skip self-assessment',exact:true}).click();
 await page.getByRole('button',{name:'Get Feedback',exact:true}).click();
 await capture('desktop-review-skipped-no-ai');
 const skipResult={designDisabled:await page.locator('[data-sf-phase-step="illustrate"]').isDisabled(),selfAssessmentAvailable:await page.getByRole('button',{name:'Submit Self-Assessment',exact:true}).count()};
 await page.locator('[data-sf-phase-step="write"]').click();
 await page.getByRole('button',{name:/Add (Scene|Paragraph)/i}).first().click();
 await page.locator('textarea[id^="sf-paragraph-text"]').nth(1).fill('This is an authored second scene that must survive regeneration.');
 await page.evaluate(()=>{window.auditProps.onCallGemini=async()=>JSON.stringify({frames:['A new opening...']});window.auditRoot.render(React.createElement(window.AlloModules.StoryForge,window.auditProps));});
 await page.getByRole('button',{name:'Generate Scene Plan',exact:true}).click();
 await page.getByRole('button',{name:'Regenerate Scene Plan',exact:true}).waitFor();
 const regenerationResult={remainingScenes:await page.locator('textarea[id^="sf-paragraph-text"]').count(),secondScenePresent:await page.locator('textarea').evaluateAll(es=>es.some(e=>e.value.includes('authored second scene')))};
 fs.writeFileSync(path.join(out,'functional-results.json'),JSON.stringify({skipResult,regenerationResult},null,2));
 fs.writeFileSync(path.join(out,'initial-results.json'),JSON.stringify({measurements,textareas,errors},null,2));
 console.log(JSON.stringify({textareas,errors}));
 await context.close();await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
