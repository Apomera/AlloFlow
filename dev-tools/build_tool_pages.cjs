#!/usr/bin/env node
'use strict';
// build_tool_pages.cjs — one indexable landing page per STEM tool on the promo site.
//
// WHY THIS EXISTS (2026-09-16)
//   All 149 STEM tools have a deep link (/water-cycle -> /app/?tool=waterCycle, generated
//   by build_stem_deep_links.cjs) and all 149 are listed in the tools.html directory. But
//   the slugs are served by CLOUDFLARE from alloflow-cdn.pages.dev, and that host emits ONE
//   <head> for every tool:
//
//       <title>AlloFlow | Adaptive UDL Platform</title>
//
//   It is a single-page app: the ?tool= query is read client-side, so all 149 URLs are the
//   same document to a crawler. Declaring them in a sitemap (the obvious fix) would publish
//   149 URLs that collapse into one page in the index — measured, not assumed.
//
//   These pages are the alternative: a real static HTML page per tool on the PAGES host
//   (apomera.github.io/AlloFlow/), each with its own title, description, structured data and
//   prose, canonical on the domain the promo site already ranks on, linking to the tool.
//
// THE HONEST LIMIT ON GENERATED CONTENT
//   tool_index.json carries label, section, desc, topics and keywords for all 149 — harvested
//   from the tool source, not written for readers. `topics` especially is raw UI text (cloud
//   names in waterCycle, image captions in zoomGallery, some carrying emoji) and is CAPPED at
//   14 entries, so it is a truncated scrape. 40 of 149 descriptions are under 80 characters.
//
//   So this generator does NOT invent teaching prose. It publishes only what is verifiable:
//   the tool's own label, section, description, its deep link, and what AlloFlow can state
//   about every tool (no account, runs in the listed environments). Anything richer — how to
//   teach with it, what students do, standards — belongs in a hand-written manual, the way
//   educator-evaluation-manual.html is hand-written, and is marked in the page as absent
//   rather than faked. `--with-manual <id>` links a tool's manual once one exists.
//
//   A thin page repeated 149 times is what search engines discount. Publishing what is true
//   for each tool, and nothing more, is the version of this that is worth publishing at all.
//
// USAGE
//   node dev-tools/build_tool_pages.cjs --list          what would be written, no writes
//   node dev-tools/build_tool_pages.cjs --only <id>...   write just these tools (review first)
//   node dev-tools/build_tool_pages.cjs                  write all 149
//   node dev-tools/build_tool_pages.cjs --check          exit 1 if any published page is stale
//
//   Output: tool-<slug>.html at the repo root (Pages serves the root), plus a generated
//   block in sitemap.xml listing the pages that exist.
//
// The promo site is GitHub Pages serving main, so pushing these publishes them immediately.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const INDEX = path.join(ROOT, 'tool_index.json');
const REDIRECTS = path.join(ROOT, '_redirects');
const SITEMAP = path.join(ROOT, 'sitemap.xml');
const PAGES_BASE = 'https://apomera.github.io/AlloFlow/';
const APP_ORIGIN = 'https://alloflow-cdn.pages.dev';

const argv = process.argv.slice(2);
const CHECK = argv.includes('--check');
const LIST = argv.includes('--list');
const onlyAt = argv.indexOf('--only');
const ONLY = onlyAt >= 0 ? argv.slice(onlyAt + 1).filter((a) => !a.startsWith('--')) : null;

const SITEMAP_BEGIN = '  <!-- __ALLO_TOOL_PAGES_BEGIN__ (generated by dev-tools/build_tool_pages.cjs) -->';
const SITEMAP_END = '  <!-- __ALLO_TOOL_PAGES_END__ -->';

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
// For values that land inside a JSON-LD string literal.
function jsonStr(s) {
  return JSON.stringify(String(s == null ? '' : s));
}

// ── inputs (both generated; this script invents nothing) ─────────────────────
const tools = JSON.parse(fs.readFileSync(INDEX, 'utf8')).tools || [];
const slugById = new Map();
for (const line of fs.readFileSync(REDIRECTS, 'utf8').split(/\r?\n/)) {
  const m = /^\/([a-z0-9-]+)\s+\/app\/\?tool=([A-Za-z0-9]+)\s+302$/.exec(line.trim());
  if (m) slugById.set(m[2], m[1]);
}
if (!tools.length || !slugById.size) throw new Error('Refusing to run with an empty registry');

// A tool gets a page only if it has a real deep link and a description worth indexing.
// A page whose only content is a label is the thin page this exists to avoid.
const MIN_DESC = 60;
const eligible = [];
const skipped = { noSlug: [], thinDesc: [] };
for (const tool of tools) {
  const slug = slugById.get(tool.id);
  if (!slug) { skipped.noSlug.push(tool.id); continue; }
  const desc = (tool.desc || '').trim();
  if (desc.length < MIN_DESC) { skipped.thinDesc.push(tool.id + ' (' + desc.length + ' chars)'); continue; }
  eligible.push({ id: tool.id, slug, label: tool.label || tool.id, section: (tool.section || '').trim(), desc });
}

const selected = ONLY ? eligible.filter((t) => ONLY.includes(t.id)) : eligible;
if (ONLY) {
  const missing = ONLY.filter((id) => !eligible.some((t) => t.id === id));
  if (missing.length) {
    console.error('Not eligible for a page (no slug, or description under ' + MIN_DESC + ' chars): ' + missing.join(', '));
    process.exit(1);
  }
}

// ── page ─────────────────────────────────────────────────────────────────────
function render(tool) {
  const pageUrl = PAGES_BASE + 'tool-' + tool.slug + '.html';
  const appUrl = APP_ORIGIN + '/' + tool.slug;
  const title = tool.label + ' — AlloFlow';
  const inSection = tool.section ? ' It sits in the ' + tool.section + ' area of the STEM Lab.' : '';
  const dirAnchor = tool.section
    ? PAGES_BASE + 'tools.html#dir-' + tool.section.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
    : PAGES_BASE + 'tools.html#directory-heading';

  const manualFile = 'manual-' + tool.slug + '.html';
  const hasManual = fs.existsSync(path.join(ROOT, manualFile));

  const ld = {
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    name: tool.label,
    applicationCategory: 'EducationalApplication',
    description: tool.desc,
    url: pageUrl,
    isPartOf: { '@type': 'WebApplication', name: 'AlloFlow', url: PAGES_BASE },
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
    isAccessibleForFree: true,
  };

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(tool.desc)}">
<meta name="robots" content="index, follow">
<link rel="canonical" href="${esc(pageUrl)}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="AlloFlow">
<meta property="og:title" content="${esc(tool.label)}">
<meta property="og:description" content="${esc(tool.desc)}">
<meta property="og:url" content="${esc(pageUrl)}">
<meta name="twitter:card" content="summary">
<meta name="twitter:title" content="${esc(tool.label)}">
<meta name="twitter:description" content="${esc(tool.desc)}">
<link rel="stylesheet" href="shared.css">
<link rel="stylesheet" href="tool-page.css">
<script type="application/ld+json">${JSON.stringify(ld, null, 1)}</script>
</head>
<body>
<a class="skip-link" href="#tool-main">Skip to content</a>
<nav class="navbar" aria-label="Primary">
    <div class="navbar-inner">
        <a class="nav-logo" href="./">AlloFlow</a>
        <div class="nav-links" data-site-nav="primary">
            <a href="tools.html">Find a Tool</a>
            <a href="features.html">Features</a>
            <a href="manuals.html">Manuals</a>
        </div>
    </div>
</nav>
<main id="tool-main" class="tool-page">
    <nav class="tool-page-crumbs" aria-label="Breadcrumb">
        <ol>
            <li><a href="./">AlloFlow</a></li>
            <li><a href="tools.html">Find a Tool</a></li>
            ${tool.section ? '<li><a href="' + esc(dirAnchor) + '">' + esc(tool.section) + '</a></li>' : ''}
            <li aria-current="page">${esc(tool.label)}</li>
        </ol>
    </nav>

    <header class="tool-page-hero">
        ${tool.section ? '<p class="tool-page-eyebrow">' + esc(tool.section) + '</p>' : ''}
        <h1>${esc(tool.label)}</h1>
        <p class="tool-page-lede">${esc(tool.desc)}</p>
        <p class="tool-page-actions">
            <a class="btn-primary tool-page-open" href="${esc(appUrl)}">Open ${esc(tool.label)}</a>
            <span class="tool-page-note">Opens the tool directly — no account, no signup, nothing to install.</span>
        </p>
    </header>

    <section class="tool-page-block" aria-labelledby="share-heading">
        <h2 id="share-heading">Share this tool with a class or a colleague</h2>
        <p>This link opens ${esc(tool.label)} on its own. Paste it into an assignment, a sub plan,
            a slide, or a message and it opens on the tool the student needs.</p>
        <p class="tool-page-url"><code>${esc(appUrl)}</code></p>
    </section>

    <section class="tool-page-block" aria-labelledby="where-heading">
        <h2 id="where-heading">Where this fits</h2>
        <p>${esc(tool.label)} is one of the tools in the AlloFlow STEM Lab.${esc(inSection)}
            AlloFlow is free and open source, and it runs in a browser.</p>
        <p><a href="${esc(dirAnchor)}">See every STEM tool with a shareable link</a>, or
            <a href="tools.html">search the tool finder</a> by topic or classroom goal.</p>
    </section>

    <section class="tool-page-block" aria-labelledby="manual-heading">
        <h2 id="manual-heading">${hasManual ? 'Teacher manual' : 'Is there a manual for this tool?'}</h2>
${hasManual
  ? '        <p>Yes. The <a href="' + esc(manualFile) + '">' + esc(tool.label) + ' teacher manual</a> covers a first lesson, a tour of the controls, classroom walkthroughs, what the tool deliberately does not do, and accessibility notes.</p>\n        <p class="tool-page-actions"><a class="btn-secondary tool-page-manual" href="' + esc(manualFile) + '">Read the ' + esc(tool.label) + ' manual</a></p>'
  : '        <p>Not yet. AlloFlow has written manuals for a few tools so far — <a href="manuals.html">see the manuals and guides page</a> — and this one is not among them. The tool itself carries its instructions on screen.</p>'}
    </section>
</main>
<footer class="tool-page-footer">
    <p><a href="tools.html">Find a Tool</a> · <a href="manuals.html">Manuals</a> ·
        <a href="./">AlloFlow home</a></p>
</footer>
</body>
</html>
`;
}

// ── write / check ────────────────────────────────────────────────────────────
if (LIST) {
  console.log('Eligible for a page: ' + eligible.length + ' of ' + tools.length + ' tools');
  if (skipped.noSlug.length) console.log('  no deep-link slug: ' + skipped.noSlug.length + ' -> ' + skipped.noSlug.join(', '));
  if (skipped.thinDesc.length) {
    console.log('  description under ' + MIN_DESC + ' chars (no page; would be a thin page): ' + skipped.thinDesc.length);
    for (const s of skipped.thinDesc) console.log('      ' + s);
  }
  console.log('\nWould write ' + selected.length + ' page(s):');
  for (const t of selected.slice(0, 12)) console.log('  tool-' + t.slug + '.html   ' + t.label);
  if (selected.length > 12) console.log('  … and ' + (selected.length - 12) + ' more');
  process.exit(0);
}

let written = 0, stale = [];
for (const tool of selected) {
  const file = path.join(ROOT, 'tool-' + tool.slug + '.html');
  const next = render(tool);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (prev === next) continue;
  if (CHECK) { stale.push('tool-' + tool.slug + '.html'); continue; }
  fs.writeFileSync(file, next, 'utf8');
  written++;
}

// sitemap block: only the pages that actually exist on disk
const existing = eligible
  .filter((t) => fs.existsSync(path.join(ROOT, 'tool-' + t.slug + '.html')))
  .map((t) => PAGES_BASE + 'tool-' + t.slug + '.html');
const today = new Date().toISOString().slice(0, 10);
const block = [SITEMAP_BEGIN]
  .concat(existing.map((u) => '  <url>\n    <loc>' + u + '</loc>\n    <lastmod>' + today + '</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.6</priority>\n  </url>'))
  .concat([SITEMAP_END]).join('\n');
const smBefore = fs.readFileSync(SITEMAP, 'utf8');
const eol = smBefore.includes('\r\n') ? '\r\n' : '\n';
const smBody = smBefore.replace(/\r\n/g, '\n');
let smNext;
const b = smBody.indexOf(SITEMAP_BEGIN);
const e = smBody.indexOf(SITEMAP_END);
if (b >= 0 && e > b) {
  smNext = smBody.slice(0, b) + block + smBody.slice(e + SITEMAP_END.length);
} else {
  const at = smBody.lastIndexOf('</urlset>');
  if (at < 0) throw new Error('sitemap.xml has no </urlset>');
  smNext = smBody.slice(0, at) + block + '\n' + smBody.slice(at);
}
// A sitemap lastmod changes every run; only treat CONTENT changes as stale.
const stripDates = (s) => s.replace(/<lastmod>[^<]*<\/lastmod>/g, '');
const smChanged = stripDates(smNext) !== stripDates(smBody);

console.log('Tool pages: ' + eligible.length + ' eligible, ' + existing.length + ' published, ' + selected.length + ' in this run.');
if (skipped.thinDesc.length) console.log('  skipped (description under ' + MIN_DESC + ' chars): ' + skipped.thinDesc.length);

if (CHECK) {
  if (stale.length || smChanged) {
    console.error('\nbuild_tool_pages: FAIL — stale output.');
    if (stale.length) console.error('  pages: ' + stale.slice(0, 8).join(', ') + (stale.length > 8 ? ' …(' + stale.length + ')' : ''));
    if (smChanged) console.error('  sitemap.xml tool-page block is stale');
    console.error('Run `node dev-tools/build_tool_pages.cjs` to regenerate.');
    process.exit(1);
  }
  console.log('\nbuild_tool_pages: OK — every published page matches the registry.');
  process.exit(0);
}
if (smChanged || b < 0) {
  fs.writeFileSync(SITEMAP, eol === '\r\n' ? smNext.replace(/\n/g, '\r\n') : smNext, 'utf8');
  console.log('  sitemap.xml: listed ' + existing.length + ' tool page(s)');
}
console.log(written ? '\nWrote ' + written + ' page(s).' : '\nAlready current; no page written.');
