#!/usr/bin/env node
/**
 * Build walkthrough_script_source_module.js from the Apps Script source.
 *
 * Mirrors mailbox_script_source_module.js: the script text ships inside the
 * app, frozen, with a version and a sha256, so the "copy script code" button
 * works offline and inside Gemini Canvas where no fetch to GitHub is possible.
 *
 * The digest is what makes the shipped copy checkable: if the module and
 * apps_script/walkthrough_records/Code.gs ever drift, the test that recomputes
 * this hash fails rather than a principal silently pasting stale code.
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'apps_script', 'walkthrough_records', 'Code.gs');
const README = path.join(ROOT, 'apps_script', 'walkthrough_records', 'README.md');
const OUTPUT = path.join(ROOT, 'walkthrough_script_source_module.js');
const DEPLOY_OUT = path.join(ROOT, 'desktop/web-app', 'public', 'walkthrough_script_source_module.js');

if (!fs.existsSync(SOURCE)) { console.error('Not found:', SOURCE); process.exit(1); }

const script = fs.readFileSync(SOURCE, 'utf-8');
const sha256 = crypto.createHash('sha256').update(script, 'utf8').digest('hex');
const versionMatch = /var WR_VERSION = (\d+);/.exec(script);
const version = versionMatch ? Number(versionMatch[1]) : 1;

// Steps are data, not prose baked into a component, so the standalone page and
// the React panel render the same instructions from one source.
const STEPS = [
  { n: 1, text: 'Type script.new into your browser address bar, signed into the Google account that should own these records. A school account is the right choice.' },
  { n: 2, text: 'Delete the starter code and paste the script copied below.' },
  { n: 3, text: 'Rename the project to AlloFlow Walkthrough Records and save.' },
  { n: 4, text: 'Click Deploy, then New deployment, and choose type Web app.' },
  { n: 5, text: 'Set Execute as: Me and Who has access: Anyone. Click Deploy.' },
  { n: 6, text: 'Authorize when prompted. Google warns that it has not verified the app, because a script you just wrote is an unpublished OAuth app. Continue only if you created this project, read the code, and recognize the account.' },
  { n: 7, text: 'Copy the Web app URL, which ends in /exec, and paste it below.' }
];

const escaped = JSON.stringify(script);
const stepsJson = JSON.stringify(STEPS, null, 2).replace(/\n/g, '\n  ');

const outputCode = `/**
 * AlloFlow Walkthrough Records - Apps Script source, shipped inside the app.
 *
 * Auto-generated by _build_walkthrough_script_source.js - DO NOT EDIT MANUALLY.
 * Source: apps_script/walkthrough_records/Code.gs
 *
 * Ships the principal-owned delivery script so the copy button works offline
 * and inside Gemini Canvas. Frozen, with a digest so drift from the repository
 * copy is detectable rather than silent.
 */
(function() {
  'use strict';
  window.AlloModules = window.AlloModules || {};
  var previous = window.AlloModules.WalkthroughScriptSource;
  if (previous && previous.version === ${version} && previous.sha256 === ${JSON.stringify(sha256)}) {
    console.log('[CDN] WalkthroughScriptSource already loaded, skipping');
    return;
  }
  window.AlloModules.WalkthroughScriptSource = Object.freeze({
    service: 'alloflow-walkthrough-records',
    version: ${version},
    sha256: ${JSON.stringify(sha256)},
    filename: 'Code.gs',
    projectName: 'AlloFlow Walkthrough Records',
    newProjectUrl: 'https://script.new',
    steps: Object.freeze(${stepsJson}),
    execUrlPattern: '^https://script\\\\.google\\\\.com/macros/s/[A-Za-z0-9_-]+/exec$',
    source: ${escaped}
  });
  console.log('[CDN] WalkthroughScriptSource loaded');
})();
`;

fs.writeFileSync(OUTPUT, outputCode, 'utf-8');
try {
  if (!fs.existsSync(path.dirname(DEPLOY_OUT))) fs.mkdirSync(path.dirname(DEPLOY_OUT), { recursive: true });
  fs.writeFileSync(DEPLOY_OUT, outputCode, 'utf-8');
  console.log('Synced to ' + DEPLOY_OUT);
} catch (e) {
  console.warn('[WalkthroughScriptSource] Could not sync to desktop/web-app/public/:', e.message);
}
console.log('Built ' + OUTPUT + ' (v' + version + ', sha256 ' + sha256.slice(0, 12) + ', ' + script.length + ' source chars)');
if (!fs.existsSync(README)) console.warn('[WalkthroughScriptSource] README missing; setup docs should ship with the script.');
